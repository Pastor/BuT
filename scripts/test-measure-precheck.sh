#!/bin/sh
# Тест обвязки замера.
#
# Обвязка сама по себе - инструмент, а не проверка: она нужна фиче, которая
# собирается записать число в карточку. Проверяется поэтому её логика вердикта,
# и проверяется быстрыми командами (`sleep`), а не настоящим предкоммитом.
#
# Что доказывается:
# 1. стабильные прогоны -> "замер годен", код 0;
# 2. разброс сверх порога -> "замер негоден", код != 0;
# 3. красный прогон замером не считается - обвязка отказывает сразу;
#   4. прогрев выполняется и его время не идёт в вердикт.
#
# POSIX sh.
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TOOL="$ROOT/scripts/measure-precheck.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

FAILED=0
ok()   { echo "  OK: $1"; }
fail() { echo "  ПРОВАЛ: $1" >&2; FAILED=1; }

echo "Сторож обвязки замера (фича 0272)..."

# --- 1. Стабильные прогоны принимаются ---------------------------------------
# Порог ослаблен намеренно: обвязка меряет время целыми
# секундами (`date +%s`), поэтому на секундной команде прогоны "1 с" и "2 с"
# отличаются на 100 % от одного лишь округления - под нагрузкой тест падал,
# не находя дефекта. Здесь проверяется, что годный замер принимается; что
# разброс ловится - условие 2, и там разница трёхкратная, гранулярностью не
# объяснимая.
if MEASURE_CMD='sleep 1' MEASURE_WARMUP=0 MEASURE_SPREAD=200 sh "$TOOL" >"$TMP/out" 2>&1 \
   && grep -q 'ЗАМЕР ГОДЕН' "$TMP/out"; then
    ok "стабильные прогоны дают годный замер"
else
    fail "стабильные прогоны отвергнуты: $(cat "$TMP/out")"
fi

# --- 2. Разброс сверх порога ловится -----------------------------------------
# Команда, которая с каждым вызовом идёт дольше: первый прогон - 1 с, второй - 6.
#
# Контраст увеличен: при паре "1 с / 3 с" тест падал под
# нагрузкой - обвязка меряет целыми секундами (`date +%s`), и растянувшийся
# первый прогон округлялся до тех же 3 с, давая разброс 0 %. Тот же класс, что
# у исправления, но в соседнем условии: ловушка обязана переживать
# замедление, иначе она ловит не дефект, а загрузку машины.
COUNTER="$TMP/counter"
: > "$COUNTER"
cat > "$TMP/uneven.sh" <<EOF
#!/bin/sh
n=\$(wc -c < "$COUNTER" | tr -d ' ')
printf 'x' >> "$COUNTER"
[ "\$n" -eq 0 ] && sleep 1 || sleep 6
EOF
chmod +x "$TMP/uneven.sh"
if ! MEASURE_CMD="$TMP/uneven.sh" MEASURE_WARMUP=0 sh "$TOOL" >"$TMP/out" 2>&1 \
   && grep -q 'ЗАМЕР НЕГОДЕН' "$TMP/out"; then
    ok "разброс сверх порога ловится"
else
    fail "разброс НЕ пойман: $(cat "$TMP/out")"
fi

# --- 3. Красный прогон замером не считается ----------------------------------
if ! MEASURE_CMD='false' MEASURE_WARMUP=0 sh "$TOOL" >"$TMP/out" 2>&1 \
   && grep -q 'завершилась неуспешно' "$TMP/out"; then
    ok "красный прогон отвергается сразу"
else
    fail "красный прогон принят за замер: $(cat "$TMP/out")"
fi

# --- 4. Прогрев выполняется и в вердикт не идёт ------------------------------
# Команда считает вызовы; при включённом прогреве их три, а вердикт опирается
# на два последних. Без этой проверки "прогрев есть" держалось бы на слове.
CALLS="$TMP/calls"
: > "$CALLS"
cat > "$TMP/counted.sh" <<EOF
#!/bin/sh
printf 'x' >> "$CALLS"
sleep 1
EOF
chmod +x "$TMP/counted.sh"
# Порог ослаблен по той же причине, что в условии 1:
# секундная команда меряется целыми секундами, и "1 с против 2 с" - это 100 %
# разброса от одного округления. Здесь проверяется число вызовов, а не вердикт.
if MEASURE_CMD="$TMP/counted.sh" MEASURE_SPREAD=200 sh "$TOOL" >"$TMP/out" 2>&1; then
    calls="$(wc -c < "$CALLS" | tr -d ' ')"
    if [ "$calls" -eq 3 ] && grep -q 'прогрев:' "$TMP/out"; then
        ok "прогрев выполняется и не идёт в вердикт (вызовов: $calls)"
    else
        fail "прогрев не выполнен либо учтён: вызовов $calls"
    fi
else
    fail "прогон с прогревом провалился: $(cat "$TMP/out")"
fi

[ "$FAILED" -eq 0 ] || { echo "  Сторож обвязки замера: ПРОВАЛ" >&2; exit 1; }
echo "  Сторож обвязки замера: все проверки пройдены"
