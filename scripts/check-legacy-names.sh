#!/bin/sh
# Проверка старых имён языка и инструментов.
#
# Правило: в рабочих файлах дерева не встречаются имена, упразднённые
# переименованиями `BuT` -> `Lam` -> `Takt`: сам язык (`BuT`, `Lam`),
# инструменты (`butc`, `lamc`, `lam-lsp`), расширения исходников (`.but`, `.lam`)
# и пути упразднённых крейтов (`grammar/...`, `simulation/...`, `-p simulation`).
#
# Повод - не косметика. Замер 2026-08-18 нашёл 36 таких мест, и одно из них было
# дефектом документации: `examples/graphics-configs/README.md` предлагал команду
# `cargo run -p simulation --bin simulation -- model.but --gif-config
# examples/gif-configs/dark.json`, у которой неверны все четыре элемента - крейт,
# бинарник, расширение и путь к пресету. Остальные 35 были комментариями, но
# отличить одно от другого можно только прочитав каждое: без проверки старое имя
# возвращается первым же скопированным комментарием.
#
# Имена В порождаемом коде Проверка проверяет тоже. До неё этот
# класс был исключён: хелперы исправлениеированной точки звались `lam_q_*` (цель `c`)
# и `LAM_Q_*` (цель `st`), то есть имя упразднённого языка уезжало в прошивку
# пользователя. переименовала их в `takt_q_*`/`TAKT_Q_*` и сняла
# исключение - шаблон ниже ловит старый преисправление в любом регистре, включая
# снапшоты `examples/generated/`. Тест этой ветви - мутация в
# `scripts/test-legacy-names.sh` (проверка 5): пока класс был исключён,
# новый хелпер заводился по образцу соседа - вместе со старым преисправлением.
#
# Служебные идентификаторы Проверка проверяет тоже. До неё класс был
# исключён - "это видит только разработчик инструмента", - и держал 114
# вхождений: `LAMC`/`lam_file` в скриптах, преисправление `lam_` у временных каталогов
# сорока с лишним тестов, `BUT_KEYWORDS`/`BUT_BUILTIN_TYPES` в LSP, крейт
# порождённых примеров `lam_generated`, ключи цветов `LAM_*` плагина IntelliJ.
# Исключение и было причиной живучести: новый временный каталог заводили по
# образцу соседнего теста - вместе со старым преисправлением.
#
# Исключения заданы ПРЕИсправлениями путей, а не пофайловым списком. В `docs/` и
# журналах старое имя - Свидетельство, а не ошибка, и цитировать
# его там будут всегда. Преисправление не устаревает, поэтому ратчет исключений (как у
# `scripts/module-size-baseline.txt`) здесь не нужен: устареть нечему.
#
# Использование:
# scripts/check-legacy-names.sh # весь индекс git (шаг precheck.sh)
# scripts/check-legacy-names.sh файл ... # только указанные (тест 0161)
#
# POSIX sh, без внешних зависимостей (образец - scripts/check-repo-url.sh).
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"

# --- Что запрещено ----------------------------------------------------------
# ERE. Границы слова записаны классами POSIX `[[:<:]]`/`[[:>:]]`? Нет: они есть у
# BSD grep и отсутствуют у GNU. Переносимо и достаточно - обрамление символами,
# не входящими в идентификатор, через отрицаемые классы.
LEGACY='(^|[^A-Za-z0-9_])(BuT|Lam|butc|lamc|lam-lsp|lam-sim)($|[^A-Za-z0-9_-])|\.(but|lam)($|[^A-Za-z0-9_])|(^|[^A-Za-z0-9_/])(grammar|simulation)/(src|tests)/|-p +(grammar|simulation)( |$)|(^|[^A-Za-z0-9_])[Ll][Aa][Mm]_[A-Za-z0-9_]|(^|[^A-Za-z0-9_])LAMC($|[^A-Za-z0-9_])|(^|[^A-Za-z0-9_])BUT_[A-Za-z0-9_]|(^|[^A-Za-z0-9_-])lam-generated($|[^A-Za-z0-9_])'

# --- Где не проверяем -------------------------------------------------------
# docs/, CHANGES.md - история и всех, кто её цитирует.
# CLAUDE.md, AGENTS.md - ссылка на карточку `0081-lamc-print-warnings.md`.
# FEATURES.md - адрес репозитория `github.com/Pastor/BuT` (действующий).
# .claude/ - артефакты сессий инструмента, не исходники проекта.
# Два проверки ниже описывают сам переезд и обязаны называть старое имя.
is_excluded() {
    case "$1" in
        docs/*|CHANGES.md|CLAUDE.md|AGENTS.md|FEATURES.md|.claude/*) return 0 ;;
        scripts/check-repo-url.sh|scripts/check-legacy-names.sh) return 0 ;;
        scripts/test-legacy-names.sh) return 0 ;;
        # `precheck.sh` исключён частично: он описывает переезд хелперов
        # и обязан называть прежний преисправление. Исключение сузилось до
        # этого повода - прежде оно покрывало весь файл и прятало 16 живых
        # `LAMC`.
        scripts/precheck.sh) return 1 ;;
        *) return 1 ;;
    esac
}

echo "Гейт старых имён (BuT/Lam → Takt, фича 0161)..."

if [ $# -gt 0 ]; then
    FILES="$*"
else
    FILES="$(cd "$ROOT" && git ls-files)"
fi

BAD=0
COUNT=0
for REL in $FILES; do
    is_excluded "$REL" && continue
    F="$ROOT/$REL"
    [ -f "$F" ] || F="$REL"
    [ -f "$F" ] || continue
    COUNT=$((COUNT + 1))
    # -I: двоичные файлы пропускаются (шрифты, снимки).
    HITS="$(grep -nIE "$LEGACY" "$F" 2>/dev/null || true)"
    [ -z "$HITS" ] && continue
    # Падаем списком: одно место за прогон означало бы столько прогонов, сколько
    # мест, - а их бывает 36.
    echo "$HITS" | while IFS= read -r LINE; do
        echo "  ОШИБКА: $REL:$LINE" >&2
    done
    BAD=1
done

if [ "$BAD" -ne 0 ]; then
    echo "  Старое имя языка/инструмента в рабочем файле (ADR 0161)." >&2
    echo "  Замены: BuT|Lam → Takt, butc|lamc → taktc, lam-lsp → takt-lsp," >&2
    echo "          .but|.lam → .takt, grammar/ → takt-lang/, simulation/ → takt-sim/," >&2
    echo "          lam_q_*|LAM_Q_* → takt_q_*|TAKT_Q_* (хелперы целей c и st)," >&2
    echo "          lam_*|LAM_*|LAMC|BUT_* → takt_*|TAKT_*|TAKTC (служебные имена)." >&2
    echo "  Историю цитировать в docs/ — там гейт не смотрит." >&2
    exit 1
fi

echo "  OK: старых имён нет (проверено файлов: $COUNT)"
