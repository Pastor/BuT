#!/bin/sh
# Проверка трейлеров коммита.
#
# Правило: сведения о со-авторстве
# (`Co-Authored-By:`) в сообщения коммитов не попадают. Авторство коммита
# выражает поле `Author`, а номер фичи - трейлер `Feature:`; третья
# запись об авторстве ни того, ни другого не уточняет.
#
# Проверка проверяет историю ветки, а не только последний коммит: правило имеет
# смысл лишь как свойство всей истории, и разовая чистка без теста отрастает
# обратно первым же коммитом, сделанным инструментом с настройкой по умолчанию.
#
# Область: коммиты, достижимые из HEAD. Ветки и теги проверяются тем, что
# достижимы из своих вершин - отдельного обхода им не нужно.
#
# Переменная CT_REV переопределяет ревизию (для теста scripts/test-commit-trailers.sh).
#
# POSIX sh, без внешних зависимостей.
set -eu

. "$(dirname "$0")/gatelib.sh"

REV="${CT_REV:-HEAD}"
FORBIDDEN='^[[:space:]]*[Cc]o-[Aa]uthored-[Bb]y:'

echo "Гейт трейлеров коммита: без Co-Authored-By (правило 31)..."

if ! git rev-parse --git-dir >/dev/null 2>&1; then
    echo "  ПРОПУСК: каталог не является git-репозиторием."
    exit 0
fi

# Список коммитов-нарушителей. Падаем списком: одно имя за прогон означало бы
# столько прогонов, сколько коммитов, - а их бывают сотни.
BAD="$(git log "$REV" --format='%H %s' --grep="$FORBIDDEN" --extended-regexp 2>/dev/null || true)"

if [ -z "$BAD" ]; then
    TOTAL="$(git rev-list --count "$REV" 2>/dev/null || echo '?')"
    NOTE="$(require_input "коммиты ветки" "$TOTAL" 1 "$REV")" || exit 1
  echo "  OK: трейлера нет ни в одном коммите; $NOTE"
    exit 0
fi

COUNT="$(printf '%s\n' "$BAD" | wc -l | tr -d ' ')"
echo "  ОШИБКА: сведения о со-авторстве найдены в $COUNT коммитах (правило 31):" >&2
printf '%s\n' "$BAD" | head -n 20 | while IFS= read -r line; do
    echo "    ${line}" >&2
done
[ "$COUNT" -gt 20 ] && echo "    … и ещё $((COUNT - 20))" >&2
echo "  Уберите трейлер из сообщений. Историю чистят переписыванием:" >&2
echo "    git filter-repo --message-callback … (или git filter-branch --msg-filter)" >&2
echo "  ⚠️ Переписывание меняет ВСЕ хеши: перенесите теги и согласуйте push." >&2
exit 1
