#!/bin/sh
# Проверка реестра кодов диагностик - единый источник истины.
#
# Правило: каждый код диагностики (`SE-036`, `CC-014`, `SIM-010`, ...)
# живёт в реестре docs/diagnostics/README.md ровно один раз. Без проверки коды
# выдавались голыми литералами `Diagnostic::with_code("...")` и грепом "последнего
# занятого" - так две фичи независимо взяли `CC-014` (коллизия), а документация
# отставала (AM/PU не описаны, ST частично). Реестр без проверки повторил бы судьбу
# README: правило, которое нельзя
# проверить командой, - не правило.
#
# Четыре условия отказа:
# 1. Незадокументированный код - код эмитируется исходником, но его нет в
# реестре. Именно это и есть "коллизия по недосмотру".
# 2. Протухшая запись - код в реестре, но исходник его не эмитирует и он не
#      помечен RESERVED/RETIRED.
# 3. Нарушение формата - код не вида `XX-NNN` (2-4 буквы, дефис, 3 цифры).
# 4. Дубль строки - один код перечислен в реестре дважды.
# 5. Код, вплавленный В текст - исходник печатает `[XX-NNN]` внутри строки
# сообщения, но отдельного литерала `"XX-NNN"` у него нет. Для условий 1-2
#      такой код не существует: проверка зелен, реестр пуст, а пользователь код в
# выводе видит. Так прожили коды `SIM-030`...`SIM-032`.
# Плюс справка: по каждому префиксу печатается максимальный занятый номер
# ("следующий свободный" = +1) - чтобы греп-и-угадай стал не нужен.
#
# POSIX sh, без внешних зависимостей (образец - scripts/check-module-size.sh).
set -eu

# Переменная окружения DC_ROOT переопределяет корень репозитория (по умолчанию -
# каталог скрипта/..). Нужна для тестируемости: scripts/test-diagnostic-codes.sh
# гоняет проверка в temp-дереве, не трогая рабочий реестр (образец - NF_ROOT у
# scripts/new-feature.sh).
. "$(dirname "$0")/gatelib.sh"

ROOT="${DC_ROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
REGISTRY="$ROOT/docs/diagnostics/README.md"
# ERE - используется всюду через `grep -E`.
CODE_RE='[A-Z][A-Z0-9]{1,3}-[0-9]{3}'

if [ ! -f "$REGISTRY" ]; then
    echo "check-diagnostic-codes: не найден реестр $REGISTRY" >&2
    exit 1
fi

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# EMITTED: коды, реально выдаваемые исходником. Берём строковые литералы вида
# "XX-NNN" из крейтов (both `.with_code("...")` и армы диспетчеров `code()` - это
# тоже строковые литералы). Тесты (`takt-lang/tests`, `takt-sim/tests`) сюда не
# входят: их `assert_eq!(..., "SIM-010")` - сверка того же кода, не новый источник.
grep -rhoE "\"$CODE_RE\"" "$ROOT/takt-lang/src" "$ROOT/takt-sim/src" \
    | tr -d '"' | sort -u > "$TMP/emitted"

# REGISTERED: коды из строк-записей реестра - только строки таблицы вида
# `| `XX-NNN` | ... |`. Секция префиксов (`| `LE` |`) под шаблон не подходит (нет
# `-NNN`), поэтому не мешает.
grep -oE "^\| \`$CODE_RE\`" "$REGISTRY" 2>/dev/null \
    | sed -E 's/^\| `//; s/`$//' | sort > "$TMP/registered_raw"
sort -u "$TMP/registered_raw" > "$TMP/registered"

# RESERVED/RETIRED: коды, помеченные как забронированные/выведенные - им эмиссия
# в исходнике не требуется.
grep -oE "^\| \`$CODE_RE\`.*(RESERVED|RETIRED)" "$REGISTRY" 2>/dev/null \
    | sed -E 's/^\| `//; s/`.*$//' | sort -u > "$TMP/reserved" || true

fail=0

# Условие 4: дубль строки в реестре.
DUPES="$(uniq -d "$TMP/registered_raw" || true)"
if [ -n "$DUPES" ]; then
    echo "ОТКАЗ (0077): код перечислен в реестре дважды:" >&2
    echo "$DUPES" | sed 's/^/  /' >&2
    fail=1
fi

# Условие 3: формат. Реестр по построению матчится шаблоном; дополнительно
# проверяем, что среди эмитируемых нет чего-то за пределами формата - на случай
# литерала вроде "SE-4" или "SEE-NNNN". Ищутся "код-подобные" литералы шире.
BADFMT="$(grep -rho '"[A-Z][A-Z0-9]*-[0-9]*"' "$ROOT/takt-lang/src" "$ROOT/takt-sim/src" \
    | tr -d '"' | sort -u | grep -vxE "[A-Z]{2,4}-[0-9]{3}" || true)"
if [ -n "$BADFMT" ]; then
    echo "ОТКАЗ (0077): код-подобный литерал нарушает формат XX-NNN:" >&2
    echo "$BADFMT" | sed 's/^/  /' >&2
    fail=1
fi

# Условие 1: эмитируется, но не в реестре.
UNDOC="$(comm -23 "$TMP/emitted" "$TMP/registered" || true)"
if [ -n "$UNDOC" ]; then
    echo "ОТКАЗ (0077): код эмитируется исходником, но отсутствует в реестре" >&2
    echo "               $REGISTRY — добавьте строку с описанием:" >&2
    echo "$UNDOC" | sed 's/^/  /' >&2
    fail=1
fi

# Условие 2: в реестре, но не эмитируется и не RESERVED/RETIRED.
STALE="$(comm -13 "$TMP/emitted" "$TMP/registered" | comm -23 - "$TMP/reserved" || true)"
if [ -n "$STALE" ]; then
    echo "ОТКАЗ (0077): код в реестре, но исходник его не эмитирует" >&2
    echo "               (выведен? пометьте RESERVED/RETIRED; переименован? поправьте):" >&2
    echo "$STALE" | sed 's/^/  /' >&2
    fail=1
fi

# Условие 5: код вплавлен в текст сообщения. Ищем скобочную форму `[XX-NNN]`
# - именно так код попадает в вывод пользователя - и требуем, чтобы у него был
# отдельный литерал. Без литерала код невидим условиям 1-2, то есть выпадает из
# реестра зелёным прогоном.
#
# Ложных срабатываний на комментариях и `assert!` внутри `src` не бывает по
# построению: они называют коды, у которых литерал есть (`SE-001`,
# `SE-002`, `SE-003`). Форма без скобок (``3``````` в прозе) под шаблон не
# подходит вовсе.
INLINE="$(grep -rhoE "\[$CODE_RE\]" "$ROOT/takt-lang/src" "$ROOT/takt-sim/src" \
    | tr -d '[]' | sort -u || true)"
if [ -n "$INLINE" ]; then
    HIDDEN="$(printf '%s\n' "$INLINE" | comm -23 - "$TMP/emitted" || true)"
    if [ -n "$HIDDEN" ]; then
        echo "ОТКАЗ (0255): код напечатан внутри текста сообщения и не имеет" >&2
        echo "               отдельного литерала \"XX-NNN\" — для гейта он" >&2
        echo "               НЕ СУЩЕСТВУЕТ и в реестр не попадёт:" >&2
        for CODE in $HIDDEN; do
            echo "  $CODE" >&2
            grep -rnE "\[$CODE\]" "$ROOT/takt-lang/src" "$ROOT/takt-sim/src" \
                | sed "s|^$ROOT/|    |" >&2 || true
        done
        echo "               Заведите код константой рядом с местом печати:" >&2
        echo '                 const CODE: &str = "XX-NNN";' >&2
        echo '                 eprintln!("Ошибка [{CODE}]: …");' >&2
        fail=1
    fi
fi

if [ "$fail" -ne 0 ]; then
    exit 1
fi

N="$(wc -l < "$TMP/registered" | tr -d ' ')"
NOTE="$(require_input "коды реестра диагностик" "$N" 1 "docs/diagnostics/README.md")" || exit 1
echo "check-diagnostic-codes: реестр согласован с исходником; $NOTE."

# Справка: максимальный занятый номер по каждому префиксу ("следующий" = +1).
echo "  Занятые диапазоны (макс. номер по префиксу — следующий свободный это +1):"
sed -E 's/-([0-9]+)$/ \1/' "$TMP/registered" \
    | awk '{ if ($2 > max[$1]) max[$1] = $2 }
           END { for (p in max) printf "    %-4s → %03d\n", p, max[p] }' \
    | sort
