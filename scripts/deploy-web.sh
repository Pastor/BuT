#!/usr/bin/env bash
# Выкладка статики онлайн-редактора.
#
# Собирает статику и раскладывает её в каталог стенда так, чтобы **старые
# ссылки продолжали работать**:
#
# - бандл лежит в `b/<отпечаток>/` и живёт год (`immutable`) - прежние
#     бандлы не удаляются сразу: у читателя открыта вкладка, и она догрузит
#     свой модуль после выкладки;
#   - модуль лежит в `wasm/<версия>/` и неизменен по построению;
#   - `index.html`, `version.json`, `wasm/index.json` перезаписываются: их
#     читают ради свежести (`no-cache`).
#
# **Отказ на подмене модуля.** Адрес `wasm/<версия>/` обещает
# неизменность. Выложить под ним другой файл - молчаливая порча у каждого, кто
# уже кешировал: страница возьмёт "свой" модуль и получит другой компилятор.
# Поэтому расхождение контрольной суммы при совпадении версии - **отказ
# выкладки**, а не перезапись. Лечится подъёмом версии крейта.
#
# Прежние бандлы копятся, поэтому их **число ограничено**: без предела
# каталог стенда растёт на 3 мб с каждой выкладкой. Самый свежий не трогается
# никогда.
#
# Использование:
#
#   scripts/deploy-web.sh [-d каталог-Стенда] [-k сколько-Бандлов] [--dry-run]

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
STAND="${TAKT_WEB_STAND:-/srv/takt/static}"
KEEP="${TAKT_WEB_KEEP_BUNDLES:-3}"
DRY=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    -d|--dest) STAND="$2"; shift 2 ;;
    -k|--keep) KEEP="$2"; shift 2 ;;
    --dry-run) DRY=1; shift ;;
    -h|--help) sed -n '2,28p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "неизвестный ключ '$1'; см. --help" >&2; exit 2 ;;
  esac
done

echo "Выкладка статики (фича 0531)..."

# -- 1. Сборка ----------------------------------------------------------------
DIST="$(mktemp -d)/dist"
TAKT_WEB_DIST="$DIST" "$ROOT/scripts/build-web.sh" >/dev/null
VERSION="$(sed -n 's/.*"takt_lang": "\([^"]*\)".*/\1/p' "$DIST/version.json" | head -1)"
BUNDLE="$(sed -n 's/.*"bundle": "\([^"]*\)".*/\1/p' "$DIST/version.json" | head -1)"
[[ -n "$VERSION" && -n "$BUNDLE" ]] || {
  echo "  ОШИБКА: собранная статика не называет ни версии, ни бандла"
  exit 1
}
echo "  собрано: бандл $BUNDLE, модуль $VERSION"

# -- 2. Отказ на подмене модуля -----------------------------------------------
NEW_SUM="$(shasum -a 256 "$DIST/wasm/$VERSION/takt.wasm" | cut -d' ' -f1)"
OLD="$STAND/wasm/$VERSION/takt.wasm"
if [[ -f "$OLD" ]]; then
  OLD_SUM="$(shasum -a 256 "$OLD" | cut -d' ' -f1)"
  if [[ "$OLD_SUM" != "$NEW_SUM" ]]; then
    echo "  ОШИБКА: под адресом wasm/$VERSION/ уже лежит ДРУГОЙ модуль"
    echo "    на стенде: $OLD_SUM"
    echo "    собранный: $NEW_SUM"
    echo "  Адрес с версией обещает неизменность, и выложить под ним другой файл —"
    echo "  молчаливая порча у каждого, кто уже кешировал. Поднимите версию крейта"
    echo "  takt-lang (Cargo.toml) и соберите заново."
    exit 1
  fi
  echo "  модуль $VERSION уже выложен и совпадает — не трогаем"
fi

if [[ "$DRY" == "1" ]]; then
  echo "  --dry-run: на стенд ничего не положено"
  rm -rf "$(dirname "$DIST")"
  exit 0
fi

# -- 3. Раскладка -------------------------------------------------------------
mkdir -p "$STAND"
# Копируется добавлением, а не заменой каталога: прежние бандлы и прежние
# версии модуля обязаны остаться - у читателя открыта вкладка.
cp -R "$DIST/." "$STAND/"
echo "  разложено в $STAND"

# `wasm/index.json` перечисляет все версии, что лежат на стенде, а не только
# свежую: страница по нему узнаёт, чем открыть старый проект.
VERSIONS="$(find "$STAND/wasm" -mindepth 1 -maxdepth 1 -type d -exec basename {} \; | sort -V)"
LIST="$(printf '%s\n' "$VERSIONS" | sed 's/.*/"&"/' | paste -sd, -)"
cat > "$STAND/wasm/index.json" <<JSON
{
  "latest": "$VERSION",
  "versions": [$LIST]
}
JSON

# -- 4. Прежние бандлы: сколько-то держим, остальные снимаем ------------------
# Ни `mapfile`, ни `stat -f`: первого нет в bash 3.2 (он стоит на macOS
# системным), у второго разный синтаксис в BSD и GNU. `ls -td` сортирует по
# времени и работает всюду.
index=0
for stale in $(ls -td "$STAND"/b/*/ 2>/dev/null); do
  index=$((index + 1))
  [[ "$index" -le "$KEEP" ]] && continue
  name="$(basename "${stale%/}")"
  # Свежий не трогается никогда - даже если предел задали нулём: без него
  # страница перестала бы открываться в тот же миг.
  [[ "$name" == "$BUNDLE" ]] && continue
  rm -rf "${stale%/}"
  echo "  снят прежний бандл $name"
done
echo "  бандлов на стенде: $(find "$STAND/b" -mindepth 1 -maxdepth 1 -type d | wc -l | tr -d ' ')"

rm -rf "$(dirname "$DIST")"
echo "  Выкладка завершена. ⚠️ Откройте страницу: гейта на браузер в проекте нет."
