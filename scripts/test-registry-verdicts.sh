#!/usr/bin/env bash
# Контрольная проба scripts/check-registry-verdicts.py: проверка отказывает,
# когда разбор реестра обнулился, ловит заготовку у закрытой фичи и молчит на
# согласованном реестре. Работа идёт на копии, боевой реестр не затрагивается.
#
# Первая проба воспроизводит класс, ради которого заведена фича 0536: смена
# ссылки-номера на ссылку-слово в первой ячейке оставляла проверку с нулём
# разобранных строк из 539, и она отвечала успехом с прежним числом в отчёте.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK="$(mktemp -d "${TMPDIR:-/tmp}/takt-registry-verdicts.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT

mkdir -p "$WORK/scripts" "$WORK/docs/features"
cp "$ROOT/scripts/check-registry-verdicts.py" "$ROOT/scripts/gatelib.py" "$WORK/scripts/"

REGISTRY="$WORK/docs/features/README.md"

run() { RV_ROOT="$WORK" python3 "$WORK/scripts/check-registry-verdicts.py" >"$WORK/out" 2>&1; }
fail() { echo "  - $1" >&2; exit 1; }

# Согласованный реестр принимается: без этого условия проверка, отвергающая
# всё, тоже прошла бы набор.
cat >"$REGISTRY" <<'REG'
| Фича | Наименование | Статус | Вердикт тестирования |
|---|---|---|---|
| [0001](./0001-a.md) | Закрытая фича | ГОТОВО | ✅ ГОТОВО |
| [0002](./0002-b.md) | Фича в работе | АНАЛИЗ | СОЗДАНА |
REG
run || fail "V0 согласованный реестр отвергнут: $(cat "$WORK/out")"
echo "  + V0 согласованный реестр принят"

# Заготовка у закрытой фичи ловится - предмет самой проверки.
cat >"$REGISTRY" <<'REG'
| Фича | Наименование | Статус | Вердикт тестирования |
|---|---|---|---|
| [0001](./0001-a.md) | Закрытая фича | ГОТОВО | СОЗДАНА |
REG
if run; then fail "V1 заготовка у закрытой фичи принята"; fi
grep -q "0001" "$WORK/out" || fail "V1 отказ не назвал фичу: $(cat "$WORK/out")"
echo "  + V1 заготовка у закрытой фичи ловится"

# Разбор обнулён сменой формы первой ячейки: номер ушёл из адреса ссылки.
# Прежняя редакция отвечала здесь успехом, печатая число строк файла.
cat >"$REGISTRY" <<'REG'
| Фича | Наименование | Статус | Вердикт тестирования |
|---|---|---|---|
| [карточка](./card-a.md) | Закрытая фича | ГОТОВО | СОЗДАНА |
| [карточка](./card-b.md) | Фича в работе | АНАЛИЗ | СОЗДАНА |
REG
if run; then fail "V2 обнулённый разбор принят за успех: $(cat "$WORK/out")"; fi
grep -q "записи реестра фич" "$WORK/out" || fail "V2 отказ не назвал вход: $(cat "$WORK/out")"
echo "  + V2 обнулённый разбор реестра - отказ"

# Отчёт называет число разобранных записей, а не строк файла: без этого числа
# обнуление разбора остаётся невидимым и в зелёном ответе.
cat >"$REGISTRY" <<'REG'
| Фича | Наименование | Статус | Вердикт тестирования |
|---|---|---|---|
| [0001](./0001-a.md) | Закрытая фича | ГОТОВО | ✅ ГОТОВО |
| [0002](./0002-b.md) | Фича в работе | АНАЛИЗ | СОЗДАНА |

Проза под таблицей, которую разбор не считает записью.
Ещё одна строка прозы.
REG
run || fail "V3 согласованный реестр отвергнут: $(cat "$WORK/out")"
grep -q "разобрано 2" "$WORK/out" || fail "V3 отчёт считает не записи: $(cat "$WORK/out")"
echo "  + V3 отчёт называет число разобранных записей"

echo "Контрольная проба вердиктов реестра: все пробы пройдены"
