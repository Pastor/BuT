#!/bin/sh
# Проверка размера модулей - храповик против роста.
#
# Правило (CLAUDE.md): "Размер модуля - не больше ~1000 строк (вместе с
# тестами); дели по логике". Оно существовало, но ничем не проверялось - и
# потому не работало: сегодняшний validate.rs когда-то был меньше 1000.
# Правило, которое нельзя проверить командой, - не правило.
#
# Метрика - `wc -l`, строки целиком: правило говорит о размере файла, и метрика
# обязана совпадать с тем, что видит читатель. Никаких "строк без комментариев".
#
# Три условия отказа:
# 1. Новый нарушитель - файл вне baseline больше лимита.
# 2. Рост из baseline - файл стал больше зафиксированного. Правки в больших
#      модулях не запрещены; запрещён рост.
# 3. Незакрытая запись - файл уложился в лимит, а запись осталась. Без этого
#      храповик проворачивается назад: ужатый файл смог бы снова дорасти до
#      старой отметки.
# 4. Запись на несуществующий файл - путь переименован или удалён. Иначе
# реестр "замораживает" пустоту, а настоящий файл под новым именем окажется
#      вне проверки: молчание тут неотличимо от порядка.
#
# Жёлтая зона. Кроме отказов проверка печатает предупреждение о файлах,
# подошедших к лимиту вплотную. Повод: без жёлтой зоны проверка молчит вплоть до превышения,
# и первым сигналом становился отказ посреди чужой правки - замер 2026-08-20
# нашёл в зоне >= 970 восемь таких файлов, о которых не говорилось ничего.
#
# Предупреждение не влияет на код возврата: правило говорит "не больше ~1000
# строк", и приближение к лимиту - повод подумать, а не отказ. Проверка, роняющий
# прогон за 30 строк до предела, заставлял бы дробить модуль в чужой правке -
# ровно то, от чего отказалась.
#
# Порог выбран замером, а не круглым числом: при 950 в зоне 15 файлов, при
# 900 - 23 (стена, которую перестают читать); при 970 их восемь.
#
# POSIX sh, без внешних зависимостей (образец - scripts/new-feature.sh).
set -eu

# Корень переопределяется MS_ROOT - для теста scripts/test-module-size.sh:
# он гоняет проверка на временном дереве, не трогая рабочее.
. "$(dirname "$0")/gatelib.sh"

ROOT="${MS_ROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
BASELINE="$ROOT/scripts/module-size-baseline.txt"
LIMIT=1000
# Начало жёлтой зоны - 97 % лимита.
WARN_FROM=970

if [ ! -f "$BASELINE" ]; then
    echo "check-module-size: не найден реестр $BASELINE" >&2
    exit 1
fi

# Файлы под правилом: модули крейтов и интеграционные тесты ("вместе с тестами").
find_sources() {
    # Каждый крейт перечислен явно: новый обязан быть назван
    # здесь, иначе предел размера его не касается - молча.
    find "$ROOT/takt-lang/src" "$ROOT/takt-sim/src" "$ROOT/takt-wasm/src" "$ROOT/takt-project/src" \
         "$ROOT/web/server/src" "$ROOT/web/server/tests" \
         "$ROOT/takt-lang/tests" "$ROOT/takt-sim/tests" \
         -name '*.rs' -type f 2>/dev/null | sed "s|^$ROOT/||" | sort
}

# Значение из baseline для пути; пусто - записи нет.
baseline_of() {
    grep -v '^[[:space:]]*#' "$BASELINE" 2>/dev/null \
        | awk -v p="$1" '$2 == p { print $1; exit }'
}

failed=0
checked=0
debt=0
# Файлы жёлтой зоны копятся и печатаются одним списком в конце: вперемежку с
# отказами предупреждение читалось бы как ещё один отказ.
warnings_list=""
warned=0

for path in $(find_sources); do
    checked=$((checked + 1))
    lines=$(wc -l < "$ROOT/$path" | tr -d ' ')
    allowed=$(baseline_of "$path")

    if [ -z "$allowed" ]; then
        # Жёлтая зона: файл ещё в пределах лимита, но запас мал.
        if [ "$lines" -ge "$WARN_FROM" ] && [ "$lines" -le "$LIMIT" ]; then
            warnings_list="$warnings_list$lines $path
"
            warned=$((warned + 1))
        fi
        # Условие 1: новый нарушитель.
        if [ "$lines" -gt "$LIMIT" ]; then
            echo "ОТКАЗ: $path — $lines строк при лимите $LIMIT." >&2
            echo "       Разделите модуль ПО ЛОГИКЕ (границы модулей = границы" >&2
            echo "       ответственности) либо внесите в $BASELINE с обоснованием." >&2
            failed=1
        fi
        continue
    fi

    # Условие 3: запись закрыта, но осталась в реестре.
    if [ "$lines" -le "$LIMIT" ]; then
        echo "ОТКАЗ: $path — $lines строк, уложился в лимит $LIMIT," >&2
        echo "       но запись всё ещё в $BASELINE. Удалите её:" >&2
        echo "       иначе храповик провернётся назад и файл сможет вырасти снова." >&2
        failed=1
        continue
    fi

    # Условие 2: рост сверх зафиксированного.
    if [ "$lines" -gt "$allowed" ]; then
        echo "ОТКАЗ: $path вырос: было $allowed, стало $lines (лимит $LIMIT)." >&2
        echo "       Файл уже сверх лимита — расти ему нельзя. Вынесите новое" >&2
        echo "       в отдельный модуль либо ужмите существующее." >&2
        failed=1
        continue
    fi

    # Уменьшение - не ошибка, но реестр обязан идти за фактом: иначе запас
    # накапливается и храповик слабеет.
    if [ "$lines" -lt "$allowed" ]; then
        echo "ОТКАЗ: $path ужат: было $allowed, стало $lines." >&2
        echo "       Обновите запись в $BASELINE — долг фиксируется по факту," >&2
        echo "       иначе разница станет запасом на будущий рост." >&2
        failed=1
        continue
    fi

    debt=$((debt + lines - LIMIT))
done

# Условие 4: реестр ссылается на файл, которого нет.
grep -v '^[[:space:]]*#' "$BASELINE" 2>/dev/null | while read -r _ path; do
    [ -n "${path:-}" ] || continue
    if [ ! -f "$ROOT/$path" ]; then
        echo "ОТКАЗ: $BASELINE ссылается на несуществующий файл: $path" >&2
        echo "       Переименован или разделён? Удалите запись — иначе реестр" >&2
        echo "       замораживает пустоту, а настоящий файл окажется вне проверки." >&2
        exit 1
    fi
done || failed=1

if [ "$failed" -ne 0 ]; then
    echo "" >&2
    echo "Правило: «Размер модуля — не больше ~$LIMIT строк (вместе с тестами);" >&2
    echo "дели по логике» (CLAUDE.md). Реестр $BASELINE — узаконенный долг," >&2
    echo "а не разрешение: единственная допустимая правка записи — уменьшение." >&2
    exit 1
fi

if [ "$warned" -ne 0 ]; then
    echo "  ⚠ Жёлтая зона ($WARN_FROM…$LIMIT строк): $warned файлов — дробить их"
    echo "    лучше СЕЙЧАС, своей правкой, а не когда лимит упрётся посреди чужой."
    echo "    На код возврата это не влияет."
    printf '%s' "$warnings_list" | sort -rn | while read -r n f; do
        echo "      $f — $n строк (запас $((LIMIT - n)))"
    done
fi

entries=$(grep -cv '^[[:space:]]*#' "$BASELINE" 2>/dev/null || echo 0)
NOTE="$(require_input "просмотренные модули" "$checked" 1 "$ROOT")" || exit 1
echo "Размер модулей: $NOTE, записей долга $entries, превышение $debt строк."
