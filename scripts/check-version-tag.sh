#!/bin/sh
# Проверка метки версии языка.
#
# коммит, поднимающий версию языка, снабжается аннотированным тегом
# `v<версия>` - и на тот самый коммит, а не на последующие: только так по
# истории видно, где проходит граница версии.
#
# Повод - замер, а не осторожность. На 2026-08-18 из восьми версий языка тегов
# не имели две: `v0.4.0` (подъём) и `v0.10.0` (подъём,
# сделанный накануне). Четверть пропусков при живом правиле - обычная судьба
# правила без команды (тот же довод, что у про саму константу версии).
#
# Главная тонкость: Проверка обязан молчать В момент подъёма. Тег ставится на
# коммит, а предкоммит идёт до коммита - наивная проверка "тег текущей версии
# существует" падала бы у каждой фичи, которая правило исполняет верно.
# Признак незакоммиченного подъёма - расхождение значения константы в рабочем
# дереве и в `HEAD`: версия поднята, коммита ещё нет, тегу взяться неоткуда.
# Как только подъём закоммичен, значения совпадают и тег становится обязателен -
# поэтому пропуск `v0.10.0` был бы пойман на первом же прогоне после.
#
# Граница: прошлые версии проверка не проверяет. Перечня версий в дереве нет
# (README документирует два перехода из восьми), а восстанавливать список из
# `git log -S` значит завести проверка, зависящий от формулировок старых коммитов.
# Прошлое размечено один раз.
#
# Клон без тегов проверке судить не о чем. Следствие, найденное тестом:
# в репозитории без единого тега пропуск тега версии неотличим от невыкачанных
# тегов, и проверка по построению выбирает мягкий пропуск. Это не дыра, а честная
# граница: различить два состояния нечем, а строгий режим их разводит. Вне CI `git clone` тянет теги сам; в
# CI это задано явно (`fetch-depth: 0` у actions/checkout). Под
# PRECHECK_STRICT=1 отсутствие тегов - ошибка, иначе мягкий пропуск: строгий
# режим для того и заведён, чтобы пропущенный проверка не был неотличим от
# пройденного.
#
# Переменная VT_ROOT переопределяет корень (для теста scripts/test-version-tag.sh).
#
# POSIX sh, без внешних зависимостей (образец - scripts/check-language-version.sh).
set -eu

ROOT="${VT_ROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
VERSION_RS="$ROOT/takt-lang/src/version.rs"
VER_RE='[0-9]+\.[0-9]+\.[0-9]+'
REL_VERSION_RS="takt-lang/src/version.rs"

[ -f "$VERSION_RS" ] || { echo "check-version-tag: не найден $VERSION_RS" >&2; exit 1; }

echo "Гейт метки версии языка: тег v<версия> на коммите подъёма (фича 0162, правило 22)..."

extract() {   # stdin → версия
    grep -oE "LANGUAGE_VERSION: &str = \"$VER_RE\"" | grep -oE "$VER_RE" | head -n1
}

WORK_VER="$(extract < "$VERSION_RS" || true)"
if [ -z "${WORK_VER:-}" ]; then
    echo "  ОШИБКА: не удалось извлечь LANGUAGE_VERSION из $REL_VERSION_RS" >&2
    exit 1
fi

cd "$ROOT"

if ! git rev-parse --git-dir >/dev/null 2>&1; then
    echo "  ПРОПУСК: каталог не является git-репозиторием — судить не о чем."
    exit 0
fi

# --- Подъём ещё не закоммичен? Тогда молчим (см. заголовок) -----------------
HEAD_VER="$(git show "HEAD:$REL_VERSION_RS" 2>/dev/null | extract || true)"
if [ -z "${HEAD_VER:-}" ]; then
    echo "  ПРОПУСК: в HEAD нет $REL_VERSION_RS — сравнивать не с чем."
    exit 0
fi
if [ "$WORK_VER" != "$HEAD_VER" ]; then
    echo "  ПРОПУСК: подъём $HEAD_VER → $WORK_VER ещё не закоммичен."
    echo "  Тег ставится НА коммит подъёма — после коммита, командой:"
    echo "    git tag -a v$WORK_VER -m \"Версия языка $WORK_VER\" <хеш коммита>"
    exit 0
fi

# --- Есть ли теги вообще ----------------------------------------------------
if [ -z "$(git tag -l 2>/dev/null)" ]; then
    if [ "${PRECHECK_STRICT:-0}" = "1" ]; then
        echo "  ОШИБКА: в клоне нет ни одного тега — гейт не может судить." >&2
        echo "  В CI нужен полный клон: actions/checkout с fetch-depth: 0." >&2
        exit 1
    fi
    echo "  ПРОПУСК: в клоне нет тегов (поверхностный клон). Строгий режим — ошибка."
    exit 0
fi

TAG="v$WORK_VER"
BAD=0

# --- Тег существует ---------------------------------------------------------
if ! git rev-parse -q --verify "refs/tags/$TAG" >/dev/null 2>&1; then
    echo "  ОШИБКА: версия языка $WORK_VER закоммичена, а тега $TAG нет." >&2
    # Тег мог быть поставлен автоматикой после пуша (: релизный
    # workflow ставит его на коммит подъёма). Локально его тогда ещё нет -
    # поэтому первой подсказкой идёт `fetch`, а не создание второго тега.
    echo "  Если подъём уже запушен, тег мог поставить релиз — подтяните теги:" >&2
    echo "    git fetch --tags" >&2
    echo "  Иначе (правило 22) пометьте КОММИТ подъёма вручную. Найти его:" >&2
    echo "    git log -S\"LANGUAGE_VERSION: &str = \\\"$WORK_VER\\\"\" -- $REL_VERSION_RS" >&2
    echo "    git tag -a $TAG -m \"Версия языка $WORK_VER\" <хеш>" >&2
    exit 1
fi

# --- Тег аннотированный -----------------------------------------------------
# Лёгкий тег не несёт ни автора, ни даты, ни сообщения - метка границы версии
# без них теряет половину смысла.
OBJTYPE="$(git for-each-ref "refs/tags/$TAG" --format='%(objecttype)')"
if [ "$OBJTYPE" != "tag" ]; then
    echo "  ОШИБКА: $TAG — лёгкий тег (objecttype=$OBJTYPE), нужен аннотированный." >&2
    echo "    git tag -f -a $TAG -m \"Версия языка $WORK_VER\" $TAG^{commit}" >&2
    BAD=1
fi

# --- Тег достижим из HEAD ---------------------------------------------------
# Тег на коммите вне ветки означает, что граница версии проведена не в той
# истории, по которой идёт работа.
if ! git merge-base --is-ancestor "$TAG^{commit}" HEAD 2>/dev/null; then
    echo "  ОШИБКА: $TAG указывает на коммит, не достижимый из HEAD." >&2
    BAD=1
fi

[ "$BAD" -eq 0 ] || exit 1

echo "  OK: $TAG → $(git rev-parse --short "$TAG^{commit}") (аннотированный, достижим из HEAD)"
