#!/bin/sh
# check-stale-candidates.sh - подсказка к ревизии кандидатов.
#
# Блок "Кандидаты в фичи" FEATURES.md - вход в проект для новой сессии, и
# устаревшая запись там дороже отсутствующей: по ней заводят уже сделанную
# работу. Скрипт помогает закрывающей фиче найти кандидатов, которых она обязана
# просмотреть.
#
# Использование:
# scripts/check-stale-candidates.sh NNNN # кандидаты, упоминающие
# scripts/check-stale-candidates.sh # сводка по блоку
#
# Это подсказка, а не проверка: код возврата всегда 0. Кандидат вполне может
# ссылаться на закрытую фичу и оставаться верным - его туда и вынесли при
# закрытии. Решение - за человеком.
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
FEATURES="$ROOT/FEATURES.md"

[ -f "$FEATURES" ] || { echo "Нет $FEATURES"; exit 0; }

# Блок 2 целиком (от заголовка "## 2." до "## 3.").
block() {
  awk '/^## 2\./{f=1} /^## 3\./{f=0} f' "$FEATURES"
}

if [ $# -ge 1 ]; then
  NUM="$1"
  echo "Кандидаты, упоминающие фичу $NUM (правило 28 — просмотреть при закрытии):"
  block | awk -v num="$NUM" '
    function flush() { if (buf != "" && hit) { print buf; print ""; n++ } }
    /^- \*\*/ { flush(); buf = $0; hit = (index($0, num) > 0); next }
    /^[^ ]/   { flush(); buf = ""; hit = 0; next }
    buf != "" { buf = buf "\n" $0; if (index($0, num) > 0) hit = 1 }
    END       { flush(); if (n == 0) print "  (ни одного — снимать нечего)" }
  ' | sed 's/^/  /'
  exit 0
fi

TOTAL=$(block | grep -c '^- \*\*' || true)
echo "Кандидатов в блоке 2: $TOTAL"
echo
echo "Подсказка работает по номеру фичи:"
echo "  scripts/check-stale-candidates.sh NNNN   # кандидаты, которых обязано просмотреть закрытие NNNN"
echo
echo "⚠️ Метрики «сколько кандидатов ссылается на закрытые фичи» здесь нет намеренно:"
echo "   такая ссылка есть почти у каждого — кандидатов туда и выносят ПРИ закрытии,"
echo "   поэтому счётчик даёт «все из всех» и ничего не сообщает (замер фичи 0140)."
exit 0
