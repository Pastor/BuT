#!/bin/sh
# Тест проверки кодов диагностик: мутацией доказывает, что каждое из
# Пяти условий отказа срабатывает, а согласованное дерево принимается.
#
# Повод прямой: до 0255 у проверки самопроверки не было вовсе, и одно его условие
# оказалось дырявым - код, вплавленный в текст сообщения (`"Ошибка [SIM-030]:
# ..."`), для него не существовал. Прогон при этом был зелёным: с обеих сторон
# пусто. Проверка, который никогда не падал, неотличим от проверки, который не смотрит.
#
# Гоняется в temp-дереве через DC_ROOT - рабочий реестр не трогается.
#
# POSIX sh (образец - scripts/test-legacy-names.sh, scripts/test-new-feature.sh).
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
GATE="$ROOT/scripts/check-diagnostic-codes.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

FAILED=0
ok()   { echo "  OK: $1"; }
fail() { echo "  ПРОВАЛ: $1" >&2; FAILED=1; }

echo "Сторож гейта кодов диагностик (фича 0255)..."

# --- Каркас temp-дерева ------------------------------------------------------
# Строится заново под каждый случай: проверка читает оба крейта и реестр, и разделять
# их состояние между проверками значило бы мерить последствия предыдущей.
build_tree() {
    SRC_BODY="$1"
    REGISTRY_BODY="$2"
    rm -rf "$TMP/tree"
    mkdir -p "$TMP/tree/takt-lang/src" "$TMP/tree/takt-sim/src" "$TMP/tree/docs/diagnostics"
    printf '%s\n' "$SRC_BODY" > "$TMP/tree/takt-sim/src/lib.rs"
    : > "$TMP/tree/takt-lang/src/lib.rs"
    {
        printf '# Реестр кодов диагностик\n\n'
        printf '| Код | Значение | Источник |\n|---|---|---|\n'
        printf '%s\n' "$REGISTRY_BODY"
    } > "$TMP/tree/docs/diagnostics/README.md"
}

run_gate() { DC_ROOT="$TMP/tree" sh "$GATE" >"$TMP/out" 2>&1; }

# --- 0. Согласованное дерево принимается ------------------------------------
build_tree 'const CODE: &str = "SIM-030";' '| `SIM-030` | порт не найден | `takt-sim/src/lib.rs` |'
if run_gate; then
    ok "согласованное дерево принимается"
else
    fail "согласованное дерево отвергнуто — гейт даёт ложное срабатывание: $(cat "$TMP/out")"
fi

# --- 1. Эмитируется, но не в реестре ----------------------------------------
build_tree 'const CODE: &str = "SIM-030";' '| `SIM-031` | другое | `x` |'
if ! run_gate && grep -q 'отсутствует в реестре' "$TMP/out"; then
    ok "условие 1: незадокументированный код ловится"
else
    fail "условие 1 не сработало: $(cat "$TMP/out")"
fi

# --- 2. В реестре, но не эмитируется ----------------------------------------
build_tree '// пусто' '| `SIM-030` | порт не найден | `takt-sim/src/lib.rs` |'
if ! run_gate && grep -q 'исходник его не эмитирует' "$TMP/out"; then
    ok "условие 2: протухшая запись ловится"
else
    fail "условие 2 не сработало: $(cat "$TMP/out")"
fi

# --- 2а. RETIRED снимает требование эмиссии ---------------------------------
build_tree '// пусто' '| `SIM-030` | выведен | RETIRED |'
if run_gate; then
    ok "условие 2: пометка RETIRED принимается"
else
    fail "RETIRED отвергнут — вывод кода стал невозможен: $(cat "$TMP/out")"
fi

# --- 3. Нарушение формата ---------------------------------------------------
build_tree 'const CODE: &str = "SIM-4";' '| `SIM-030` | порт не найден | RETIRED |'
if ! run_gate && grep -q 'нарушает формат' "$TMP/out"; then
    ok "условие 3: формат XX-NNN проверяется"
else
    fail "условие 3 не сработало: $(cat "$TMP/out")"
fi

# --- 4. Дубль строки в реестре ----------------------------------------------
build_tree 'const CODE: &str = "SIM-030";' '| `SIM-030` | порт не найден | `x` |
| `SIM-030` | он же второй раз | `x` |'
if ! run_gate && grep -q 'перечислен в реестре дважды' "$TMP/out"; then
    ok "условие 4: дубль строки ловится"
else
    fail "условие 4 не сработало: $(cat "$TMP/out")"
fi

# --- 5. Код вплавлен в текст сообщения (предмет ) ------------------
# Форма ровно та, в которой класс и жил: код внутри строки, отдельного литерала
# нет. До 0255 такой прогон был зелёным.
build_tree 'eprintln!("Ошибка [SIM-030]: шаг {n}: порт не найден");' '| `SIM-031` | другое | RETIRED |'
if ! run_gate && grep -q 'внутри текста сообщения' "$TMP/out"; then
    ok "условие 5: вплавленный код ловится"
else
    fail "условие 5 не сработало — класс фичи 0255 вернулся: $(cat "$TMP/out")"
fi

# --- 5а. Место названо с номером строки -------------------------------------
# Отказ списком мест, а не одним кодом: иначе автор ищет вручную.
if grep -q 'takt-sim/src/lib.rs:1' "$TMP/out"; then
    ok "условие 5: место названо файлом и строкой"
else
    fail "условие 5 не называет места — автору негде искать: $(cat "$TMP/out")"
fi

# --- 5б. Контроль: со своим литералом та же строка проходит ------------------
# Без контроля "ловится" означало бы лишь, что проверка ругается на любую скобку.
build_tree 'const CODE: &str = "SIM-030";
eprintln!("Ошибка [{CODE}]: порт не найден");
// в комментарии код тоже упоминается как [SIM-030]' \
    '| `SIM-030` | порт не найден | `takt-sim/src/lib.rs` |'
if run_gate; then
    ok "условие 5: код с отдельным литералом принимается"
else
    fail "код с литералом отвергнут — шаблон слишком широк: $(cat "$TMP/out")"
fi

[ "$FAILED" -eq 0 ] || { echo "  Сторож гейта кодов диагностик провален." >&2; exit 1; }
echo "  Сторож гейта кодов диагностик пройден (условия 1–5 и контроль)."
