# gatelib.sh - нижняя граница входа проверки на POSIX sh.
#
# Двойник scripts/gatelib.py для проверок, написанных на sh: их десять из
# сорока восьми, и без своего помощника у них завёлся бы второй способ отказа.
# Предмет и доводы описаны в gatelib.py; здесь только форма.
#
# Подключение и вызов:
#
#     . "$(dirname "$0")/gatelib.sh"
#     NOTE="$(require_input "просмотренные файлы" "$COUNT" 1 "$ROOT/docs")" || exit 1
#     ...
#     echo "Стиль документов: $NOTE, нарушений нет"
#
# Описание входа уходит в stdout, отказ - в stderr с кодом 1. Хвост `|| exit 1`
# обязателен: подстановка команд исполняет функцию в подоболочке, и выход из неё
# оставил бы вызывающего с пустым описанием и нулевым кодом - ровно тем
# молчанием, против которого заведён помощник. Под `set -e` вызывающий упадёт и
# без хвоста, но полагаться на режим оболочки помощник не вправе.

# require_input <имя> <размер> [граница] [источник]
require_input() {
    gl_name="$1"
    gl_size="$2"
    gl_min="${3:-1}"
    gl_source="${4:-}"

    if [ "$gl_min" -lt 1 ]; then
        echo "ОШИБКА: граница входа не может быть меньше единицы" >&2
        return 2
    fi
    if [ "$gl_size" -lt "$gl_min" ]; then
        if [ -n "$gl_source" ]; then
            gl_place=" ($gl_source)"
        else
            gl_place=""
        fi
        {
            echo "ОШИБКА: вход «$gl_name» не достиг границы$gl_place: разобрано $gl_size при границе $gl_min."
            echo "Пустая выборка - не благополучие, а слепота: разбор ничего не нашёл, и"
            echo "находкам взяться неоткуда, поэтому проверка ответила бы успехом, не прочитав"
            echo "ни строки. Верните разметку либо обновите разбор вместе с нею - но не"
            echo "оставляйте проверку без входа."
        } >&2
        return 1
    fi
    echo "разобрано $gl_size - $gl_name"
}
