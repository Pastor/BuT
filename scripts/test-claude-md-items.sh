#!/bin/sh
# Тест проверки размера пунктов CLAUDE.md (;: у каждого
# проверки есть тест, и он идёт первым).
#
# Проверка гоняется на копии дерева (`CM_ROOT`), а не на рабочем: проверяется его
# предмет, а не то, что он запускается. Условий пять - по числу способов,
# которыми проверка может оказаться бутафорской:
#
#   1. согласованное дерево принимается;
#   2. переросший пункт вне реестра ловится и назван;
#   3. запись реестра замораживает долг (пункт той же длины проходит);
#   4. протухшая запись (пункт уложился в предел) ловится;
#   5. рост сверх записанного ловится;
# 6. двухстрочный жирный заголовок узнаётся - иначе пункт приписывается
#      предыдущему, и проверка сообщает о пунктах, которых нет (дефект первой
#      редакции, пойман на живом файле).
#
# POSIX sh.
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TOOL="$ROOT/scripts/check-claude-md-items.py"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

FAILED=0
ok()   { echo "  OK: $1"; }
fail() { echo "  ПРОВАЛ: $1" >&2; FAILED=1; }

echo "Сторож гейта размера пунктов CLAUDE.md (фича 0408)..."

mkdir -p "$TMP/scripts"

# Пункт из N строк: заголовок плюс продолжения.
item() {
    name="$1"; lines="$2"
    printf -- '- **%s**\n' "$name"
    i=1
    while [ "$i" -lt "$lines" ]; do
        printf '  продолжение %s.\n' "$i"
        i=$((i + 1))
    done
}

write_context() {
    {
        echo "# Контекст"
        echo
        echo "## Технические подводные камни"
        echo
        cat
    } > "$TMP/CLAUDE.md"
}

run() { CM_ROOT="$TMP" python3 "$TOOL" >"$TMP/out" 2>&1; }

# --- 1. Согласованное дерево принимается ------------------------------------
: > "$TMP/scripts/claude-md-item-baseline.txt"
item "Короткий пункт" 5 | write_context
if run; then
    ok "согласованное дерево принимается"
else
    fail "короткий пункт отвергнут: $(cat "$TMP/out")"
fi

# --- 2. Переросший пункт вне реестра ловится и назван -----------------------
item "Разросшийся пункт" 40 | write_context
if ! run && grep -q 'Разросшийся пункт' "$TMP/out"; then
    ok "переросший пункт ловится и назван"
else
    fail "переросший пункт не пойман: $(cat "$TMP/out")"
fi

# --- 3. Запись реестра замораживает долг ------------------------------------
# 41, а не 40: пустая строка в конце файла принадлежит последнему пункту -
# длину берём из ответа самого проверки, а не из числа напечатанных строк.
echo "41 Разросшийся пункт" > "$TMP/scripts/claude-md-item-baseline.txt"
if run; then
    ok "узаконенный долг пропускается"
else
    fail "долг не пропущен: $(cat "$TMP/out")"
fi

# --- 4. Протухшая запись ловится --------------------------------------------
item "Разросшийся пункт" 5 | write_context
if ! run && grep -q 'протухли' "$TMP/out"; then
    ok "протухшая запись ловится"
else
    fail "протухшая запись не поймана: $(cat "$TMP/out")"
fi

# --- 5. Рост сверх записанного ловится --------------------------------------
item "Разросшийся пункт" 60 | write_context
if ! run && grep -q 'выросли сверх записанного' "$TMP/out"; then
    ok "рост сверх реестра ловится"
else
    fail "рост не пойман: $(cat "$TMP/out")"
fi

# --- 6. Двухстрочный заголовок узнаётся -------------------------------------
# Жирный заголовок, разорванный переносом строки: наивная построчная регулярка
# его не видит, пункт приписывается предыдущему - и длины обоих неверны.
: > "$TMP/scripts/claude-md-item-baseline.txt"
{
    item "Первый пункт" 5
    printf -- '- **Заголовок, который занимает\n  ДВЕ строки** и дальше текст.\n'
    i=1
    while [ "$i" -lt 30 ]; do
        printf '  продолжение %s.\n' "$i"
        i=$((i + 1))
    done
} | write_context
if ! run && grep -q 'Заголовок, который занимает ДВЕ строки' "$TMP/out"; then
    ok "двухстрочный заголовок узнаётся и назван целиком"
else
    fail "двухстрочный заголовок не узнан: $(cat "$TMP/out")"
fi

if [ "$FAILED" -ne 0 ]; then
    echo "Сторож гейта размера пунктов: ПРОВАЛ" >&2
    exit 1
fi
echo "  Сторож гейта размера пунктов: все проверки пройдены"
