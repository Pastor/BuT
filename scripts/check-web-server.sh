#!/usr/bin/env bash
# Проверка сервера проектов.
#
# Что доказывает:
#
#   1. сервер собирается и его код чист (`clippy -D warnings`, `fmt --check`);
#   2. проверки, которым база не нужна (пароли, токены, окно частоты, форма
#      ошибок, список маршрутов), проходят всегда;
#   3. проверки хранилища и HTTP проходят там, где есть PostgreSQL.
#
# Копия сервиса проверяется отдельным тестом (`test-dump-web.sh`): у неё
# другой предмет - "снятое читается обратно", и другой набор инструментов
# (`pg_dump`, `pg_restore`).
#
# Хранилище - PostgreSQL ( отменяет SQLite из
# проработки). Вместе с базой в памяти ушла возможность проверять хранилище без
# сервера субд, и половина проверок стала зависеть от внешнего инструмента.
# Политика та же, что у ST-арбитра и `verilator`: нет базы - мягкий
# пропуск, под `PRECHECK_STRICT=1` - ошибка. Строка подключения -
# `TAKT_WEB_TEST_DB`.
#
# Свой каталог сборки: `web/server` - Отдельный workspace, и без явного
# `CARGO_TARGET_DIR` он писал бы в `target/precheck` корня, который предкоммит
# чистит по размеру - то есть пересобирал бы полторы сотни крейтов на
# каждом прогоне.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT/web/server"

STRICT="${PRECHECK_STRICT:-0}"
export CARGO_TARGET_DIR="${TAKT_WEB_SERVER_TARGET:-$ROOT/target/web-server}"

echo "Гейт сервера проектов (фича 0531)..."

# -- 1. Код чист --------------------------------------------------------------
cargo fmt --check || {
  echo "  ОШИБКА: код сервера не отформатирован (cargo fmt)"
  exit 1
}
cargo clippy --all-targets -- -D warnings 2>&1 | grep -E "^(error|warning)" && {
  echo "  ОШИБКА: clippy недоволен кодом сервера"
  exit 1
}

# -- 2. Проверки без базы -----------------------------------------------------
cargo test --lib || {
  echo "  ОШИБКА: проверки сервера без базы красны"
  exit 1
}

# -- 3. Проверки с базой ------------------------------------------------------
if [[ -z "${TAKT_WEB_TEST_DB:-}" ]]; then
  if [[ "$STRICT" == "1" ]]; then
    echo "  ОШИБКА: не задан TAKT_WEB_TEST_DB — проверки хранилища и HTTP не выполнены (PRECHECK_STRICT=1)"
    exit 1
  fi
  echo "  пропуск: не задан TAKT_WEB_TEST_DB — проверки хранилища и HTTP не выполнены"
  echo "  (поднять базу: TAKT_WEB_TEST_DB=postgresql://пользователь@хост:порт/база)"
  exit 0
fi

# -- 4. Статика для проверок архива -------------------------------------------
# Вывод целей в архиве собирает модуль `takt-wasm` из собранной статики (задача
# 09g). Нет её - половина набора архива пропускается, и каждая проверка говорит
# об этом словами. Собирать статику здесь нельзя: это предмет соседнего проверки.
if [[ -z "${TAKT_WEB_TEST_STATIC:-}" && -f "$ROOT/web/dist/version.json" ]]; then
  export TAKT_WEB_TEST_STATIC="$ROOT/web/dist"
  echo "  статика для проверок архива: $TAKT_WEB_TEST_STATIC"
fi

# `--tests`, а не `--test http`: наборов шесть (вход, проекты, витрина,
# права, архив, срок хранения), и забытый набор молча не прогонялся бы.
cargo test --tests || {
  echo "  ОШИБКА: проверки хранилища и HTTP красны"
  exit 1
}
echo "  Сервер проектов: код чист, проверки без базы и с базой пройдены."
