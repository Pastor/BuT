#!/usr/bin/env bash
# Гигиена каталога сборки предкоммита.
#
# Зачем. У cargo нет сборки мусора: каждая сборка кладёт в `debug/deps` артефакты
# с новым хешем, а старые остаются навсегда. Каталог растёт монотонно, и однажды
# обращение к нему становится дороже самой компиляции. Замер 2026-08-15 на
# накопленном каталоге (83 гб, 599 435 файлов в `debug/deps`):
#
#   листинг deps (599 435 файлов) ......... 66.7 с
#   листинг deps (17 558 файлов, здоровый).. 0.13 с
#   вся сборка проекта с тестами с нуля .... 42 с
#
# То есть один обход каталога стоил дороже, чем собрать проект целиком, а cargo
# обходит его перед каждой единицей компиляции. Полный предкоммит на таком
# каталоге шёл более суток при том, что исполнение всех 2949 тестов занимает 64 с.
#
# Чем мерим. Размером записи каталога (`stat`), а не `du`/`find`/`ls`: на больном
# каталоге те стоят 74 / десятки / 67 секунд - то есть метрика сама становится
# болезнью. `stat` стоит 0.021 с и линеен по числу файлов (32 байта на запись):
#
# здоровый: 17 558 файлов -> 561 920 байт (0.5 МиБ)
# больной: 599 435 файлов -> 19 229 632 байт (19.2 МиБ)
#
# Что чистим. Только каталог проверки, переданный первым аргументом. Рабочий
# `target` автора - чужие данные, и этот скрипт их не трогает никогда: путь
# удаления обязан оканчиваться на `/target/precheck` (проверка ниже), иначе
# скрипт отказывает.
#
# Использование:
#   scripts/precheck-hygiene.sh <каталог-проверки>
# Переменные:
# PRECHECK_DEPS_LIMIT_MIB порог в МиБ (умолчание 4; ≈ 130 тыс. файлов -
#                            восьмикратный запас к здоровому состоянию)
set -euo pipefail

TARGET_DIR="${1:?использование: precheck-hygiene.sh <каталог-гейта>}"
LIMIT_MIB="${PRECHECK_DEPS_LIMIT_MIB:-4}"

# Защита от удаления чужого: путь обязан оканчиваться на /target/precheck.
# Проверка стоит до любого обращения к файловой системе - ошибка в вызове не
# должна получить шанс превратиться в потерю рабочего каталога.
case "$TARGET_DIR" in
  */target/precheck) ;;
  *)
    echo "  ОШИБКА гигиены: '$TARGET_DIR' не оканчивается на /target/precheck — отказ." >&2
    exit 1
    ;;
esac

DEPS="$TARGET_DIR/debug/deps"
[ -d "$DEPS" ] || exit 0

# Размер записи каталога: BSD (macOS) и GNU (Linux/CI) - разные ключи `stat`.
dir_entry_size() {
  stat -f "%z" "$1" 2>/dev/null || stat -c "%s" "$1" 2>/dev/null || echo 0
}

SIZE="$(dir_entry_size "$DEPS")"
LIMIT=$((LIMIT_MIB * 1024 * 1024))

if [ "$SIZE" -le "$LIMIT" ]; then
  exit 0
fi

SIZE_MIB=$((SIZE / 1024 / 1024))
echo "Гигиена каталога гейта (фича 0234): запись $DEPS = ${SIZE_MIB} МиБ > порога ${LIMIT_MIB} МиБ."
echo "  Накопленные артефакты делают обращение к каталогу дороже самой сборки"
echo "  (замер: 67 с на листинг против 0.13 с у здорового), поэтому каталог гейта"
echo "  удаляется целиком; следующая сборка с нуля стоит около полутора минут."
echo "  ⚠️ Рабочий target НЕ трогается — если тормозит IDE, чистить его вам."
rm -rf "$TARGET_DIR"
echo "  Удалено: $TARGET_DIR"
