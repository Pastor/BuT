#!/usr/bin/env bash
# Резервная копия сервиса проектов.
#
# Копий две, и они разного рода:
#
# 1. **база** - учётные записи, сведения о проектах, состав файлов, права
#      (`pg_dump`, формат `custom`: он сжат и восстанавливается выборочно);
# 2. **файловая система с исходниками** - то, чего в базе больше нет
# `<владелец>/<проект>/<файлы>`.
#
# Копия базы без копии файлов бесполезна: восстановленный сервис покажет
# список проектов, у которых нет ни строчки исходника. Обратное так же верно.
# Поэтому файлы снимаются **по умолчанию**, а не по просьбе, а `--no-files`
# существует лишь для того, кто снимает их иначе (снимок тома, `rsync`).
#
# Порядок обязателен: **сначала файлы, потом база**. Между двумя снимками
# сервис живёт, и проект, заведённый между ними, попадёт в базу без файлов -
# то есть будет виден и пуст. При обратном порядке он попадёт в файлы без
# записи в базе - то есть будет невидим и цел, а это чинится подметанием.
#
# Использование:
#
#   scripts/dump-web.sh [-o каталог] [--no-files]
#
# Переменные: `TAKT_WEB_DB` (строка подключения), `TAKT_WEB_PROJECTS`
# (каталог исходников) - те же, что у сервера.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${TAKT_WEB_DUMP_DIR:-$ROOT/web/dumps}"
FILES=1

while [[ $# -gt 0 ]]; do
  case "$1" in
    -o|--out) OUT="$2"; shift 2 ;;
    --no-files) FILES=0; shift ;;
    -h|--help)
      sed -n '2,30p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
      exit 0 ;;
    *) echo "неизвестный ключ '$1'; см. --help" >&2; exit 2 ;;
  esac
done

DB="${TAKT_WEB_DB:-postgresql://localhost/takt_web}"
PROJECTS="${TAKT_WEB_PROJECTS:-$ROOT/web/projects}"
STAMP="$(date -u +%Y%m%dT%H%M%SZ)"
mkdir -p "$OUT"

echo "Резервная копия сервиса проектов (фича 0531)..."

# -- 1. Файлы -----------------------------------------------------------------
# Первыми: см. про порядок в шапке.
if [[ "$FILES" == "1" ]]; then
  if [[ -d "$PROJECTS" ]]; then
    ARCHIVE="$OUT/projects-$STAMP.tar.gz"
    # `-C` и точка: в архиве лежит содержимое каталога, а не путь машины, с
    # которой снимали. Иначе восстановление на другом стенде разворачивало бы
    # чужую иерархию каталогов.
    tar -czf "$ARCHIVE" -C "$PROJECTS" .
    echo "  исходники: $ARCHIVE ($(du -h "$ARCHIVE" | cut -f1))"
  else
    echo "  ОШИБКА: каталога исходников '$PROJECTS' нет — копировать нечего"
    echo "  (задайте TAKT_WEB_PROJECTS либо снимите копию с --no-files)"
    exit 1
  fi
else
  echo "  исходники: пропуск по --no-files (снимаются иначе)"
fi

# -- 2. База ------------------------------------------------------------------
command -v pg_dump >/dev/null 2>&1 || {
  echo "  ОШИБКА: не найден pg_dump — копия базы не снята"
  exit 1
}
DBFILE="$OUT/db-$STAMP.dump"
pg_dump --format=custom --no-owner --no-privileges --file="$DBFILE" "$DB" || {
  echo "  ОШИБКА: pg_dump не отработал"
  exit 1
}
echo "  база: $DBFILE ($(du -h "$DBFILE" | cut -f1))"

echo "  Копия снята. Восстановление — scripts/restore-web.sh $STAMP"
