#!/bin/sh
# Тест инструмента снятия замера: проверяет, что
# scripts/probe.sh ловит каждую известную ловушку пробы и не поднимает ложную
# тревогу на годной.
#
# Повод - прямой: `scripts/run_simulations.sh` сломался в день
# (искал бинарник в `target/debug`, тогда как сборка переехала в
# `target/precheck`) и не был замечен, потому что его никто не запускает.
# Инструмент, который никто не гоняет, неотличим от сломанного, - поэтому
# тест стоит шагом предкоммита.
#
# POSIX sh (образец - scripts/test-legacy-names.sh).
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PROBE="$ROOT/scripts/probe.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

FAILED=0
ok()   { echo "  OK: $1"; }
fail() { echo "  ПРОВАЛ: $1" >&2; FAILED=1; }

echo "Сторож инструмента снятия замера (фича 0301)..."

BIN_DIR="$("$ROOT/scripts/target-dir.sh")"
if [ ! -x "$BIN_DIR/taktc" ] || [ ! -x "$BIN_DIR/takt-sim" ]; then
    if [ "${PRECHECK_STRICT:-0}" = "1" ]; then
        echo "  ОШИБКА: нет бинарников в $BIN_DIR — сторож не может судить." >&2
        exit 1
    fi
    echo "  ПРОПУСК: нет бинарников в $BIN_DIR (соберите taktc и takt-sim)."
    exit 0
fi

# --- 1. Годная проба: тревоги нет -------------------------------------------
cat > "$TMP/good.takt" <<'TAKT'
var n: u8 := 0;
start Run {
    always { n := n + 1; }
    ref Run: n < 2;
}
TAKT
OUT="$("$PROBE" -n 1 "$TMP/good.takt" 2>&1)"
if printf '%s' "$OUT" | grep -q 'проба негодна'; then
    fail "ложная тревога на годной пробе: $OUT"
else
    ok "годная проба принимается"
fi
printf '%s' "$OUT" | grep -q 'ЭТАЛОН' && printf '%s' "$OUT" | grep -q 'ЦЕЛИ' \
    && ok "замер содержит и эталон, и цели" \
    || fail "в выводе нет разделов эталона или целей"

# --- 2. Ловушка: объявлено, но не используется ------------------------------
# Тот же класс: штатный фильтр выбрасывает такое объявление из вывода
# целей, и замер показывает "расхождения нет" там, где оно есть.
cat > "$TMP/unused.takt" <<'TAKT'
var idle: u8 := 0;
var n: u8 := 0;
start Run {
    always { n := n + 1; }
    ref Run: n < 2;
}
TAKT
OUT="$("$PROBE" -n 1 "$TMP/unused.takt" 2>&1)"
if printf '%s' "$OUT" | grep -q 'idle' && printf '%s' "$OUT" | grep -q 'проба негодна'; then
    ok "ловится: объявлено, но не используется"
else
    fail "неиспользуемое объявление НЕ поймано: $OUT"
fi

# --- 3. Ловушка: имя файла сталкивается с объявленным именем ----------------
# корневая модель берёт имя из имени файла, и в выводе появляется
# посторонняя коллизия, к предмету замера отношения не имеющая.
cat > "$TMP/pt.takt" <<'TAKT'
struct Pt { a: u8, b: u8 }
var p: Pt;
var n: u8 := 0;
start Run {
    always { n := n + 1; p := p; }
    ref Run: n < 2;
}
TAKT
OUT="$("$PROBE" -n 1 "$TMP/pt.takt" 2>&1)"
if printf '%s' "$OUT" | grep -q "имя файла 'pt' совпадает"; then
    ok "ловится: имя файла сталкивается с именем ТИПА"
else
    fail "коллизия имени файла НЕ поймана: $OUT"
fi

# --- 3а. Контроль: `model` с именем файла - Идиома, не ловушка ---------------
# `model Regulator` в `regulator.takt` - так написан почти каждый пример
# корпуса, и цель `c` такой вход принимает. Проверка, объявляющая
# негодной каждую вторую пробу; тест, кричащий всегда,
# замолкает навсегда.
cat > "$TMP/gate.takt" <<'TAKT'
model Gate {
    var n: u8 := 0;
    start Run {
        always { n := n + 1; }
        ref Run: n < 2;
    }
}
start Main = Gate;
TAKT
OUT="$("$PROBE" -n 1 "$TMP/gate.takt" 2>&1)"
if printf '%s' "$OUT" | grep -q 'проба негодна'; then
    fail "ложная тревога на идиоме «model с именем файла»: $OUT"
else
    ok "идиома «model с именем файла» тревоги не даёт"
fi

# --- 3б. Объявленный тип без коллизии: скрипт доходит до конца ---------------
# под `set -eu` тело цикла проверки 1б кончалось формой
# `[ ... ] && printf`, и при отсутствии совпадения статус 1 ронял весь скрипт -
# то есть замер не снимался ни на одной пробе с объявленным типом. Прежние
# входы теста этого не показывали: либо типов не было вовсе, либо совпадение
# было. Здесь проверяется отрицательная ветвь - и код возврата, и вывод.
cat > "$TMP/kinds.takt" <<'TAKT'
enum Command { Stop = 0, Go = 1 }
var c: Command := Stop;
var seen: u8 := 0;
start Run {
    always { c := Go; }
    ref Done: c = 1;
}
state Done { always { seen := 1; } }
TAKT
if OUT="$("$PROBE" -n 1 "$TMP/kinds.takt" 2>&1)"; then
    if printf '%s' "$OUT" | grep -q 'ЦЕЛИ'; then
        ok "проба с объявленным типом доходит до замера"
    else
        fail "замер не снят, хотя код возврата нулевой: $OUT"
    fi
else
    fail "скрипт упал на пробе с объявленным типом (фикс 0301-02): $OUT"
fi

# --- 4. Общий отказ отделён от отказа цели ----------------------------------
# `SE-052` приходит раньше цели, и её поведение не измерено - но
# выглядит как "цель эту форму отвергает".
cat > "$TMP/common.takt" <<'TAKT'
var n: u8 := 0;
start Run {
    always { n := n + 1; }
    ref Done: nosuchname;
}
state Done;
TAKT
OUT="$("$PROBE" -n 1 "$TMP/common.takt" 2>&1)"
if printf '%s' "$OUT" | grep -q 'ОБЩИЙ — поведение цели НЕ измерено'; then
    ok "общий отказ отделён от отказа цели"
else
    fail "общий отказ не отделён: $OUT"
fi

# --- 5. Отказ цели отмечается иначе -----------------------------------------
# Без этого различения пункт 4 был бы "всё называть общим".
cat > "$TMP/target.takt" <<'TAKT'
var v: float := 0.5;
var n: u8 := 0;
start Run {
    always { n := n + 1; v := v + 0.5; }
    ref Run: n < 2;
}
TAKT
OUT="$("$PROBE" -n 1 "$TMP/target.takt" 2>&1)"
if printf '%s' "$OUT" | grep -q '(отказ цели)'; then
    ok "отказ цели отмечен как отказ цели"
else
    fail "отказ цели не отличается от общего: $OUT"
fi

# --- 6. Каталог бинарников - один носитель ----------------------------------
# Знание о каталоге сборки живёт в target-dir.sh; копия в скрипте разошлась бы
# с конфигом ровно так, как это случилось с run_simulations.sh.
# Комментарии из поиска исключены: объяснение о прежнем пути
# target/debug - свидетельство, а не копия знания. Поиск по ним
# этого не различала и падала на собственном объяснении.
for s in "$ROOT/scripts/probe.sh" "$ROOT/scripts/run_simulations.sh"; do
    if grep -vE '^[[:space:]]*#' "$s" | grep -qE 'target/debug'; then
        fail "$(basename "$s") несёт свою копию пути к бинарникам"
    else
        ok "$(basename "$s") берёт каталог у target-dir.sh"
    fi
done

# --- 7. Раздел инструментов целей есть, и годный вывод тревоги не даёт -------
# нулевой код возврата `taktc` не означает валидного вывода -
# порождённый файл принимает или отвергает чужой инструмент. Класс находили
# вручную одиннадцать фич подряд; здесь проверяется, что замер его показывает.
OUT="$("$PROBE" -n 1 "$TMP/good.takt" 2>&1)"
if printf '%s' "$OUT" | grep -q 'ИНСТРУМЕНТЫ ЦЕЛЕЙ'; then
    ok "раздел инструментов целей печатается"
else
    fail "раздела инструментов целей нет: $OUT"
fi
# Контроль: на годном выводе ни один инструмент не ругается. Без него проверка
# 8 доказывала бы лишь, что скрипт умеет печатать слово "отверг".
if printf '%s' "$OUT" | sed -n '/ИНСТРУМЕНТЫ ЦЕЛЕЙ/,$p' | grep -qE 'ОТВЕРГ|НЕ СОБРАЛ|НЕ СИНТЕЗ'; then
    fail "ложная тревога инструмента на годной пробе: $OUT"
else
    ok "годный вывод тревоги инструментов не даёт"
fi

# --- 8. Отказ инструмента виден --------------------------------------------
# Проверяется механизм, а не живой дефект языка: заглушка `cc`, отвергающая
# любой вход, устойчива к правке целей, тогда как вход-дефект протух бы первой
# же фичей, которая его закроет.
mkdir -p "$TMP/fakebin"
cat > "$TMP/fakebin/cc" <<'SH'
#!/bin/sh
echo "fake cc: отвергаю всё" >&2
exit 1
SH
chmod +x "$TMP/fakebin/cc"
OUT="$(PATH="$TMP/fakebin:$PATH" "$PROBE" -n 1 "$TMP/good.takt" 2>&1)"
if printf '%s' "$OUT" | grep -q 'cc ОТВЕРГ'; then
    ok "отказ инструмента цели показан"
else
    fail "отказ инструмента НЕ показан: $OUT"
fi

# --- 9. Отсутствие инструмента - "пропуск", а не "принял" -------------------
# Молчание при отсутствующем арбитре повторило бы ровно тот класс, ради
# которого раздел заведён (`iec2c`, `verilator`, `yosys` внешние).
OUT="$(IEC2C_PREFIX="$TMP/nosuchprefix" "$PROBE" -n 1 "$TMP/good.takt" 2>&1)"
if printf '%s' "$OUT" | grep -q 'пропуск: нет iec2c'; then
    ok "отсутствие инструмента названо пропуском"
else
    fail "отсутствие iec2c не отмечено пропуском: $OUT"
fi
if printf '%s' "$OUT" | sed -n '/ИНСТРУМЕНТЫ ЦЕЛЕЙ/,$p' | grep -qE '^  st +iec2c принял'; then
    fail "отсутствующий iec2c выглядит как «принял»: $OUT"
else
    ok "пропуск не выдаётся за успех"
fi

# --- 10. Строгость не теряется ----------------------------------------------
# Мягче проверки - замер объявит годным вывод, который предкоммит отвергнет.
# Проверяются флаги, а не совпадение строк: команды проверок несут обвязку
# (корпус, списки, стабы, тестбенчи, cmake), и дословного равенства быть не
# может.
for flag in '-Wall' '-Wextra' '-Werror' '-D warnings' '--lint-only'; do
    if grep -qF -- "$flag" "$PROBE"; then
        ok "проба несёт флаг строгости $flag"
    else
        fail "в probe.sh нет флага строгости $flag — замер мягче гейта"
    fi
done

# --- 11. Цель без вывода инструмента не получает ----------------------------
# `taktc` отказал - проверять нечего; строка обязана называть код отказа, а не
# молчать (иначе отказ цели неотличим от принятого вывода).
cat > "$TMP/refused.takt" <<'TAKT'
var v: float := 0.5;
var n: u8 := 0;
start Run {
    always { n := n + 1; v := v + 0.5; }
    ref Run: n < 2;
}
TAKT
OUT="$("$PROBE" -n 1 "$TMP/refused.takt" 2>&1)"
if printf '%s' "$OUT" | sed -n '/ИНСТРУМЕНТЫ ЦЕЛЕЙ/,$p' | grep -q 'вывода нет (taktc:'; then
    ok "цель без вывода названа, и назван код отказа"
else
    fail "цель без вывода не отмечена: $OUT"
fi

[ "$FAILED" -eq 0 ] || { echo "  Сторож инструмента снятия замера провален." >&2; exit 1; }
echo "  Сторож инструмента снятия замера пройден."
