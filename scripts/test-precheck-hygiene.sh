#!/usr/bin/env bash
# Тест гигиены каталога проверки.
#
# Проверяет три свойства, каждое из которых при нарушении стоит дорого:
# A1 на здоровом каталоге чистка не срабатывает - иначе каждый прогон платил
#       бы полную пересборку, и изоляция каталога теряла бы смысл;
# A2 при превышении порога каталог проверки удаляется, а сообщение называет
# путь, размер и порог - молчаливое удаление данных недопустимо;
# A3 путь, не оканчивающийся на `/target/precheck`, отвергается - ошибка в
#       вызове не имеет права превратиться в потерю рабочего каталога.
#
# Проверка A3 - не формальность: единственное отличие гигиены от аварии есть
# правильность одной переменной.
set -euo pipefail

SCRIPT="$(cd "$(dirname "$0")" && pwd)/precheck-hygiene.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
FAILED=0

ok()   { echo "  OK: $1"; }
fail() { echo "  ПРОВАЛ: $1" >&2; FAILED=1; }

# Каталог с N файлами в debug/deps: размер записи каталога растёт линейно
# (≈32 байта на запись), и именно его читает гигиена.
make_target() {
  local root="$1" count="$2" i
  mkdir -p "$root/debug/deps"
  for i in $(seq 1 "$count"); do : > "$root/debug/deps/artifact-$i.rlib"; done
}

# -- A1. Здоровый каталог не чистится -----------------------------------------
HEALTHY="$TMP/healthy/target/precheck"
make_target "$HEALTHY" 50
OUT="$("$SCRIPT" "$HEALTHY" 2>&1)"
if [ -d "$HEALTHY/debug/deps" ] && [ -z "$OUT" ]; then
  ok "A1 здоровый каталог не тронут, вывод пуст"
else
  fail "A1 здоровый каталог не должен ни чиститься, ни печатать: '$OUT'"
fi

# -- A2. Превышение порога: чистка + внятное сообщение ------------------------
DIRTY="$TMP/dirty/target/precheck"
make_target "$DIRTY" 50
# Порог задаётся переменной, поэтому тест не обязан создавать 130 тысяч файлов:
# сравнение идёт с размером записи каталога, а он у 50 файлов уже больше нуля.
OUT="$(PRECHECK_DEPS_LIMIT_MIB=0 "$SCRIPT" "$DIRTY" 2>&1)"
if [ ! -d "$DIRTY" ]; then
  ok "A2 каталог гейта удалён при превышении порога"
else
  fail "A2 каталог гейта обязан быть удалён при превышении порога"
fi
case "$OUT" in
  *"$DIRTY"*) ok "A2 сообщение называет путь" ;;
  *) fail "A2 сообщение обязано называть удаляемый путь: '$OUT'" ;;
esac
case "$OUT" in
  *"порога"*) ok "A2 сообщение называет порог" ;;
  *) fail "A2 сообщение обязано называть порог: '$OUT'" ;;
esac
case "$OUT" in
  *"Рабочий target НЕ трогается"*) ok "A2 сообщение отделяет каталог гейта от рабочего" ;;
  *) fail "A2 сообщение обязано сказать, что рабочий target не тронут: '$OUT'" ;;
esac

# -- A3. Чужой путь отвергается -----------------------------------------------
FOREIGN="$TMP/foreign/target"
make_target "$FOREIGN" 50
if PRECHECK_DEPS_LIMIT_MIB=0 "$SCRIPT" "$FOREIGN" >/dev/null 2>&1; then
  fail "A3 путь вне /target/precheck обязан отвергаться"
else
  if [ -d "$FOREIGN/debug/deps" ]; then
    ok "A3 чужой путь отвергнут, каталог цел"
  else
    fail "A3 чужой каталог УДАЛЁН — это авария, а не гигиена"
  fi
fi

# -- A4. Отсутствующий каталог - не ошибка ------------------------------------
if "$SCRIPT" "$TMP/nonexistent/target/precheck" >/dev/null 2>&1; then
  ok "A4 отсутствующий каталог гейта не валит скрипт (первый прогон)"
else
  fail "A4 отсутствующий каталог гейта не должен быть ошибкой"
fi

if [ "$FAILED" = "0" ]; then
  echo "test-precheck-hygiene: все проверки пройдены (A1–A4)."
else
  echo "test-precheck-hygiene: ЕСТЬ ПРОВАЛЫ." >&2
  exit 1
fi
