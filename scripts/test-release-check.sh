#!/bin/sh
# Тест релизного конвейера: проверяет все ветви решения и
# сборку тела релиза в
# temp-репозитории, не трогая рабочее дерево.
#
# Тест здесь не формальность, а единственная проверка, какая вообще
# возможна: сам workflow в проекте не исполняется (аккаунт заблокирован по
# биллингу, замер 2026-08-19), поэтому решение о релизе проверяется только так.
# Инструмент без теста неотличим от сломанного - урок.
#
# POSIX sh.
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CHECK="$ROOT/scripts/release-check.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

FAILED=0
ok()   { echo "  OK: $1"; }
fail() { echo "  ПРОВАЛ: $1" >&2; FAILED=1; }

echo "Сторож решателя релиза (фича 0302)..."

G="git -C $TMP -c user.email=t@t -c user.name=t -c commit.gpgsign=false -c init.defaultBranch=main"

set_version() {
    mkdir -p "$TMP/takt-lang/src"
    printf 'pub const LANGUAGE_VERSION: &str = "%s";\n' "$1" > "$TMP/takt-lang/src/version.rs"
}
commit() { $G add -A >/dev/null; $G commit -q -m "$1"; }
decide() { ( cd "$TMP" && "$CHECK" "$@" ); }

$G init -q .
set_version 0.9.0;  commit "версия 0.9.0"
set_version 0.9.1;  commit "патч 0.9.1"
set_version 0.10.0; commit "подъём 0.10.0"

# --- 1. Минорная поднялась - релиз ------------------------------------------
OUT="$(decide HEAD)"
if [ "$OUT" = "release 0.10.0" ]; then
    ok "подъём минорной → релиз с версией"
else
    fail "подъём не распознан: $OUT"
fi

# --- 2. Патч минорной не меняет - релиза нет --------------------------------
OUT="$(decide HEAD~1)"
case "$OUT" in
    skip*"не менялась"*) ok "патч релиза не выпускает" ;;
    *) fail "патч принят за релиз: $OUT" ;;
esac

# --- 3. Тег уже стоит - повтора нет (идемпотентность) -----------------------
# требует ставить тег на коммит подъёма; если это сделано вручную,
# автоматика обязана промолчать, а не падать и не выпускать второй релиз.
$G tag -a v0.10.0 -m "версия 0.10.0" HEAD
OUT="$(decide HEAD)"
case "$OUT" in
    skip*"уже существует"*) ok "существующий тег останавливает повтор" ;;
    *) fail "повторный релиз не остановлен: $OUT" ;;
esac
$G tag -d v0.10.0 >/dev/null

# --- 4. Понижение версии релизом не считается -------------------------------
# Откат - исправление истории; выпустить под него релиз значит закрепить ошибку.
set_version 0.9.0; commit "откат к 0.9.0"
OUT="$(decide HEAD)"
case "$OUT" in
    skip*"понижена"*) ok "понижение релиза не выпускает" ;;
    *) fail "понижение принято за релиз: $OUT" ;;
esac

# --- 5. Нет предыдущей ревизии - молчание, а не релиз -----------------------
# Мелкий клон (`fetch-depth: 1`) не даёт родителя; выпускать релиз "на ровном
# месте" при каждом таком прогоне нельзя.
FIRST="$($G rev-list --max-parents=0 HEAD)"
OUT="$(decide "$FIRST")"
case "$OUT" in
    skip*"сравнивать не с чем"*) ok "без предыдущей ревизии релиза нет" ;;
    *) fail "первый коммит принят за релиз: $OUT" ;;
esac

# --- 6. Нет файла версии - Ошибка, а не молчаливый пропуск ------------------
# Молчаливый пропуск здесь означал бы "релизы отключились", и заметить это
# было бы нечем.
if decide 0000000000000000000000000000000000000000 >/dev/null 2>&1; then
    fail "несуществующая ревизия принята молча"
else
    ok "нечитаемая ревизия — ошибка, а не пропуск"
fi

# --- 7. Решение печатается одной строкой ------------------------------------
# Вызывающий (workflow) читает stdout; многострочный ответ разобрать нечем.
LINES="$(decide HEAD | wc -l | tr -d ' ')"
[ "$LINES" = "1" ] && ok "решение — одна строка" || fail "строк в решении: $LINES"

# --- 8. Тело релиза собирается из истории и не разрастается в журнал --------
# Тело раздела `## [Не выпущено]` файла журнала здесь не годится:
# CHANGES.md, и проба дала 9765 строк: заголовок `## ` там один на весь файл.
NOTES="$ROOT/scripts/release-notes.sh"
set_version 0.11.0; commit "подъём 0.11.0"
BODY="$( cd "$TMP" && "$NOTES" 0.11.0 )"
if printf '%s' "$BODY" | grep -q '^## Версия языка 0.11.0'; then
    ok "тело релиза озаглавлено версией"
else
    fail "в теле нет заголовка версии: $BODY"
fi
if printf '%s' "$BODY" | grep -q 'подъём 0.11.0'; then
    ok "тело релиза перечисляет коммиты"
else
    fail "в теле нет коммитов: $BODY"
fi
BODY_LINES="$(printf '%s' "$BODY" | wc -l | tr -d ' ')"
if [ "$BODY_LINES" -lt 40 ]; then
    ok "тело релиза соразмерно ($BODY_LINES строк)"
else
    fail "тело релиза разрослось: $BODY_LINES строк"
fi

# --- 9. Предыдущий тег ищется по версии, а не лексикографически -------------
# `v0.9.0` лексикографически больше `v0.10.0`; без `sort -V` тело релиза
# считалось бы от неверной границы.
$G tag -a v0.9.0 -m "9" HEAD~2 >/dev/null 2>&1 || $G tag -a v0.9.0 -m "9" HEAD~1
$G tag -a v0.10.0 -m "10" HEAD~1
BODY="$( cd "$TMP" && "$NOTES" 0.11.0 )"
if printf '%s' "$BODY" | grep -q 'Изменения с v0.10.0'; then
    ok "предыдущий тег выбран по версии (v0.10.0, а не v0.9.0)"
else
    fail "предыдущий тег выбран неверно: $(printf '%s' "$BODY" | head -3)"
fi

[ "$FAILED" -eq 0 ] || { echo "  Сторож решателя релиза провален." >&2; exit 1; }
echo "  Сторож решателя релиза пройден."
