// gatelib.mjs - нижняя граница входа проверки на JavaScript.
//
// Третий двойник scripts/gatelib.py: проверка тождественности модуля написана
// на JavaScript, и без своего помощника у неё завёлся бы четвёртый способ
// отказа. Предмет и доводы описаны в gatelib.py; здесь только форма.
//
//     import { requireInput } from "./gatelib.mjs";
//     const note = requireInput("примеры корпуса", examples.length, 1, "examples/");
//
// Отказ печатается в stderr и завершает процесс кодом 1; при достаточном входе
// возвращается описание для строки успеха.

export function requireInput(name, size, minimum = 1, source = "") {
  if (minimum < 1) {
    throw new Error("граница входа не может быть меньше единицы");
  }
  if (size < minimum) {
    const place = source ? ` (${source})` : "";
    console.error(
      `ОШИБКА: вход «${name}» не достиг границы${place}: разобрано ${size} при границе ${minimum}.\n` +
        "Пустая выборка - не благополучие, а слепота: разбор ничего не нашёл, и\n" +
        "находкам взяться неоткуда, поэтому проверка ответила бы успехом, не прочитав\n" +
        "ни строки. Верните разметку либо обновите разбор вместе с нею - но не\n" +
        "оставляйте проверку без входа."
    );
    process.exit(1);
  }
  return `разобрано ${size} - ${name}`;
}
