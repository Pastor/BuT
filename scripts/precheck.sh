# ГЕЙТ ТЕСТБЕНЧЕЙ ЦЕЛИ SV: линт и синтез доказывают, что RTL валиден и
# синтезируем, но НЕ что он ведёт себя как модель (см. предупреждение README —
# молча неверная трансляция синтезируется тоже). Тестбенчи в
# examples/generated/sv/tb/ прогоняют модуль замкнутой средой на осмысленном
# сценарии, проверяют наблюдаемое поведение assert-ами (провал → $fatal →
# ненулевой код выхода) и снимают осциллограмму <name>.vcd для gtkwave.
#
# Тестбенчи написаны РУКАМИ (не порождаются taktc): тестбенч — принадлежность
# проверки, а не продукта (решение 0045-07). Список модулей — тот же
# $SV_TRANSLATABLE: у каждого обязан быть парный tb/<name>_tb.sv.
#
# Verilator собирает симулятор (--binary --timing) с трассировкой (--trace).
# Отдельного мягкого/жёсткого разбора отсутствия verilator здесь нет: гейт линта
# выше уже отметил его нехватку (пропуск локально, ошибка в CI). Если verilator
# есть — тестбенчи ОБЯЗАНЫ собраться и пройти.
SV_TB_DIR="$SV_OUTPUT/tb"
if command -v verilator &>/dev/null; then
  echo "Гейт тестбенчей sv: verilator (--binary) прогоняет tb/<name>_tb.sv..."
  for name in $SV_TRANSLATABLE; do
    tb_src="$SV_TB_DIR/${name}_tb.sv"
    if [ ! -e "$tb_src" ]; then
      echo "  $name → тестбенч $tb_src отсутствует (ожидался парный tb для \$SV_TRANSLATABLE)."
      sv_failed=1
      continue
    fi
    tb_obj="$(mktemp -d)"
    tb_log="$(mktemp)"
    if verilator --binary --timing --trace -Wno-fatal --top-module tb \
        -Mdir "$tb_obj" -o simtb \
        "$tb_src" "$SV_OUTPUT/${name}.sv" >"$tb_log" 2>&1; then
      # Прогон в каталоге tb/: <name>.vcd ложится рядом с исходником тестбенча
      # (путь в $dumpfile относительный). Код выхода ≠ 0 (провал assert/$fatal)
      # валит гейт.
      if ( cd "$SV_TB_DIR" && "$tb_obj/simtb" ) >"$tb_log" 2>&1; then
        sed 's/^/    /' "$tb_log" | grep -E 'OK|TICK' | head -4 || true
        echo "  $name → тестбенч ПРОШЁЛ; осциллограмма $SV_TB_DIR/${name}.vcd"
      else
        echo "  $name → тестбенч ПРОВАЛИЛСЯ:"
        sed 's/^/    /' "$tb_log" | head -12
        sv_failed=1
      fi
    else
      echo "  $name → verilator НЕ СОБРАЛ тестбенч:"
      sed 's/^/    /' "$tb_log" | head -12
      sv_failed=1
    fi
    rm -rf "$tb_obj" "$tb_log"
  done
fi

# ГЕЙТ ТЕСТБЕНЧА АДАПТЕРА ШИНЫ (фича 0169). Линт и синтез принимают обёртку,
# которая НЕ РАБОТАЕТ: цикл APB можно перепутать фазами, и оба инструмента
# промолчат (урок 0045). Тестбенч ведёт настоящие трансферы и сверяет значения.
SV_MMIO_TB_DIR="$SV_MMIO_OUTPUT/tb"
if command -v verilator &>/dev/null; then
  echo "Гейт тестбенчей sv-mmio: verilator (--binary) прогоняет tb/<name>_apb_tb.sv..."
  for name in $SV_MMIO_TRANSLATABLE; do
    tb_src="$SV_MMIO_TB_DIR/${name}_apb_tb.sv"
    if [ ! -e "$tb_src" ]; then
      echo "  $name → тестбенч $tb_src отсутствует (ожидался парный tb для адаптера)."
      sv_failed=1
      continue
    fi
    tb_obj="$(mktemp -d)"
    tb_log="$(mktemp)"
    if verilator --binary --timing --trace -Wno-fatal --top-module tb \
        -Mdir "$tb_obj" -o simtb \
        "$tb_src" "$SV_MMIO_OUTPUT/${name}_apb.sv" "$SV_MMIO_OUTPUT/${name}.sv" \
        >"$tb_log" 2>&1; then
      if ( cd "$SV_MMIO_TB_DIR" && "$tb_obj/simtb" ) >"$tb_log" 2>&1; then
        sed 's/^/    /' "$tb_log" | grep -E 'OK|TICK' | head -4 || true
        echo "  ${name}_apb → тестбенч ПРОШЁЛ; осциллограмма $SV_MMIO_TB_DIR/${name}_apb.vcd"
      else
        echo "  ${name}_apb → тестбенч ПРОВАЛИЛСЯ:"
        sed 's/^/    /' "$tb_log" | head -12
        sv_failed=1
      fi
    else
      echo "  ${name}_apb → verilator НЕ СОБРАЛ тестбенч:"
      sed 's/^/    /' "$tb_log" | head -12
      sv_failed=1
    fi
    rm -rf "$tb_obj" "$tb_log"
  done
fi

if [ "$sv_failed" -ne 0 ]; then
  echo "  Порождённый SystemVerilog не проходит гейт — предкоммит провален (фича 0045)."
  exit 1
fi

# Гейт цели `c` под -Wall -Werror (фича 0171). Прежде гейт собирал порождённый
# код БЕЗ единого флага предупреждений — и потому принял тождественно ложное
# `if (model->lv == -5)` при `uint8_t lv`: `cc` об этом ГОВОРИЛ, а гейт не
# слушал. Именно так дефект знака перечисления (фикс 0005-01, Tier 1) дожил
# незамеченным. Урок 0045 наоборот: там инструмент молчал, здесь — говорил впустую.
#
# Замер перед включением (правило карточки «прежде чем включать — прогнать»):
# корпус под `-Wall` даёт **0** предупреждений, то есть строгость бесплатна.
#
# `-Wextra` добавлен фичей 0220 — тогда с ЯВНЫМ исключением одного класса
# (`-Wno-unused-parameter`: корпус давал 49 предупреждений, гейт `c-hal` — 45).
# Фича 0260 исключение СНЯЛА: там, где тело параметром не пользуется, цель
# печатает `(void)параметр;` (`generator/c/c_params.rs`), и оба гейта дают ноль
# без единого `-Wno-`.
#
# ⚠️ Замер 0260 добавил к картине то, чего не видел отладочный гейт: под
# `-DNDEBUG` предупреждений было БОЛЬШЕ — 53, потому что `assert(0 != main);`
# исчезает, а прошивки собирают именно так. Признак «параметр использован»
# поэтому не доверяет `assert`.
#
# ⚠️ Флаги задаются ГЕЙТОМ, а не CMakeLists порождённого примера: `-Werror` в
# поставляемом файле навязал бы строгость всякому, кто скопирует
# `examples/generated/c` себе, — а это его выбор, не наш.
cmake -DCMAKE_BUILD_TYPE=Debug -G Ninja \
  -DCMAKE_C_FLAGS="-Wall -Wextra -Werror" \
  -S $C_OUTPUT -B $C_OUTPUT/cmake-build-debug/
cd $C_OUTPUT/cmake-build-debug/ && ninja
cd -

# Тот же корпус в РЕЛИЗНОМ режиме (фича 0312). Прошивки собирают именно так, а
# оба гейта цели `c` шли только в отладке — и разница была уже измерена:
# замер 0260 нашёл под `-DNDEBUG` 53 предупреждения против 49 без него, потому
# что `assert(0 != main);` в релизе исчезает. После 0260 разницы не стало, но
# её отсутствие никем не сторожилось.
#
# ⚠️ Первый же прогон этого шага нашёл ОТКАЗ: харнесс `batch_cycle_main.c`
# проверял порядок фаз `assert`-ами, и под `-DNDEBUG` он не только переставал
# проверять (правило «assert в неисполненном коде молчит всегда»), но и не
# компилировался — `-Wunused-but-set-variable` на счётчике `phases`. Харнесс
# переведён на проверку, работающую в любом режиме.
#
# ⚠️ Каталог сборки СВОЙ: общий с отладочным дал бы перекомпиляцию туда-сюда на
# каждом прогоне (кэш cmake хранит флаги).
echo "Гейт цели c: сборка корпуса в РЕЛИЗЕ (-DNDEBUG, фича 0312)..."
cmake -DCMAKE_BUILD_TYPE=Release -G Ninja \
  -DCMAKE_C_FLAGS="-Wall -Wextra -Werror -DNDEBUG" \
  -S $C_OUTPUT -B $C_OUTPUT/cmake-build-release/
cd $C_OUTPUT/cmake-build-release/ && ninja
cd -

# Харнессы ЗАПУСКАЮТСЯ в релизе, а не только собираются (урок 0166: `assert` в
# неисполненном коде молчит всегда — а в релизе он молчит и в исполненном).
for harness in batch_cycle stacker; do
  if [ -x "$C_OUTPUT/cmake-build-release/$harness" ]; then
    if "$C_OUTPUT/cmake-build-release/$harness" > /tmp/${harness}_release.log 2>&1; then
      echo "  $harness [релиз] → проверки пройдены"
    else
      echo "  $harness [релиз] → ПРОВАЛ:"
      sed 's/^/    /' /tmp/${harness}_release.log | head -8
      exit 1
    fi
  fi
done

# Гейт компиляции цели c-hal (фикс 0020-01 / фича 0098). Прежде c-hal НИГДЕ не
# компилировалась — только диффилась на детерминизм (её вывод сверяли сам с
# собой). Ровно эта дыра покрытия дала дожить UB в дефолтном HAL (сдвиг бита
# ≥ ширины типа). Теперь каждый пример генерируется в c-hal и компилируется в
# объект (`cc -c`); линковка не нужна — extern fn и main здесь ни при чём.
# Примеры без адресов портов (elevator_mini → SE-052) в c-hal не транслируются —
# это не отказ гейта, а отсутствие адресов; такие пропускаются.
if require_tool cc "гейт c-hal, фикс 0020-01; обычно есть на всех платформах"; then
  echo "Гейт c-hal: компиляция порождённого дефолтного HAL (фикс 0020-01)..."
  chal_failed=0
  for takt_file in examples/*.takt; do
    name="$(basename "$takt_file" .takt)"
    chal_dir="$(mktemp -d)"
    if ! "$TAKTC" compile "$takt_file" -t c-hal -o "$chal_dir" >"$chal_dir/gen.log" 2>&1; then
      echo "  $name [c-hal] → пропуск (не транслируется: $(head -1 "$chal_dir/gen.log" | cut -c1-40))"
      rm -rf "$chal_dir"
      continue
    fi
    ok=1
    for c in "$chal_dir"/*.c; do
      [ -e "$c" ] || continue
      # -Wall -Werror (фича 0171): порождённый HAL обязан собираться СТРОГО —
      # пользователь со своим `-Wall -Werror` иначе не соберёт наш код вовсе.
      # Замер: до фичи каждый пример давал `-Wunused-function` на
      # `<Root>_bind_default_hal` (объявлен в заголовке, зовётся не всякой
      # единицей трансляции); вылечено `static inline` в генераторе.
      #
      # `-Wextra` добавлен фичей 0220 ВМЕСТЕ с корпусом: политика двух гейтов
      # цели `c` одна, иначе класс, невидимый здесь, всплывал бы там.
      # Исключение `-Wno-unused-parameter` снято фичей 0260 — здесь оно гасило
      # 45 предупреждений, включая параметр `m` помощника `bind_default_hal`,
      # который живёт в ЗАГОЛОВКЕ и уезжал к пользователю.
      if ! cc -std=c11 -Wall -Wextra -Werror \
           -I "$chal_dir" -c "$c" -o /dev/null 2>"$chal_dir/cc.log"; then
        echo "  $name [c-hal] → НЕ КОМПИЛИРУЕТСЯ:"
        sed 's/^/    /' "$chal_dir/cc.log" | head -8
        ok=0
        chal_failed=1
      fi
