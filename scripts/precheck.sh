# единственный пример корпуса с `+` (extend_complex) целью sv не транслируется.
# Синтез на `+` прогонялся вручную - то есть регресс в этой ветви проверка не ловил.
SV_TRANSLATABLE="stacker elevator_mini regulator pid_regulator batch_cycle"

# Примеры для цели `sv-mmio`: порты с адресом -> регистровый файл на
# шине. `stacker` - его 17 адресов (`0x100`...`0x601`) суть готовая карта
# регистров, причём и на запись, и на чтение.
#
# `regulator` добавлен и покрывает второй состав портов: все они
# выходные, поэтому шине писать некуда и ядро не получает `reg_wdata`/`reg_wen`.
# Без такого примера класс был невидим - а `verilator --lint-only -Wall` на
# прежнем выводе давал два `UNUSEDSIGNAL` и ненулевой код возврата, то есть
# уронил бы проверка, попади туда любая модель без входных битов.
#
# Прочие sv-транслируемые примеры адресов не несут: под `sv-mmio` они дали бы
# обычный модуль без регистрового файла, то есть дубль проверки `sv`.
SV_MMIO_TRANSLATABLE="stacker regulator"

# Примеры на `float`, которым цель `sv` требует
# понижения float->q(m.n) флагом `--float-as-q`: нативного float в синтезируемом
# RTL нет, без флага - `SV-003`. float->q(8,8) байт-в-байт равно явному q
# поэтому committed `.sv` таких примеров не меняется от перевода
# исходника с q на float. Значение - точность q(m.n). Цели `c`/`rust`/`st` берут
# float нативно (double/f64/LREAL); встраиваемые `c-hal`/`st-at` - q через
# `--float-embedded` (отдельный проверка ниже).
FLOAT_AS_Q_EXAMPLES="pid_regulator"
FLOAT_AS_Q_PREC="8.8"

# Доп. флаги генерации `sv` для float-примера (пусто для остальных).
sv_float_flags() {  # $1 = имя примера
  case " $FLOAT_AS_Q_EXAMPLES " in
    *" $1 "*) printf -- '--float-as-q=%s' "$FLOAT_AS_Q_PREC" ;;
    *) : ;;
  esac
}

echo "Генерация C-кода из примеров Takt..."
for takt_file in examples/*.takt; do
  name="$(basename "$takt_file" .takt)"
  echo "  $takt_file → $C_OUTPUT/${name}.c / ${name}.h"
  $TAKTC compile "$takt_file" -o "$C_OUTPUT" || echo "    [предупреждение] ошибка генерации $takt_file"
  # Цель st. Отказ не валит предкоммит: генератор дописывается
  # и на непокрытом узле он закономерно
  # отвечает ST-011 - это замысел ("никакого тихого пропуска"), а не поломка.
  $TAKTC compile "$takt_file" -t st -o "$ST_OUTPUT" \
    || echo "    [предупреждение] цель st: $takt_file не транслируется (бэкенд не закончен)"
  # Цель rust. Отказ не валит предкоммит по той же причине, что и у
  # st: на непокрытом узле генератор закономерно отвечает RS-0xx - это замысел
  # ("никакого тихого пропуска"), а не поломка. Что именно не покрыто -
  # перечислено в README, раздел "Генерация Rust".
  $TAKTC compile "$takt_file" -t rust -o "$RUST_OUTPUT" \
    || echo "    [предупреждение] цель rust: $takt_file не транслируется (бэкенд не закончен)"
  # Цель sv. Отказ здесь не валит предкоммит, но и не остаётся
  # безнаказанным: список обязательных примеров проверяется ниже отдельно
  # ($SV_TRANSLATABLE) - иначе выпадение примера из проверки прошло бы молча.
  # float-примерам добавляется --float-as-q (иначе SV-003).
  # shellcheck disable=SC2046,SC2086
  $TAKTC compile "$takt_file" -t sv $(sv_float_flags "$name") -o "$SV_OUTPUT" \
    || echo "    [предупреждение] цель sv: $takt_file не транслируется"
done

# Цель sv-mmio: регистровый файл из адресов портов - только stacker
# (см. $SV_MMIO_TRANSLATABLE). Отказ не валит предкоммит здесь: обязательность
# проверяется проверкой ниже (как у sv).
# Адаптер шины APB порождается тем же прогоном: флаг `--bus=apb`
# добавляет рядом с ядром обёртку `<name>_apb.sv`, ядро при этом не меняется.
# Проверки ниже проверяют оба файла - и линтом с синтезом, и тестбенчем.
for name in $SV_MMIO_TRANSLATABLE; do
  $TAKTC compile "examples/${name}.takt" -t sv-mmio --bus=apb -o "$SV_MMIO_OUTPUT" \
    || echo "    [предупреждение] цель sv-mmio: examples/${name}.takt не транслируется"
done
echo "Готово. Файлы в $C_OUTPUT/"

# Проверка воспроизводимости: два прогона компилятора на одном входе
# обязаны давать байт-в-байт одинаковый вывод. Порядок эмиссии - свойство общего
# слоя (BTreeMap), а не привычка генератора; забытый источник недетерминизма не
# ломает сборку и не ловится юнит-тестом - он проявляется случайно, раз в
# несколько прогонов. Проверка жёсткий: внешних инструментов не требует (сравнение -
# diff -r), поэтому мягкого пропуска нет (в отличие от проверки ST).
#
# Сравниваются каталоги двух прогонов, а не сам факт генерации: если цель на
# каком-то примере не транслируется, оба прогона одинаково пусты -> это не
# недетерминизм. Цель `st` детерминирована уже сегодня - служит контрольной
# точкой правки общего слоя.
# Тем же обходом проверяется второе свойство, и оно зависит от того, объявляет ли
# пример параметры:
#
# - пример без параметров - `--parameters=specialize` обязан дать тот же вывод,
#     что умолчание (: на непараметризованном входе флаг не
#     наблюдаем);
# - пример С параметрами (`pid_law`, `pid_heater`) сравнивать с
#     умолчанием нельзя: специализация там **обязана** менять форму вывода. У него
# проверяется другое - **детерминизм самой специализации** (два прогона под
#     флагом байт-в-байт), потому что имена копий порождает компилятор, и именно
# они - риск недетерминизма.
#
# Прогоны встроены в этот обход, а не заведены отдельным циклом, ровно чтобы не
# появилось второй копии вычисления флагов цели (`sv_float_flags`) - о
# двух источниках истины. Предметы при этом различимы: у каждого сравнения своё
# сообщение.
echo "Гейт воспроизводимости: два прогона (+ режим specialize) на пример × цель..."
repro_failed=0
for takt_file in examples/*.takt; do
  name="$(basename "$takt_file" .takt)"
  for spec in "c:" "c-hal:-t c-hal" "st:-t st" "st-at:-t st-at" "rust:-t rust" "sv:-t sv" "sv-mmio:-t sv-mmio"; do
    tgt="${spec%%:*}"
    flag="${spec#*:}"
    # float-примерам цели sv/sv-mmio требуют --float-as-q - иначе оба
    # прогона пусты (SV-003) и детерминизм вывода не проверился бы вовсе.
    if [ "$tgt" = "sv" ] || [ "$tgt" = "sv-mmio" ]; then
      flag="$flag $(sv_float_flags "$name")"
    fi
    d1="$(mktemp -d)"
    d2="$(mktemp -d)"
    d3="$(mktemp -d)"
    d4="$(mktemp -d)"
    # shellcheck disable=SC2086
    $TAKTC compile "$takt_file" $flag -o "$d1" >/dev/null 2>&1 || true
    # shellcheck disable=SC2086
    $TAKTC compile "$takt_file" $flag -o "$d2" >/dev/null 2>&1 || true
    # shellcheck disable=SC2086
    $TAKTC compile "$takt_file" $flag --parameters=specialize -o "$d3" >/dev/null 2>&1 || true
    # Объявляет ли параметры сам пример либо файл, который он подключает:
    # параметры может объявлять библиотека, а форма вывода меняется у импортёра.
    # Проверяется именно этот пример, а не корпус целиком - иначе один
    # параметризованный файл снял бы проверку R7 со всех остальных.
    check_files="$takt_file"
    for imported in $(grep -oE 'from[[:space:]]+"[^"]+"' "$takt_file" 2>/dev/null \
                      | sed -E 's/from[[:space:]]+"([^"]+)"/\1/'); do
      [ -f "examples/$imported" ] && check_files="$check_files examples/$imported"
    done
    parameterized=0
    # shellcheck disable=SC2086
    if grep -qE '^[[:space:]]*parameter[[:space:]]' $check_files; then
      parameterized=1
    fi
    if [ "$parameterized" -eq 1 ]; then
      # shellcheck disable=SC2086
      $TAKTC compile "$takt_file" $flag --parameters=specialize -o "$d4" >/dev/null 2>&1 || true
    fi
    if ! diff -r "$d1" "$d2" >/dev/null 2>&1; then
      echo "  $name [$tgt] → НЕДЕТЕРМИНИЗМ (два прогона разошлись):"
      diff -r "$d1" "$d2" 2>&1 | sed 's/^/    /' | head -8
      repro_failed=1
    elif [ "$parameterized" -eq 1 ]; then
      if diff -r "$d3" "$d4" >/dev/null 2>&1; then
        echo "  $name [$tgt] → воспроизводим; специализация детерминирована"
      else
        echo "  $name [$tgt] → НЕДЕТЕРМИНИЗМ СПЕЦИАЛИЗАЦИИ (два прогона разошлись):"
        diff -r "$d3" "$d4" 2>&1 | sed 's/^/    /' | head -8
        repro_failed=1
      fi
    elif diff -r "$d1" "$d3" >/dev/null 2>&1; then
      echo "  $name [$tgt] → воспроизводим; режим specialize не наблюдаем"
    else
      echo "  $name [$tgt] → РЕЖИМ НАБЛЮДАЕМ (--parameters=specialize изменил вывод):"
      diff -r "$d1" "$d3" 2>&1 | sed 's/^/    /' | head -8
      repro_failed=1
    fi
    rm -rf "$d1" "$d2" "$d3" "$d4"
  done
done
if [ "$repro_failed" -ne 0 ]; then
  echo "  Генерация недетерминирована либо режим параметров наблюдаем на корпусе" \
       "— предкоммит провален (фичи 0048, 0185)."
  exit 1
fi

# Проверка представления FLOAT: пример на `float`
# на встраиваемом профиле без FPU (`c-hal`/`st-at`) обязан давать q через
# `--float-embedded --float-as-q` - "q там, где аппаратного float нет". Проверка
# проверяет, что понижение float->q собирается (не тихо теряется): q-путь у
# c-hal/st-at - то же ядро, что и явный q, и потактово сверен с симулятором в
# conformance_float_*_tests. Жёсткий: флаги и ядро прозрачного float - уже в репозитории.
echo "Гейт представления float: встраиваемые профили (c-hal/st-at) → q..."
float_embed_failed=0
for name in $FLOAT_AS_Q_EXAMPLES; do
  for etgt in c-hal st-at; do
    d="$(mktemp -d)"
    if $TAKTC compile "examples/${name}.takt" -t "$etgt" \
         --float-embedded --float-as-q="$FLOAT_AS_Q_PREC" -o "$d" >/dev/null 2>&1; then
      echo "  $name [$etgt] → q сформирован (--float-embedded --float-as-q=$FLOAT_AS_Q_PREC)"
    else
      echo "  $name [$etgt] → float→q НЕ собрался под --float-embedded"
      float_embed_failed=1
    fi
    rm -rf "$d"
  done
done
if [ "$float_embed_failed" -ne 0 ]; then
  echo "  float→q для встраиваемых профилей не собрался — предкоммит провален (фича 0096)."
  exit 1
fi

# Проверка цели RUST: порождённый.rs обязан приниматься
# rustc И clippy. Проверка жёсткий и мягкого пропуска не имеет: инструменты - уже
# зависимости проекта (это Rust-репозиторий), ставить нечего. Тем он и дешевле
# соседей: арбитр ST (`iec2c`) собирается из исходников, арбитр SV требует
# `brew install verilator yosys`.
#
# Почему обёртка, А не файл напрямую. Порождённый модуль не содержит `#![no_std]`:
# этот атрибут допустим только в корне крейта, и в файле, подключённом через
# `mod`, он даёт предупреждение "can only be used at the crate root" - то есть
# ломал бы сборку пользователя под -D warnings. Поэтому no_std-совместимость
# проверяется так, как модуль и будет использоваться: он кладётся в корень с
# `#![no_std]`. Это строже проверки файла в одиночку - обращение к std всплывёт
# именно здесь.
#
# Политика линтов (R9, решение варианта (а) ): `-D warnings`.
# Пробы 2026-07-16: калька с C проверка не проходит (`dead_code` на вариантах,
# которые C эмитит всегда, а модель не конструирует). Выбрано "не эмитить
# недостижимое", а не `#[allow]`: тест должен остаться живым. Приватность
# перечислений состояний - часть этого решения (у `pub enum` dead_code не
# срабатывает вовсе, то есть публичность = глушение линта видимостью).
echo "Гейт цели rust: rustc + clippy по порождённым .rs..."
rust_failed=0
rust_gate_dir="$(mktemp -d)"
for rs_file in "$RUST_OUTPUT"/*.rs; do
  [ -e "$rs_file" ] || continue
  name="$(basename "$rs_file" .rs)"
  # Пропусков нет: единственный, что здесь был (`comprehensive` -
  # clippy::absurd_extreme_comparisons на `temperature <= 0` при `u8`), снят
  # вместе с причиной. Пример больше не сравнивает беззнаковое с
  # нулём: порог выхода из охлаждения выражен именованным условием
  # `cond Cooled = temperature = 0`.
  wrapper="$rust_gate_dir/gate_${name}.rs"
  {
    echo "#![no_std]"
    echo "#[path = \"$(cd "$(dirname "$rs_file")" && pwd)/${name}.rs\"]"
    echo "pub mod generated;"
  } > "$wrapper"
  if rustc --edition 2021 --crate-type=lib -D warnings "$wrapper" \
      --out-dir "$rust_gate_dir/out" 2>"$rust_gate_dir/${name}.rustc"; then
    echo "  $name → rustc принял"
  else
    echo "  $name → rustc ОТВЕРГ:"
    sed 's/^/    /' "$rust_gate_dir/${name}.rustc" | head -12
    rust_failed=1
  fi
  if clippy-driver --edition 2021 --crate-type=lib -D warnings "$wrapper" \
      --out-dir "$rust_gate_dir/out" 2>"$rust_gate_dir/${name}.clippy"; then
    echo "  $name → clippy принял"
  else
    echo "  $name → clippy ОТВЕРГ:"
    sed 's/^/    /' "$rust_gate_dir/${name}.clippy" | head -12
    rust_failed=1
  fi
done
# A12/R10: unsafe в порождаемом коде отсутствует. Проверка дублирует
# `#![forbid(unsafe_code)]` в шапке модуля намеренно: атрибут ловит `unsafe` в
# коде, а grep - ещё и попытку убрать сам атрибут.
if grep -rn "unsafe" "$RUST_OUTPUT"/*.rs 2>/dev/null | grep -v "forbid(unsafe_code)" ; then
  echo "  В порождённом Rust найден unsafe — предкоммит провален (A12, фича 0050)."
  rust_failed=1
fi
rm -rf "$rust_gate_dir"
if [ "$rust_failed" -ne 0 ]; then
  echo "  Порождённый Rust не проходит гейт — предкоммит провален (фича 0050)."
  exit 1
fi

# Проверка исполнения цели RUST: порождённый автомат обязан не только компилироваться,
# но и работать. Аналог пары "cmake + ninja + запуск stacker" цели `c`.
#
# Проверка выше доказывает, что вывод принимают rustc и clippy, - то есть что он
# Синтаксически и типово верен. Молча неверную трансляцию (перепутанный
# приоритет, потерянный переход, не тот операнд) он не ловит: такой код
# компилируется. Поэтому каждый `main` в `examples/generated/rust/src/bin/`
# прогоняет свою модель на подставном железе и проверяет наблюдаемое поведение
# через `assert!` - падение `assert!` валит предкоммит.
#
# Крейт намеренно вне workspace репозитория (своя таблица `[workspace]`), потому
# и вызывается отдельным `--manifest-path`: его содержимое порождается `taktc`, и
# под `cargo check`/`clippy` корня попадать не должно. По той же причине здесь
# `build`, а не `clippy`: на `comprehensive.rs` clippy закономерно ругается
# (известный дефект примера, - см. пропуск в проверке выше), а `rustc`
# этот пример принимает.
echo "Гейт исполнения цели rust: сборка Cargo и прогон проверок по моделям..."
RUST_MANIFEST="$RUST_OUTPUT/Cargo.toml"
$CARGO_CMD build --quiet --manifest-path "$RUST_MANIFEST" --bins
for bin_src in "$RUST_OUTPUT"/src/bin/*.rs; do
  [ -e "$bin_src" ] || continue
  bin="$(basename "$bin_src" .rs)"
  $CARGO_CMD run --quiet --manifest-path "$RUST_MANIFEST" --bin "$bin" | sed 's/^/  /'
done

# Проверка цели SV: порождённый.sv обязан приниматься
# Verilator (линт) И yosys (синтез). Два инструмента - не осторожность, а вывод
# из проб 2026-07-15: они ловят непересекающиеся классы дефектов, причём ровно
# те два, что критичны для решений.
#
# | проба | verilator --lint-only -Wall | yosys synth |
#   |----------------------|-----------------------------|----------------------|
# | целевой модуль | чисто, код 0 | 22 ячейки, код 0 |
# | `real` в always_ff | принял молча, код 0 | ERROR TOK_REAL, код 1|
# | комбинационная петля | UNOPTFLAT, код 1 | синтезировал, код 0 |
#
# То есть расхожее "--lint-only даёт проверку синтеза" неверно: Verilator - линтер
# и симулятор, для него `real` легален, и с одним лишь Verilator решение
# "Rational -> SV-003" осталось бы недоказанным. Обратно: центральный риск
# отображения `M1 | M2` - комбинационная петля - синтезатором не ловится вовсе.
# Убрать любой из двух = ослепить проверка на целый класс дефектов.
#
# Мягкая деградация (образец - `cc_available()` в conformance_c_tests.rs):
# инструмента нет -> шаг пропускается с явным сообщением. Verilator и yosys для
# сборки и тестов `taktc` не нужны (ставятся `brew install verilator yosys`), и
# машина разработчика вправе быть без них.
#
# В CI мягкость недопустима: пропущенный проверка зелёный, то есть неотличим от
# пройденного, - и фича осталась бы без арбитра, сама себя объявив проверенной.
# Поэтому CI выставляет SV_GATE_REQUIRED=1, и тогда отсутствие инструмента -
# Ошибка, а не пропуск.
#
# `lint_off` в порождённом коде не применяется: если вывод требует глушения
# предупреждения - это дефект генератора, а не повод глушить.
echo "Гейт цели sv: verilator (линт) + yosys (синтез) по порождённым .sv..."
sv_failed=0
# SV_GATE_REQUIRED уже установлен вверху скрипта (наследует PRECHECK_STRICT,
# ); здесь лишь используется.

# Отсутствие инструмента: пропуск локально, ошибка в CI (SV_GATE_REQUIRED=1).
sv_tool_missing() {
  if [ "$SV_GATE_REQUIRED" = "1" ]; then
    echo "  $1 не найден, а SV_GATE_REQUIRED=1 — гейт sv обязателен. Провал."
    sv_failed=1
  else
    echo "  [пропуск] $1 не найден — гейт пропущен (brew install $1)"
  fi
}

# Сперва - обязательный список. Пример, переставший транслироваться, обязан
# ронять предкоммит громко, а не тихо исчезать из прогона проверки ниже.
for name in $SV_TRANSLATABLE; do
