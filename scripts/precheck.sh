      # пропустит. Замер 0260: разница между режимами уже была (53 против 49).
      if ! cc -std=c11 -Wall -Wextra -Werror -DNDEBUG \
           -I "$chal_dir" -c "$c" -o /dev/null 2>"$chal_dir/cc-release.log"; then
