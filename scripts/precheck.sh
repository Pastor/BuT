# Проверка примеров документа book/
#
# (д) свода требует проверять пример раздела компиляцией И симуляцией,
# но машины под этим требованием не было: слова `book` не встречалось ни в
# предкоммите, ни в CI. Цена бездоказательности известна поимённо - seed-пример
# `01-overview/examples/blinker.takt` не компилировался вовсе (форма `start state`
# и отсутствие верхнеуровневого входа), и это доживает до аудита, потому что
# примеры включаются в PDF, а PDF локально не собирают.
#
# Что проверяется:
# 1) каждый самостоятельный пример компилируется (цель `c` - самая строгая по
#      покрытию конструкций из дешёвых);
# 2) он же отрабатывает N тактов в симуляторе без ошибки вычисления - ловит
# класс "компилируется, но падает на первом такте" (SIM-0xx).
#
# Библиотечные примеры (те, что импортируются другими) standalone не
# компилируются по построению: у них нет верхнеуровневого входа. Они и не
# проверяются отдельно - их проверяет импортёр. Признак выводится автоматически
# (грепом по `from "<имя>"`), а не списком-исключений: список пришлось бы
# сопровождать руками, и он бы протух.
BOOK_TICKS=10
if [ -d book/src ]; then
  echo "Гейт примеров book/: компиляция и симуляция (правило 27д, фича 0133)..."
  book_failed=0
  book_ok=0
  book_lib=0
  for takt_file in $(find book/src -name '*.takt' | sort); do
    base="$(basename "$takt_file")"
    # Импортируется ли этот файл другим примером книги?
    if grep -rql "from \"$base\"" book/src --include='*.takt' 2>/dev/null; then
      echo "  $base → библиотечный (импортируется), проверяется импортёром"
      book_lib=$((book_lib + 1))
      continue
    fi
    out_dir="$(mktemp -d)"
    # Контракт частоты: модель с объявлением `clock` требует
    # совпадающий `--tick-hz`, иначе компиляция целью `c` даёт SE-069. Проверка
    # извлекает объявленную частоту и передаёт её явно (и печатает, что передал),
    # чтобы проверка примеров не зависела от угадывания частоты.
    tick_flag=""
    # `|| true`: под `set -euo pipefail` grep без совпадения (файл без `clock`)
    # вернул бы 1 и оборвал предкоммит - здесь отсутствие совпадения штатно.
    clock_lit="$(grep -oE 'clock[[:space:]]+[0-9]+[kMG]?Hz' "$takt_file" | head -1 | sed -E 's/clock[[:space:]]+//' || true)"
    if [ -n "$clock_lit" ]; then
      clock_num="$(printf '%s' "$clock_lit" | sed -E 's/([0-9]+).*/\1/')"
      case "$clock_lit" in
        *kHz) clock_hz=$((clock_num * 1000)) ;;
        *MHz) clock_hz=$((clock_num * 1000000)) ;;
        *GHz) clock_hz=$((clock_num * 1000000000)) ;;
        *) clock_hz=$clock_num ;;
      esac
      tick_flag="--tick-hz=$clock_hz"
      echo "  $base → объявляет $clock_lit, передаю $tick_flag"
    fi
    if ! "$TAKTC" compile "$takt_file" -t c $tick_flag -o "$out_dir" >"$out_dir/gen.log" 2>&1; then
      echo "  $base → НЕ КОМПИЛИРУЕТСЯ:"
      sed 's/^/    /' "$out_dir/gen.log" | head -3
      book_failed=1
      rm -rf "$out_dir"
      continue
    fi
    if ! "$TAKT_SIM" -n "$BOOK_TICKS" "$takt_file" >"$out_dir/sim.log" 2>&1; then
      echo "  $base → СИМУЛЯЦИЯ ОТКАЗАЛА:"
      sed 's/^/    /' "$out_dir/sim.log" | tail -3
      book_failed=1
      rm -rf "$out_dir"
      continue
    fi
    echo "  $base → компилируется и симулируется"
    book_ok=$((book_ok + 1))
    rm -rf "$out_dir"
  done
  echo "  Примеров book/: $book_ok проверено, $book_lib библиотечных."
  if [ "$book_failed" -ne 0 ]; then
    echo "  Пример документа не проходит проверку — предкоммит провален (правило 27д)."
    exit 1
  fi
fi

