# Проверка цели `c` под -Wall -Werror. Собирая порождённый код без флагов,
# код без единого флага предупреждений - и потому принял тождественно ложное
# `if (model->lv == -5)` при `uint8_t lv`: `cc` об этом говорил, а проверка не
# проверка молчит. Именно так дефект знака перечисления и живёт долго
# незамеченным. наоборот: там инструмент молчал, здесь - говорил впустую.
#
# Замер перед включением (правило карточки "прежде чем включать - прогнать"):
# корпус под `-Wall` даёт **0** предупреждений, то есть строгость бесплатна.
#
# `-Wextra` добавлен - тогда с явным исключением одного класса
# (`-Wno-unused-parameter`: корпус давал 49 предупреждений, проверка `c-hal` - 45).
# исключение сняла: там, где тело параметром не пользуется, цель
# печатает `(void)параметр;` (`generator/c/c_params.rs`), и оба проверки дают ноль
# без единого `-Wno-`.
#
# Замер добавил к картине то, чего не видит отладочная сборка: под
# `-DNDEBUG` предупреждений было больше - 53, потому что `assert(0 != main);`
# исчезает, а прошивки собирают именно так. Признак "параметр использован"
# поэтому не доверяет `assert`.
#
# Флаги задаются Проверкой, а не CMakeLists порождённого примера: `-Werror` в
# поставляемом файле навязал бы строгость всякому, кто скопирует
# `examples/generated/c` себе, - а это его выбор, не наш.
cmake -DCMAKE_BUILD_TYPE=Debug -G Ninja \
  -DCMAKE_C_FLAGS="-Wall -Wextra -Werror" \
  -S $C_OUTPUT -B $C_OUTPUT/cmake-build-debug/
cd $C_OUTPUT/cmake-build-debug/ && ninja
cd -

# Тот же корпус в релизном режиме. Прошивки собирают именно так, а
# оба проверки цели `c` шли только в отладке - и разница была уже измерена:
# замер нашёл под `-DNDEBUG` 53 предупреждения против 49 без него, потому
# что `assert(0 != main);` в релизе исчезает. Сейчас разницы нет, но
# её отсутствие никем не проверялось.
#
# Первый же прогон этого шага нашёл отказ: харнесс `batch_cycle_main.c`
# проверял порядок фаз `assert`-ами, и под `-DNDEBUG` он не только переставал
# проверять (правило "assert в неисполненном коде молчит всегда"), но и не
# компилировался - `-Wunused-but-set-variable` на счётчике `phases`. Харнесс
# переведён на проверку, работающую в любом режиме.
#
# Каталог сборки свой: общий с отладочным дал бы перекомпиляцию туда-сюда на
# каждом прогоне (кэш cmake хранит флаги).
echo "Гейт цели c: сборка корпуса в РЕЛИЗЕ (-DNDEBUG, фича 0312)..."
cmake -DCMAKE_BUILD_TYPE=Release -G Ninja \
