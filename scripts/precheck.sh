#!/usr/bin/env bash
# Предкоммит-проверка: ссылки в Markdown + fmt + check + clippy + test +
# формат примеров (taktc fmt --check) +
# генерация C/ST/Rust/SV из примеров Takt + проверка воспроизводимости
# + сборка сгенерированного кода (C - cmake/ninja, Rust - cargo +
# прогон проверок по моделям, SV - verilator + yosys).
# Запускать из любого каталога.
set -euo pipefail

if command -v rtk &>/dev/null; then
  CARGO_CMD="rtk cargo"
else
  CARGO_CMD="cargo"
fi

# Каталог сборки Проверки. Предкоммит собирает в свой каталог, а не в
# общий `target`, потому что состояние каталога обязано быть свойством проверки, а
# не дисциплиной автора: замер 2026-08-15 показал, что накопленный за месяцы
# рабочий каталог (83 гб, 599 435 файлов в `debug/deps`) превращает 83-секундную
# сборку в сутки - один обход такого каталога стоит 67 с, а cargo обходит его
# перед каждой единицей компиляции.
#
# Каталог лежит внутри `target/`: он уже в `.gitignore` (артефакты проверки не
# попадут в коммит случайно), а `cargo clean` автора сносит его заодно - и это
# желаемое, чистка проверки лишней не бывает. Рабочий `target` и кэш rust-analyzer
# не задеты: инкрементальность разработки сохраняется.
REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PRECHECK_TARGET_DIR="${PRECHECK_TARGET_DIR:-$REPO_ROOT/target/precheck}"
export CARGO_TARGET_DIR="$PRECHECK_TARGET_DIR"

# Параллельная сборка порождённого C++. `verilator --binary` внутри
# запускает `make`, и по умолчанию тот идёт В один поток - а это главная статья
# времени сверок SystemVerilog: замер 2026-08-17 дал 85 % тестового времени в
# шести наборах из 29 тестов (711.9 / 368.2 / 331.7 / 316.2 / 249.2 / 233.2 с),
# тогда как 1093 юнит-теста укладываются в 49.9 с.
#
# Задаётся переменной окружения, а не флагом `-j` в девяти местах: вызовы
# `verilator` живут в шести файлах сверок и двух проверках ниже, и девять правок
# разъехались бы. Переменная наследуется всеми потомками
# разом. Проба с флагом в тестах вдобавок растит модуль:
# `conformance_sv_tests.rs` - 999 строк из 1000.
export MAKEFLAGS="${MAKEFLAGS:--j$(sysctl -n hw.ncpu 2>/dev/null || nproc 2>/dev/null || echo 4)}"

# Гигиена: у cargo нет сборки мусора, поэтому каталог проверки деградировал бы так
# же. Порог аварийный, метрика дешёвая - подробности и замеры в самом скрипте.
"$(dirname "$0")/precheck-hygiene.sh" "$PRECHECK_TARGET_DIR"

# Холодный прогон - Не замер. Если каталога сборки нет (первый
# прогон, только что `cargo clean`), время этого прогона свойством сборки не
# является: прогон сразу после удаления 18.6 ГиБ дал 1633.8 с
# против 233.2 с в спокойных условиях, разница в 70 раз. Записывать такую цифру
# в карточку нельзя; для замера есть scripts/measure-precheck.sh (прогрев + два
# прогона + вердикт по разбросу).
if [ ! -d "$PRECHECK_TARGET_DIR" ]; then
  echo "⚠ Каталог сборки пуст — прогон ХОЛОДНЫЙ."
  echo "  Его время замером НЕ является (фича 0272): для числа в карточку"
  echo "  используйте scripts/measure-precheck.sh."
fi

# Строгий режим. В CI отсутствие любого инструмента проверки - Ошибка,
# а не мягкий пропуск: пропущенный проверка зелёный, то есть неотличим от пройденного
# . Локально (умолчание PRECHECK_STRICT=0) поведение прежнее: нет
# инструмента -> [пропуск], сборка не падает - машина разработчика вправе быть без
# verilator/iec2c. SV_GATE_REQUIRED теперь наследует общий флаг;
# явно заданное значение по-прежнему уважается (обратная совместимость).
PRECHECK_STRICT="${PRECHECK_STRICT:-0}"
export SV_GATE_REQUIRED="${SV_GATE_REQUIRED:-$PRECHECK_STRICT}"

# require_tool <бинарник> <назначение/как поставить>: единая точка мягкого
# пропуска. Под PRECHECK_STRICT=1 отсутствие инструмента валит скрипт; иначе -
# прежний [пропуск]. Код возврата (для `if require_tool ...; then <гейт>; fi`):
# 0 - инструмент есть, проверка выполнять; 1 - мягкий пропуск, проверка не выполнять.
require_tool() {
  command -v "$1" >/dev/null 2>&1 && return 0
  if [ "$PRECHECK_STRICT" = "1" ]; then
    echo "  ОШИБКА: $1 не найден, а PRECHECK_STRICT=1 — гейт обязателен ($2)." >&2
    exit 1
  fi
  echo "  [пропуск] $1 не найден — гейт пропущен ($2)"
  return 1
}

