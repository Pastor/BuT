# Проверка компиляции цели c-hal. Без неё c-hal нигде не
# компилировалась - только диффилась на детерминизм (её вывод сверяли сам с
# собой). Ровно эта дыра покрытия дала дожить UB в принятом по умолчанию HAL (сдвиг бита
# >= ширины типа). Теперь каждый пример генерируется в c-hal и компилируется в
# объект (`cc -c`); линковка не нужна - extern fn и main здесь ни при чём.
# Примеры без адресов портов (elevator_mini -> SE-052) в c-hal не транслируются -
# это не отказ проверки, а отсутствие адресов; такие пропускаются.
if require_tool cc "гейт c-hal, фикс 0020-01; обычно есть на всех платформах"; then
  echo "Гейт c-hal: компиляция порождённого дефолтного HAL (фикс 0020-01)..."
  chal_failed=0
  for takt_file in examples/*.takt; do
    name="$(basename "$takt_file" .takt)"
    chal_dir="$(mktemp -d)"
    if ! "$TAKTC" compile "$takt_file" -t c-hal -o "$chal_dir" >"$chal_dir/gen.log" 2>&1; then
      echo "  $name [c-hal] → пропуск (не транслируется: $(head -1 "$chal_dir/gen.log" | cut -c1-40))"
      rm -rf "$chal_dir"
      continue
    fi
    ok=1
    for c in "$chal_dir"/*.c; do
      [ -e "$c" ] || continue
      # -Wall -Werror: порождённый HAL обязан собираться строго -
      # пользователь со своим `-Wall -Werror` иначе не соберёт наш код вовсе.
      # Замер: до фичи каждый пример давал `-Wunused-function` на
      # `<Root>_bind_default_hal` (объявлен в заголовке, зовётся не всякой
      # единицей трансляции); вылечено `static inline` в генераторе.
      #
      # `-Wextra` добавлен вместе с корпусом: политика двух проверок
      # цели `c` одна, иначе класс, невидимый здесь, всплывал бы там.
      # Исключение `-Wno-unused-parameter` снято - здесь оно гасило
      # 45 предупреждений, включая параметр `m` помощника `bind_default_hal`,
      # который живёт в заголовке и уезжал к пользователю.
      if ! cc -std=c11 -Wall -Wextra -Werror \
           -I "$chal_dir" -c "$c" -o /dev/null 2>"$chal_dir/cc.log"; then
        echo "  $name [c-hal] → НЕ КОМПИЛИРУЕТСЯ:"
        sed 's/^/    /' "$chal_dir/cc.log" | head -8
        ok=0
        chal_failed=1
      fi
      # ...и в релизе: прошивки собирают с `-DNDEBUG`, а под ним
      # `assert` исчезает - класс, видимый только там, отладочный проверка
      # пропустит. Замер: разница между режимами уже была (53 против 49).
      if ! cc -std=c11 -Wall -Wextra -Werror -DNDEBUG \
           -I "$chal_dir" -c "$c" -o /dev/null 2>"$chal_dir/cc-release.log"; then
        echo "  $name [c-hal, релиз] → НЕ КОМПИЛИРУЕТСЯ:"
        sed 's/^/    /' "$chal_dir/cc-release.log" | head -8
        ok=0
        chal_failed=1
      fi
    done
    [ "$ok" -eq 1 ] && echo "  $name [c-hal] → компилируется"
    rm -rf "$chal_dir"
  done
  if [ "$chal_failed" -ne 0 ]; then
    echo "  Порождённый c-hal не компилируется — предкоммит провален (фикс 0020-01)."
    exit 1
  fi
fi

