//! Адрес экземпляра модели в дереве юнитов.
//!
//! # Предмет
//!
//! Одна модель бывает шагом композиции несколько раз
//! (`Middle = Engine + (Engine | Engine) + Engine`), и имя активного состояния не
//! говорит, какой из экземпляров его несёт. Адрес говорит: путь по владельцам
//! реализаций от корня до узла.
//!
//! # Форма
//!
//! Сегмент пути - состояние-владелец реализации, номер листа её выражения при обходе
//! слева направо (с единицы) и модель этого листа. Владелец - состояние с
//! реализацией; у модели, свёрнутой в композицию, - её единственное состояние (в том
//! числе то, в которое семантика разворачивает `model M = A + B { }`); у модели
//! без собственных состояний - имя самой модели. Корень адреса не имеет.
//!
//! Путь записывает построитель при спуске в лист выражения и хранит на узле, а не
//! выводит из формы дерева: слияние цепочек и параллелей расплющивает дерево, и шаг
//! из модели без собственных состояний после слияния неотличим от скобок.

use crate::unit::{Unit, UnitKind};

/// Сегмент адреса экземпляра: владелец реализации, номер листа и модель листа.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Segment {
    /// Состояние-владелец реализации (либо имя модели без собственных состояний).
    pub owner: String,
    /// Номер листа выражения реализации слева направо, с единицы.
    pub step: usize,
    /// Модель, стоящая этим листом, - её экземпляр и адресует путь до сегмента
    /// включительно.
    pub model: String,
}

/// Активное состояние такта вместе с адресом экземпляра, который его несёт.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ActiveState {
    /// Путь от корня до экземпляра; пустой - корневая модель.
    pub path: Vec<Segment>,
    /// Модель узла; у анонимной модели имени нет.
    pub model: Option<String>,
    /// Имя активного состояния.
    pub state: String,
    /// Узел терминален после такта: шаг цепочки, который он несёт, завершён.
    pub done: bool,
}

impl Unit {
    /// Активные состояния по дереву юнитов с адресами экземпляров.
    ///
    /// Порядок - порядок строки трассы: узел, затем его реализация; у параллели -
    /// все ветви; у цепочки - только идущий шаг. Имена состояний этого списка и
    /// есть [`Unit::active_states`]: второго обхода нет, и разойтись им нечем.
    pub fn active_instances(&self) -> Vec<ActiveState> {
        let mut out = Vec::new();
        collect(self, &mut out);
        out
    }
}

fn collect(unit: &Unit, out: &mut Vec<ActiveState>) {
    match unit.kind() {
        UnitKind::None => {}
        UnitKind::Node {
            state,
            state_impls,
            model_name,
            path,
            ..
        } => {
            if let Some(s) = state {
                out.push(ActiveState {
                    path: path.clone(),
                    model: model_name.clone(),
                    state: s.clone(),
                    done: unit.is_terminal(),
                });
                // Состояния внутри реализации - часть активной конфигурации автомата, а
                // не деталь: без них трасса `state P = A + B` показывала бы одно
                // неподвижное `P`, тогда как у формы `start P = A | B` (та же
                // композиция без переходов) сообщаются состояния ветвей. Две записи
                // одной конструкции обязаны наблюдаться одинаково.
                if let Some(inner) = state_impls.get(s) {
                    collect(&inner.borrow(), out);
                }
            }
        }
        UnitKind::Parallel { units, .. } => {
            for u in units {
                collect(&u.borrow(), out);
            }
        }
        UnitKind::Sequential { units, index, .. } => {
            if let Some(u) = units.get(*index) {
                collect(&u.borrow(), out);
            }
        }
    }
}

/// Владелец листов выражения при построении: путь до владельца и его имя.
///
/// Номер листа считает построитель, спускаясь в выражение слева направо; путь
/// экземпляра - путь владельца плюс сегмент листа.
pub(crate) struct Owner<'a> {
    pub(crate) prefix: &'a [Segment],
    pub(crate) name: &'a str,
}

impl Owner<'_> {
    /// Путь экземпляра, стоящего листом `step` этого владельца.
    pub(crate) fn leaf(&self, step: usize, model: &str) -> Vec<Segment> {
        let mut path = self.prefix.to_vec();
        path.push(Segment {
            owner: self.name.to_string(),
            step,
            model: model.to_string(),
        });
        path
    }
}
