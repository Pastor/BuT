//! Сверка **насыщения** `q(m, n) sat` с целью `c`.
//!
//! Вынесено подмодулем по той же причине, что и `fixed_width.rs`: родительский файл
//! упирается в лимит размера модуля. Помощники (`c_trace`, `simulate_trace`,
//! `cc_available`) берутся из родителя через `use super::*`.
//!
//! Проверка `cc` доказывает, что порождённый C **компилируется**, но не что он
//! **верен**: цель, которая печатает `q(m, n) sat` как обычный перенос,
//! компилируется ровно так же. Вердикт даёт только сверка значений - уроки
//! 0045/0050, подтверждённые исправлением.

use super::*;

/// Трасса представлений исправлениетуры насыщения.
///
/// Столбцы: `up` (прижатие сверху), `down` (прижатие снизу), `neg` (край
/// `−(−2^(W−1))`).
///
/// Копия этой таблицы стоит и в сверках `st`/`sv`: тестовые файлы -
/// **разные крейты**, общего модуля у них нет. Разъехаться молча копии не
/// могут: каждая сверяется с трассой одного и того же симулятора.
fn expected_sat_w12() -> Vec<Vec<i128>> {
    vec![
        vec![512, -512, 512],
        vec![1024, -1024, 1024],
        vec![1536, -1536, 1536],
        vec![2047, -2048, 2047],
        vec![2047, -2048, 2047],
        vec![2047, -2048, 2047],
    ]
}

/// A4/A5/A6 (цель C): насыщение прижимает к границам **формата** на обеих границах и на
/// крае унарного минуса - и совпадает с эталоном побитово.
///
/// Формат `q(6, 6)` намеренный: `W = 12`, хранение - 16 бит. Прижатие к ширине
/// **хранения** дало бы на такте 4 значение 2048 вместо 2047 - то самое расхождение,
/// которое `q(8, 8)` скрыл бы.
///
/// Такты 5-6 столь же обязательны, как такт 4: они доказывают, что значение на границе
/// **удерживается**, а не "перепрыгивает" через неё на следующем шаге.
#[test]
fn fixed_saturation_matches_generated_c() {
    let vars = ["up", "down", "neg"];
    let fixture = "tests/data/eval/conformance_fixed_sat_w12.takt";
    let sim = simulate_trace(fixture, &vars);
    assert_eq!(
        sim,
        expected_sat_w12(),
        "q(6,6) sat: прижатие к repr ∈ [−2048, 2047]; перенос дал бы на такте 4 \
         up = −2048 и neg = −2048"
    );

    if !cc_available() {
        eprintln!("[ПРОПУСК] fixed_saturation_matches_generated_c: `cc` не найден");
        return;
    }
    let dir: PathBuf = std::env::temp_dir()
        .join(format!("takt_pid{}", std::process::id()))
        .join("takt_conformance_fixed_sat_w12");
    std::fs::create_dir_all(&dir).expect("каталог сборки");
    let c = c_trace(
        &dir,
        fixture,
        "conformance_fixed_sat_w12",
        "ConformanceFixedSatW12",
        "entry",
        &vars,
    );
    assert_eq!(
        sim, c,
        "насыщение обязано совпасть с C на каждом такте.\nсимулятор={sim:?}\nC={c:?}"
    );
}
