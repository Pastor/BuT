//! Пиннинги потактовых трасс цели `c`.
//!
//! Значения названы один раз на набор: два списка одних и тех же чисел разошлись бы при
//! первой правке исправлениетуры, и половина сверки судила бы вчерашнее. Здесь же они не
//! мешают читать сами проверки.

/// Q-трасса: -3.0, -1.5, -2·2⁻⁸ (floor!), +2.0-ish - и дальше накопление продолжается:
/// состояние с телом автомат не завершает.
pub(super) fn q_trace() -> Vec<Vec<i128>> {
    [-768, -384, -2, 510, 1022, 1534]
        .into_iter()
        .map(|v| vec![v])
        .collect()
}

/// Пиннинг переноса `+` над q: значение растёт по единице представления - состояние с
/// телом автомат не завершает.
pub(super) fn wrap_trace() -> Vec<Vec<i128>> {
    (-32768..=-32763).map(|v| vec![v]).collect()
}

/// Пиннинг: `n` растёт 1 -> 2 -> 3 и держится - состояние `S2` имеет тело и потому
/// автомат не завершает.
pub(super) fn held_trace() -> Vec<Vec<i128>> {
    vec![vec![1], vec![2], vec![3], vec![3], vec![3], vec![3]]
}
