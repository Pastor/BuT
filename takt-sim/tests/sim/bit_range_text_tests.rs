//! Текст `SIM-011` называет **разряды значения**, а не ширину слова.
//!
//! # Граница
//!
//! У `Value::Number` объявленного типа нет: `[bit;8]` от `u64` в момент отказа
//! неотличим, и названные 64 - правда о **носителе**. Догадываться нельзя, поэтому
//! сообщение говорит о значении, а не об объявлении.
//!
//! Тесты сквозные - гоняют бинарник: проверяется ровно тот текст, который увидит
//! пользователь (образец `diagnostics_tests`).

use std::process::Command;

const DIR: &str = "tests/data/bitrange";

/// Запускает симулятор на фикстуре; `ok` - ожидается ли успех.
fn run(fixture: &str, ok: bool) -> String {
    let out = Command::new(env!("CARGO_BIN_EXE_takt-sim"))
        .args([&format!("{DIR}/{fixture}"), "--steps", "2"])
        .output()
        .expect("запуск симулятора");
    assert_eq!(
        out.status.success(),
        ok,
        "{fixture}: ожидался {}",
        if ok { "успех" } else { "отказ" }
    );
    String::from_utf8_lossy(if ok { &out.stdout } else { &out.stderr }).into_owned()
}

/// Предмет: разряд за шириной многословного вектора называет её саму.
///
/// Отвечает семантика (`SE-125`), а не прогон: объявленная
/// ширина здесь известна. Прежде разряд брался у результата вызова - тип не
/// выводился, и вход доходил до такта, где `SIM-011` называл ширину
/// **носителя**; с результат вызова поднимается во временную, и эта
/// ветвь для многословного значения стала недостижимой. У скаляра она
/// достижима по-прежнему - соседний тест.
#[test]
fn wide_vector_names_its_own_width() {
    let err = run("wide_vector.takt", false);
    assert!(err.contains("SE-125"), "{err}");
    assert!(
        err.contains("96"),
        "текст обязан назвать объявленную ширину значения:\n{err}"
    );
    assert!(
        !err.contains("0..64"),
        "ширина слова носителя в тексте остаться не может:\n{err}"
    );
}

/// **Контроль:** разряд 70 в том же векторе эталон исполняет.
///
/// Без него "0..127" было бы просто другим числом; контроль показывает, что прежний
/// текст **лгал**, а новый описывает действительную границу.
#[test]
fn bit_inside_the_vector_is_executed() {
    let out = run("wide_vector_ok.takt", true);
    assert!(
        out.contains("probe=1"),
        "разряд внутри вектора обязан записываться:\n{out}"
    );
}

/// **Граница:** у скаляра называется ширина носителя - догадок об объявлении нет.
#[test]
fn scalar_names_the_carrier_width() {
    let err = run("narrow_scalar.takt", false);
    assert!(err.contains("SIM-011"), "{err}");
    assert!(
        err.contains("0..63"),
        "у скаляра называется носитель, и граница печатается включительно:\n{err}"
    );
}
