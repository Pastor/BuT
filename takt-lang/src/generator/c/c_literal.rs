//! Печать целочисленного литерала в C.
//!
//! Отдельный модуль, потому что печать числа - не `to_string()`: у C есть правило
//! вывода типа для десятичной константы (C11 6.4.4.1), и значение выше `LLONG_MAX` под
//! ним не имеет знакового типа. `clang` на такой литерал отвечает
//! `-Wimplicitly-unsigned-literal`, а проверка цели `c` идёт под `-Werror` - то есть без
//! суффикса вывод не собирается.
//!
//! Суффикс печатается только когда иначе вывод невалиден: всё, что укладывается в
//! `long long`, печатается без него. Иначе особая форма разошлась бы со снимками
//! корпуса.

/// Литерал `value` в форме, которую C принимает без предупреждений.
///
/// Выше `i64::MAX` добавляется `ULL`: в C суффикса не имеет только тот тип, который
/// компилятор подобрал бы сам, а для такого значения знакового типа нет. Ниже границы -
/// прежняя печать (`-9223372036854775808` включительно: значение конструируется как
/// унарный минус от `9223372036854775808`, что в C законно и внутри `long long`).
pub(crate) fn c_int_literal(value: i128) -> String {
    if value > i128::from(i64::MAX) {
        format!("{value}ULL")
    } else {
        value.to_string()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Обычные значения печатаются как раньше - иначе поехали бы снапшоты.
    #[test]
    fn ordinary_values_are_printed_bare() {
        assert_eq!(c_int_literal(0), "0");
        assert_eq!(c_int_literal(42), "42");
        assert_eq!(c_int_literal(-1), "-1");
        assert_eq!(c_int_literal(i128::from(i64::MAX)), "9223372036854775807");
        assert_eq!(c_int_literal(i128::from(i64::MIN)), "-9223372036854775808");
    }

    /// Выше `LLONG_MAX` - суффикс, иначе `cc -Werror` отвергает вывод.
    #[test]
    fn beyond_signed_range_gets_unsigned_suffix() {
        assert_eq!(
            c_int_literal(i128::from(i64::MAX) + 1),
            "9223372036854775808ULL"
        );
        assert_eq!(
            c_int_literal(i128::from(u64::MAX)),
            "18446744073709551615ULL"
        );
    }
}
