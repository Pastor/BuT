//! Что печатается: снимок модели для эмиссии цели `rust`.
//!
//! # Что внутри
//!
//! [`ModelEmit`] - **неизменяемый** снимок: карта, дерево модели, таблица состояний,
//! экземпляры под-моделей, шаги композиций, список состояний, стартовое, общие
//! переменные, признаки корня и нужды в HAL, набор портов. Всё это вычисляется один раз
//! в `emit_model` и дальше только читается.
//!
//! [`StateEmit`] - то же для одного состояния-композиции: имя, узел, описание
//! расширения и следующее состояние. Четыре значения, которые ходят вместе.
//!
//! **Изменяемое сюда не кладётся.** `Printer`, `Scope`, `StmtOutput` и накопитель
//! предупреждений остаются отдельными параметрами: они не "описание модели", а
//! состояние печати, и прятать их в снимок значило бы получить структуру с `&mut`
//! внутри - то есть ту же связность, но менее видимую.

use crate::generator::rust::rust_decl::PortSet;
use crate::generator::rust::rust_map::RustMap;
use crate::generator::rust::rust_model::{Instance, StateTable};
use crate::semantic::minimap::{Element, Name, StateExtend};
use crate::semantic::type_node::TypeNode;
use crate::semantic::{ModelNode, StateNode};

/// Снимок модели, которую печатает цель `rust`.
///
/// Живёт ровно столько, сколько идёт эмиссия одной модели: все поля - заимствования из
/// `emit_model`.
pub(crate) struct ModelEmit<'a> {
    /// Снимок карты моделей (минимап).
    pub map: &'a RustMap,
    /// Уникальное имя печатаемой модели.
    pub name: &'a Name,
    /// Семантическое дерево модели.
    pub model: &'a ModelNode,
    /// Элемент карты, отвечающий модели.
    pub element: &'a Element,
    /// Таблица состояний (перечисление и его варианты).
    pub table: &'a StateTable,
    /// Экземпляры под-моделей по состояниям.
    pub instances: &'a [(Name, Vec<Instance>)],
    /// Шаги последовательных композиций по состояниям.
    pub concats: &'a [crate::generator::rust::rust_chain::Chain],
    /// Состояния модели в порядке карты.
    pub states: &'a [Name],
    /// Стартовое состояние.
    pub start: &'a Name,
    /// Общие с под-моделями переменные.
    pub shared: &'a [(String, TypeNode)],
    /// Печатается ли корневая модель.
    pub is_root: bool,
    /// Нужен ли модели HAL - транзитивно (см.
    pub uses_hal: bool,
    /// Порты программы.
    pub ports: &'a PortSet,
}

/// Состояние-композиция: то, что ходит вместе при печати расширения.
pub(crate) struct StateEmit<'a> {
    /// Имя состояния.
    pub name: &'a Name,
    /// Узел состояния в дереве.
    pub raw: &'a StateNode,
    /// Описание расширения (`= Модель`, `|`, `+`).
    pub extend: &'a StateExtend,
    /// Состояние, в которое уходим по завершении.
    pub next: &'a Name,
}
