//! Правка напечатанного текста цели `rust` - снятие внешних скобок.
//!
//! Вынесено из `rust_expr` по границе ответственности (правило размера модуля): там
//! строится выражение из семантического узла, здесь - работа со строкой, которая узлов
//! не знает вовсе.

/// Снимает внешние скобки, если ими обёрнуто выражение целиком.
///
/// Нужен в позиции условия: `if (x != 0) {` даёт `unnecessary parentheses around 'if'
/// condition` - ошибку под `-D warnings` (проба 2026-07-16). Внутренние скобки при этом
/// обязаны остаться: именно они и держат приоритет.
pub(crate) fn unwrap_outer(text: &str) -> &str {
    let bytes = text.as_bytes();
    if bytes.first() != Some(&b'(') || bytes.last() != Some(&b')') {
        return text;
    }
    // Первая скобка обязана закрываться последней, иначе `(a) | (b)` потерял бы куски.
    let mut depth = 0usize;
    for (i, ch) in text.char_indices() {
        match ch {
            '(' => depth += 1,
            ')' => {
                depth -= 1;
                if depth == 0 && i + ch.len_utf8() != text.len() {
                    return text;
                }
            }
            _ => {}
        }
    }
    &text[1..text.len() - 1]
}
