//! Печать позиции диагностики и её заметок (вынос из `diagnostics/mod.rs`).
//!
//! Модуль заведён по правилу размера (`docs/CODE.md`): родитель сверх лимита, и новое
//! выносится, а не дописывается. Предмет у обеих функций один - перевод `Location` в
//! человекочитаемую координату, поэтому живут они вместе.

use super::{Diagnostic, Location, Note, line_column};

/// Префикс `путь:строка:колонка: ` для диагностики.
///
/// **Общая точка печати позиции для всех бинарников** (`taktc`, `takt-sim`).
/// Формат позиции - свойство диагностики, а не того, кто её показывает: копия в
/// каждом бинарнике разошлась бы, и пользователь одной и той же ошибки видел бы
/// разное. Это доказанный класс дефекта - см., где печать
/// расходилась по целям генерации.
///
/// Формат - как у `rustc`/`gcc`: машиночитаем и кликабелен в редакторах.
///
/// # Когда префикс пуст
///
/// - Позиции нет (`Location::Codegen`/`Implicit`/`Builtin`/`CommandLine`) либо
///   путь неизвестен: **выдумывать** координаты нельзя - пользователь пошёл бы
///   искать ошибку в первой строке файла.
/// - Файл не читается: префикс вырождается в `путь: `. Сообщить о причине важнее,
///   чем промолчать из-за проблемы с показом.
///
/// Чтение файла с диска здесь осознанно: путь в [`Diagnostic::file`] уже разрешён, а
/// тащить тексты всех файлов в каждый бинарник - хуже.
pub fn position_prefix(diag: &Diagnostic) -> String {
    let Some(path) = diag.file.as_deref() else {
        return String::new();
    };
    let Location::Source(_, start, _) = diag.loc else {
        return String::new();
    };
    // Текст нужен, чтобы перевести байтовое смещение в строку и колонку.
    let Ok(text) = std::fs::read_to_string(path) else {
        return format!("{path}: ");
    };
    let (line, column) = line_column(&text, start as usize);
    format!("{path}:{line}:{column}: ")
}

/// Позиция **заметки** в том же виде, что и позиция самой диагностики.
///
/// Заметка несёт собственный `loc` (например, "первое объявление типа - здесь",
/// `SE-108`), и без координаты её польза наполовину теряется: автор узнаёт, что
/// объявление где-то есть, но не где. Путь берётся у диагностики - заметка своего файла
/// не хранит, а ставит его тот же `stamp_file`.
///
/// Возвращает пустую строку там же, где и [`position_prefix`]: у заметки без исходной
/// позиции (`Location::Codegen`, `Builtin`) координаты нет и выдумывать её нельзя.
pub fn note_position_prefix(diag: &Diagnostic, note: &Note) -> String {
    let Some(path) = diag.file.as_deref() else {
        return String::new();
    };
    let Location::Source(note_file, start, _) = note.loc else {
        return String::new();
    };
    // Путь берётся у диагностики, а заметка вправе указывать в другой файл (`SE-108` на
    // столкновении через `import`). Печатать чужую координату под своим путём нельзя -
    // это обман: строка 1:6 читалась бы в файле, где на ней стоит совсем другое. Пока
    // заметка своего пути не хранит, в таком случае координата опускается, а на файл
    // указывает текст заметки.
    let same_file = matches!(diag.loc, Location::Source(diag_file, _, _) if diag_file == note_file);
    if !same_file {
        return String::new();
    }
    let Ok(text) = std::fs::read_to_string(path) else {
        return String::new();
    };
    let (line, column) = line_column(&text, start as usize);
    format!("{line}:{column}: ")
}
