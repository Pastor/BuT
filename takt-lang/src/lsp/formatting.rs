//! Форматирование документа (`textDocument/formatting`).
//!
//! Часть модуля `lsp`.

use super::*;

/// Собирает диагностику из исходного кода Takt.
///
/// Выполняет лексический, синтаксический и семантический анализ. Возвращает список
/// LSP-диагностик для отображения в редакторе. Правки для `textDocument/formatting`.
///
/// Возвращает **одну** правку, заменяющую документ целиком каноническим текстом, либо
/// `None`, если форматировать нечего (текст уже каноничен) - так редактор не помечает
/// файл изменённым на ровном месте.
///
/// # Единое ядро
///
/// Используется та же [`crate::format::format_source`], что и в `taktc fmt`, - поэтому
/// расхождения стилей между CLI и редактором быть не может **по построению**, а не по
/// договорённости.
///
/// # Ошибки
///
/// `Err` - исходник не форматируется (синтаксическая ошибка или непокрытый узел).
/// Вызывающий обязан решить, что с этим делать: LSP-сервер логирует и отвечает `null`,
/// потому что молча "отформатировать во что-то" хуже, чем не форматировать вовсе.
///
/// Ветвь [`FormatError::Parse`](crate::format::FormatError::Parse) несёт
/// `Vec<Diagnostic>` **со структурой**, а не строку: при желании сервер волен
/// превратить их в настоящие LSP-диагностики, а не только записать в журнал.
pub fn formatting_edits(source: &str) -> Result<Option<Vec<TextEdit>>, crate::format::FormatError> {
    let formatted = crate::format::format_source(source)?;
    if formatted == source {
        return Ok(None);
    }
    Ok(Some(vec![TextEdit {
        range: offset_to_range(source, 0, source.len()),
        new_text: formatted,
    }]))
}
