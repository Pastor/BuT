//! Паттерн "текущее состояние модели": `S(Модель) = Состояние` и его краткая форма
//! `Модель = Состояние`.
//!
//! Обе записи означают одно, и распознают их одинаково все потребители: канонизация
//! скобок, судья условий (`validate/common.rs`), печатники целей `c` и `rust`. Копия
//! разбора у каждого расходится с прочими: судья, знающий только `S(Модель)`, отвергает
//! `ref X: E != End;` кодом `SE-025`, тогда как цель `c` ту же запись переводит
//! (`model->...state != MODEL_STATE`).
//!
//! Правая часть паттерна (имя состояния) остаётся неразрешённой и здесь не трогается:
//! `End` - состояние модели-аргумента, а не той, где записано условие. Разрешает его
//! тот, кто знает область видимости: судья - проверкой (`SE-033`), генератор - печатью
//! имени.

use crate::parser::ast::Condition;
use crate::semantic::{ConditionNode, FunctionDefinitionNode, ModelNode};
use std::cell::RefCell;
use std::rc::Rc;

/// Модель, о состоянии которой говорит условие: `S(Модель)` либо краткое `Модель`.
/// `None` - это не паттерн "текущее состояние модели".
///
/// Единый источник истины о форме паттерна: зовут судья условий, печатники целей
/// `c`/`rust`, канонизация скобок ([`is_state_of`]) и адаптер условий симулятора.
pub fn state_of_model(cond: &ConditionNode) -> Option<&Rc<RefCell<ModelNode>>> {
    match cond {
        ConditionNode::Model(model, _) => Some(model),
        ConditionNode::Function(fun, args, _) => {
            if !matches!(&*fun.borrow(), FunctionDefinitionNode::Builtin("S", ..)) {
                return None;
            }
            // Арность встроенной `S` - ровно один параметр (`model`), проверена
            // семантикой; аргумент обязан быть моделью.
            match args.first().map(|a| a.as_ref())? {
                ConditionNode::Model(model, _) => Some(model),
                _ => None,
            }
        }
        _ => None,
    }
}

/// Является ли условие паттерном "текущее состояние модели".
///
/// Булев вид [`state_of_model`] - второго разбора формы здесь нет: разъехавшись, они
/// дали бы разный ответ на один текст.
pub(crate) fn is_state_of(cond: &ConditionNode) -> bool {
    state_of_model(cond).is_some()
}

/// Имя состояния из правой части сравнения `S(Модель) = Состояние`.
///
/// Формы правой части - три, и все законны:
///
/// - `Unresolved(Variable)` - штатный случай: имя принадлежит модели-аргументу,
///   а не той, где записано условие, и потому не разрешается;
/// - `Variable` - имя разрешилось в переменную объемлющей модели (совпадение
///   имён); берётся только само имя - искать всё равно в модели-аргументе;
/// - `State` - то же для состояния объемлющей модели.
///
/// `None` - правая часть не является именем: сравнение бессмысленно, и потребитель
/// отвечает своей диагностикой (`CC-013` у цели `c`, `SIM-036` у симулятора).
///
/// Разбор общий у цели `c` и эталона: своя копия у каждого разошлась бы на форме,
/// которую видит только один из них.
pub fn compared_state_name(right: &ConditionNode) -> Option<String> {
    match right {
        ConditionNode::Unresolved(Condition::Variable(id)) => Some(id.name.clone()),
        ConditionNode::Variable(var, ..) => Some(var.borrow().name().to_string()),
        ConditionNode::State(state, _) => Some(state.borrow().name().to_string()),
        _ => None,
    }
}
