//! Проверка охранных формул: `: [Guard] c;`, краткая `: c;` и десахаризация `invariant
//! Имя = c;`.
//!
//! Формула - элемент модели наравне с `cond` и ребром `ref`, и условие в ней - обычное
//! условие. Прочие проверки её не видят: `validate_conditions` идёт по
//! `model.conditions`, обход рёбер - по `references`, обход тел - по операторам, а
//! формулы не принадлежат ни одному из этих множеств. Без этого обхода опечатка в имени
//! внутри охранной формулы (`: [Guard] levl < 3;`) молчит - средство безопасности
//! перестаёт проверять, а автор об этом не узнаёт; цель `c` при этом печатает
//! `assert( < 3);`, и отказ приходит от чужого инструмента (`cc`).
//!
//! **Судья здесь не заводится.** Проверка только доставляет условие существующему судье
//! [`validate_cond`](super::common::validate_cond) - тем же приёмом, что
//! `validate/bodies.rs`. Поэтому формулы получают весь набор проверок условия
//! (`SE-025`, `SE-033`, предел глубины), а не одно правило "нет ли `Unresolved`".
//!
//! **`Formula::LTL` в объём не входит** - у неё своя проверка
//! ([`ltl_check`](crate::semantic::ltl_check), `SE-056`) и иной режим строгости:
//! предупреждение, потому что абстракция LTL заведомо сверх-аппроксимирует. Включение
//! LTL сюда превратило бы предупреждение в ошибку.

use super::*;
use crate::semantic::formula::sites::{FormulaLeaf, model_formula_sites};

/// Проверяет охранные формулы модели (без вложенных: их обходит
/// [`validate_model_all`](super::validate_model_all)).
///
/// Накопление: **одна диагностика на формулу, все формулы высказываются**. Внутри одной
/// формулы ранний выход сохраняется - дальше пошли бы следствия первой ошибки.
pub(super) fn validate_formulas(model: Rc<RefCell<ModelNode>>) -> Vec<Diagnostic> {
    // Сайты собираются до вызова судьи: `validate_cond` берёт `model.borrow()` сам, и
    // удержание заимствования здесь дало бы панику.
    let sites = model_formula_sites(&model.borrow());

    let mut out = Vec::new();
    for site in sites {
        match site.formula {
            FormulaLeaf::Guard(cond) => {
                out.extend(validate_cond(None, &cond, model.clone()).err());
            }
            FormulaLeaf::Ltl(_) => {}
        }
    }
    out
}
