//! Правило приведения **целого к целочисленному типу** - общий носитель.
//!
//! # Граница
//!
//! Здесь живёт **только** целочисленное правило. Дробное (`q`), длительность, структуры
//! и массивы остаются у эталона: их правила завязаны на его представление значения
//! (`Value`), а копия в компиляторе разошлась бы значениями - довод, он в силе.

/// Знаковое переполнение при приведении: значение не помещается в тип.
///
/// Отдельный тип, а не `Option`: сторона-вызыватель обязана **назвать** причину своими
/// словами - эталон отвечает `SIM-003` в такте, компилятор `SE-121` при сборке, и текст
/// у них разный.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SignedOverflow {
    /// Значение, которое не поместилось.
    pub value: i128,
    /// Ширина целевого типа в битах.
    pub bits: u8,
}

/// Приводит целое к целочисленному типу по правилам.
///
/// - **беззнаковое** - обёртка `mod 2ⁿ` (определённое поведение C);
/// - **знаковое** - выход за диапазон есть ошибка: в C это UB, и
///   воспроизводить его нельзя.
///
/// Шире 64 бит типов в языке нет; `Enum` приходит сюда с `bits = 64`. Носитель значения -
/// `i128`, поэтому маска и границы считаются одной формулой для любой ширины:
/// спецслучая "bits >= 64" нет, и именно он давал `SIM-004` у границы `i64::MAX`.
pub fn integer(value: i128, bits: u8, signed: bool) -> Result<i128, SignedOverflow> {
    let bits = bits.min(64);
    if signed {
        let min = -(1_i128 << (bits - 1));
        let max = (1_i128 << (bits - 1)) - 1;
        if value < min || value > max {
            return Err(SignedOverflow { value, bits });
        }
        Ok(value)
    } else {
        let mask = (1_i128 << bits) - 1;
        Ok(value & mask)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Беззнаковое приведение оборачивает: `300 as u8` - это 44.
    #[test]
    fn unsigned_wraps() {
        assert_eq!(integer(300, 8, false), Ok(44));
        assert_eq!(integer(-1, 8, false), Ok(255));
    }

    /// Знаковое вне диапазона - ошибка, а не обёртка: в C это UB.
    #[test]
    fn signed_out_of_range_is_an_error() {
        assert_eq!(
            integer(300, 8, true),
            Err(SignedOverflow {
                value: 300,
                bits: 8
            })
        );
        assert_eq!(integer(-128, 8, true), Ok(-128));
        assert_eq!(integer(127, 8, true), Ok(127));
    }

    /// Ширина 64 идёт общим путём - спецслучая нет.
    #[test]
    fn width_64_has_no_special_case() {
        assert_eq!(
            integer(i128::from(i64::MAX) + 1, 64, false),
            Ok(i128::from(i64::MIN) & ((1_i128 << 64) - 1))
        );
        assert!(integer(i128::from(i64::MAX) + 1, 64, true).is_err());
    }
}
