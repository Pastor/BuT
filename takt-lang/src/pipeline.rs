//! Общий конвейер: разбор → построение дерева → сбор диагностик.
//!
//! Вынесено из `lib.rs` (фича 0130): файл пришпилен реестром размеров, а логика
//! здесь самостоятельная — «как получить модель (или все ошибки) из текста».

use crate::diagnostics::{self, Diagnostic};
use crate::{parse, semantic};

/// Проверка «файл в позиции ВХОДА исполнения» — наружу для симулятора.
///
/// Правило одно на оба инструмента: цели зовут его ниже, в
/// [`parse_and_construct`], а `takt-sim` — по этому пути. Два ответа на один
/// вход разошлись бы (фикс 0182-02).
///
/// ⚠️ Реэкспорт живёт здесь, а не в `semantic/mod.rs`: тот файл — узаконенный
/// долг реестра размеров (`scripts/module-size-baseline.txt`), и расти ему
/// нельзя даже на строку.
pub use crate::semantic::validate::validate_entry_model;
// Подсказка «кто подключает эту библиотеку» (фича 0294) — спутник
// `validate_entry_model`: её зовут те же два потребителя, что и проверку,
// и оба обязаны отвечать одинаково. Слой `semantic::import` наружу крейта
// закрыт, поэтому доступ к подсказке даётся здесь же, рядом с проверкой.
pub use crate::semantic::import::importers::{find_importers, importers_note};

/// Разбирает и строит модель, проставляя диагностике **путь её файла** (фича 0053).
///
/// Общий шаг всех целей. Заведён потому, что путь нужно разрешить там, где
/// [`FileTable`](diagnostics::FileTable) ещё жив: реестр — деталь компиляции и
/// наружу не выходит, а `Location` несёт лишь номер файла. Без этого диагностика
/// из импортированной библиотеки была неотличима от своей — `taktc` печатал обе
/// дословно одинаково.
/// ⚠️ Возвращает **и реестр файлов** (фича 0212): диагностика цели рождается
/// после этого шага, а путь её файла разрешается только реестром. Прежде он
/// наружу не выходил, и отказ генератора печатался без координаты — даже когда
/// нёс `Location::Source` (класс фикса 0228, где то же случилось с
/// предупреждениями). Штамповать имя входного файла вместо реестра **нельзя**:
/// смещения принадлежат файлу диагностики, а он может быть импортированным.
pub(crate) fn parse_and_construct(
    filename: &str,
    source: &str,
    search_paths: &[String],
    options: &crate::generator::GenerateOptions,
) -> Result<Compilation, Diagnostic> {
    let mut files = diagnostics::FileTable::new(filename);

    // Корневой файл — номер 0 (его зарегистрировал `FileTable::new`).
    let (model_ast, source_comments) = parse(source, 0).map_err(|ds| {
        let d = ds.into_iter().next().unwrap();
        stamp_file(d, &files)
    })?;

    let model = semantic::tree::construct_model_with_files(
        &model_ast,
        None,
        search_paths,
        &mut files,
        options.specialize,
    )
    .map_err(|d| stamp_file(d, &files))?;

    // Библиотечный файл (без единого состояния) законен, но входом исполнения
    // быть не может — фикс 0182-02. Проверка стоит ЗДЕСЬ, а не в
    // `validate_model_all`: позиция «вход» — свойство вызова, а не модели, и
    // тому же дереву, пришедшему из `import`, она не адресована. Прежде такой
    // файл доезжал до генератора и получал `SE-011` «Модель должна содержать
    // начальное состояние» — сообщение о пропущенном `start`, которого автор
    // библиотеки не писал, и вдобавок без позиции.
    if let Some(mut d) = semantic::validate::validate_entry_model(&model) {
        // Подсказка «кто эту библиотеку подключает» (фича 0294): причину
        // `SE-102` называла и раньше, а следующий шаг автор делал сам — искал
        // импортёра глазами. Поиск живёт ЗДЕСЬ, а не в проверке: он ходит по
        // файловой системе, а семантика её не знает (та же граница, по которой
        // сама проверка стоит в конвейере, а не в `validate_model_all`).
        if let Some(note) = semantic::import::importers::importers_note(filename, search_paths) {
            d.notes.push(diagnostics::Note {
                // Позиции у подсказки нет по существу: она говорит о ДРУГОМ
                // файле, и координата в своём была бы ложью (правило 0243,
                // образец `SE-119`). `Location::Codegen` печатается без
                // префикса — на файл указывает сам текст заметки.
                loc: diagnostics::Location::Codegen,
                message: note,
            });
        }
        return Err(stamp_file(d, &files));
    }
    // Подстановка тела функции (фича 0444) — тоже ПОСЛЕ семантики и тоже в
    // конвейере цели: атрибут автора действует всегда, эвристика — по флагу.
    //
    // ⚠️ Эталон этот проход не зовёт **намеренно**: подстановка меняет форму, а
    // не поведение, и сверка «эталон против прошивки» тем и доказывает
    // тождественность. Позови её обе стороны — сверка перестала бы видеть
    // дефект подстановки.
    semantic::inline::inline_functions(
        &model,
        matches!(options.inline, crate::generator::InlinePolicy::Auto),
    );
    // Guard границ массива (фича 0433) — по флагу и ПОСЛЕ семантики: проходу
    // нужен разрешённый тип базы, а печатникам целей о его форме знать не
    // нужно (приём 0400). Место — конвейер, а не стадии: флаг принадлежит
    // вызову цели, и эталон зовёт проход своим (`takt-sim --bounds-check`).
    //
    // ⚠️ Guard идёт ПОСЛЕ подстановки (фича 0466): защита обязана охранять то,
    // что напечатается, а решение о подстановке не должно зависеть от того,
    // включена ли защита. Обратный порядок стоил двух расхождений: эвристика
    // 0444 мерила тело, уже раздутое обёртками, а ветвь отказа приезжала в
    // место вызова блоком из двух операторов — и цель `rust` печатала
    // отложенное объявление, которое `clippy` отвергает
    // (`needless_late_init`).
    if options.bounds_check {
        semantic::bounds_guard::insert_bounds_guards(&model);
    }
    Ok(Compilation {
        model,
        files,
        comments: std::rc::Rc::new(crate::generator::comments::SourceComments::new(
            source,
            &source_comments,
        )),
    })
}

/// Единица компиляции: построенная модель **и** реестр её файлов (фича 0212).
///
/// # Зачем тип, а не пара
///
/// Диагностика цели рождается **после** построения дерева, а путь её файла
/// разрешается только реестром. Прежде реестр наружу не выходил, и отказ
/// генератора печатался без координаты — даже когда нёс `Location::Source`
/// (класс фикса 0228, где то же случилось с предупреждениями). Пара
/// `(модель, реестр)` возложила бы штамповку на **дисциплину вызова** в восьми
/// входах `compile_to_*`; тип возлагает её на [`Compilation::emit`], то есть на
/// себя.
///
/// ⚠️ Штамповать имя входного файла вместо реестра **нельзя**: смещения
/// принадлежат файлу диагностики, а он может быть импортированным.
pub(crate) struct Compilation {
    /// Построенное семантическое дерево.
    pub(crate) model: std::rc::Rc<std::cell::RefCell<semantic::ModelNode>>,
    /// Реестр файлов компиляции: по нему разрешается путь диагностики.
    files: diagnostics::FileTable,
    /// Комментарии автора модели (фича 0535, задача 04).
    ///
    /// ⚠️ Живут ЗДЕСЬ, а не в опциях вызывающего: их знает только тот, кто
    /// видел исходник, а опции приходят снаружи и о тексте не осведомлены.
    comments: std::rc::Rc<crate::generator::comments::SourceComments>,
}

impl Compilation {
    /// Проставляет диагностике путь её файла.
    ///
    /// ⚠️ Метод ТИПА, а не свободная функция с публичным полем: путь ставит
    /// владелец реестра, и это то же решение, что у [`Compilation::emit`]
    /// (0212). Нужен он диагностикам, рождённым ВНЕ генерации, — разрешению
    /// адресов: его отказ печатался без координаты (фича 0467).
    pub(crate) fn stamp(&self, diagnostic: Diagnostic) -> Diagnostic {
        stamp_file(diagnostic, &self.files)
    }

    /// Понижения, зависящие от ЦЕЛИ, — с путём файла в диагностике.
    ///
    /// ⚠️ Отдельный метод по той же причине, что [`Compilation::stamp`]: отказ
    /// разворота составного порта (`SE-130`, фича 0501) рождается ВНЕ
    /// генерации, и без стампа печатался бы без координаты — класс 0467.
    pub(crate) fn lower_for_target(
        &self,
        split: semantic::condition::port_split::PortSplit,
        fold_state_observe: bool,
    ) -> Result<(), Diagnostic> {
        semantic::condition::observe::lower_for_target(&self.model, split, fold_state_observe)
            .map_err(|d| self.stamp(d))
    }

    /// Печатает цель В ПАМЯТЬ, проставляя диагностике путь её файла (фича 0531).
    ///
    /// Тот же отбор вставок и та же печать, что у [`Compilation::emit`]; разница
    /// одна — файлы возвращаются, а не кладутся на диск.
    pub(crate) fn emit_texts(
        &self,
        language: crate::generator::Language,
        options: &crate::generator::GenerateOptions,
    ) -> Result<crate::generator::Output, Diagnostic> {
        crate::semantic::target_block::prune(
            &self.model,
            crate::semantic::target_block::label_of(&language),
        );
        // Комментарии подставляются здесь: вызывающий их не знает, а
        // генератору они нужны — иначе переносить нечего.
        let mut options = options.clone();
        options.comments = Some(self.comments.clone());
        crate::generator::generate_texts(language, &self.model.borrow(), &options)
            .map_err(|d| stamp_file(d, &self.files))
    }
}

/// Первая ОШИБКА списка диагностик (предупреждения пропускаются).
///
/// Живёт здесь, а не у двух вызывающих: разрешение адресов отдаёт смешанный
/// список, и «найти в нём отказ» — одно правило на обе цели с адресами.
pub(crate) fn first_error(diagnostics: &[Diagnostic]) -> Option<Diagnostic> {
    diagnostics
        .iter()
        .find(|d| d.level == diagnostics::Level::Error)
        .cloned()
}

/// Разрешает номер файла диагностики в путь.
pub(crate) fn stamp_file(d: Diagnostic, files: &diagnostics::FileTable) -> Diagnostic {
    let path = files.path_of(&d.loc).map(str::to_string);
    d.with_file_if_unset(path.as_deref())
}

/// **Все** ошибки исходного текста за один прогон (фича 0130).
///
/// Тот же конвейер, что у `compile_to_*` (`parse` → построение дерева →
/// проверки), но результат — **список**, а не первая встреченная ошибка.
/// Пустой список означает, что модель строится.
///
/// # Зачем отдельный вход
///
/// `compile_to_*` возвращают `Result<_, Diagnostic>` — одну ошибку, и менять их
/// сигнатуры ради вывода значило бы править семь целей и 183 вызова
/// (`construct_model`). Вместо этого потребитель, которому нужны **все** ошибки,
/// зовёт эту функцию до компиляции; так делает и `taktc`, и языковой сервер —
/// и потому отвечают одинаково. Прежде расходились: сервер перечислял все ошибки
/// разбора, а CLI печатал первую, хотя оба зовут один [`parse`].
///
/// # Что уже накоплено, а что нет
///
/// - **Разбор** отдаёт все свои ошибки (лексер + парсер) — они и так собирались
///   в `Vec`, но терялись на стыке: вызывающий брал первую.
/// - **Построение дерева** остаётся терминальным: после ошибки дерево неполно, и
///   продолжение дало бы сообщения о следствиях, а не о причинах (решение
///   ADR 0130).
/// - **Проверки** (`validate`) высказываются все: они идут по готовому дереву и
///   независимы друг от друга.
///
/// # Почему вход знает про режим параметров
///
/// `specialize` — режим `--parameters=specialize` (фича 0185). Диагностика от
/// него **зависит** и зависеть обязана: параметр в позиции compile-time величины
/// (`after PARAM`, адрес порта) законен в `specialize` и отвергается в `assign`
/// (`SE-088`, R12) — это единственное место, где режим виден не в форме вывода, а
/// в множестве принимаемых программ. Прогон с жёстко зашитым `false` печатал бы
/// `SE-088` о программе, которую сам же компилятор в этом режиме собирает, — то
/// есть отказ на верном входе. Параметр продет **одной** сигнатурой, как и у
/// `parse_and_construct` (0185-05): два входа «с режимом» и «без» разошлись бы.
///
/// Список упорядочен по позиции в тексте и не содержит точных повторов
/// ([`diagnostics::normalize`]).
pub fn collect_compile_diagnostics(
    filename: &str,
    source: &str,
    search_paths: &[String],
    specialize: bool,
) -> Vec<Diagnostic> {
    let mut files = diagnostics::FileTable::new(filename);

    let model_ast = match parse(source, 0) {
        Ok((ast, _)) => ast,
        Err(ds) => {
            let stamped = ds.into_iter().map(|d| stamp_file(d, &files)).collect();
            return diagnostics::normalize(stamped);
        }
    };

    // Стадии построения и проверки разделены намеренно. Слитно (через
    // `construct_model_with_files`) получить всё нельзя — тот вход отдаёт первую
    // ошибку по контракту.
    //
    // ⚠️ С фичи 0152 стадии построения тоже отдают **список**: внутри стадий
    // 4–6 (тела блоков, функций, условия рёбер) диагностики накапливаются, между
    // стадиями — нет. Неполное дерево при этом наружу не выходит, поэтому здесь
    // на руках либо готовая модель, либо только диагностики.
    let model = match semantic::stages::construct_stages(
        &model_ast,
        None,
        search_paths,
        &mut files,
        specialize,
    ) {
        Ok(model) => model,
        Err(ds) => {
            let stamped = ds.into_iter().map(|d| stamp_file(d, &files)).collect();
            return diagnostics::normalize(stamped);
        }
    };

    let found = semantic::validate::validate_model_all(model)
        .into_iter()
        .map(|d| stamp_file(d, &files))
        .collect();
    diagnostics::normalize(found)
}
