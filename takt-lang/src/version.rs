//! Версия языка Takt - единственный источник истины в коде.
//!
//!
//! Теперь номер версии живёт здесь, а проверка `scripts/check-language-version.sh` (в
//! `precheck.sh`, а значит и в CI, сверяет эту константу с канонической строкой
//! `**Версия языка: X.Y.Z**` в `README.md`: расхождение валит предкоммит.
//!
//! **Версия языка накапливается по циклам**: несколько фич, меняющих язык в одном
//! цикле, вносят изменения в **уже поднятую** версию и **не** поднимают её снова.
//! Подъём делает первая закрытая фича цикла и помечает коммит тегом `v<версия>`. Меняя
//! эту константу, синхронно правь каноническую строку `README.md` - иначе проверка
//! покраснеет.
//!
//! Это **не** версия крейта `takt-lang` (`CARGO_PKG_VERSION`): крейт версионируется по
//! SemVer на каждую фичу, версия языка - накапливается. Они намеренно разные.
//!
//! **Наружу модуль отдаёт только то, что зовут за его пределами**: константу версии
//! и два входа инструментов - `run_version_subcommand` для компилятора и
//! `handle_server_args` для сервера. Прочие функции модульные, и это граница, а не
//! случайность: `pub` поверх недостижимого кода глушит `dead_code`, и мёртвая
//! функция живёт в дереве незамеченной. Модульная - валит сборку под `-D warnings`.

/// Текущая версия языка Takt (SemVer, `x.y.z`). Единственный источник истины;
/// `README.md` обязан ей соответствовать (проверка `check-language-version.sh`).
pub const LANGUAGE_VERSION: &str = "0.19.0";

/// Печать версий инструмента - подкоманда `taktc version`.
///
/// **Логика здесь, а не в бинарнике** - образец `address-map`: так проверяется
/// **вывод**, а не факт вызова. Бинарник остаётся диспетчером.
///
/// Версий **две, и они намеренно разные**: версия крейта растёт по SemVer на каждую
/// фичу, версия языка накапливается по циклам. Печатать одну значило бы вводить в
/// заблуждение - какая из них имеется в виду, пользователь угадывать не обязан.
///
/// Ни одно число здесь не написано литералом: обе величины читаются из кода, иначе
/// появился бы второй источник истины - ровно тот, против которого эта константа и
/// заведена.
fn version_text() -> String {
    version_text_for("taktc")
}

/// То же для любого инструмента проекта - имя передаётся параметром.
///
/// Обобщено потому, что версию обязан называть **и языковой сервер**: `takt-lsp`
/// аргументы командной строки не разбирал вовсе, `--version` уходил в протокол и падал
/// `ProtocolError`. Пользователь не мог отличить дефект языка от устаревшего сервера -
/// замер 2026-08-23: сервер сборки 2026-08-17 отвечал `SE-003` на файл, который свежий
/// компилятор принимает.
///
/// Своей печати у сервера заводить нельзя: форма вывода - одно знание на проект.
fn version_text_for(tool: &str) -> String {
    format!(
        "{} {}\nязык Takt {}",
        tool,
        env!("CARGO_PKG_VERSION"),
        LANGUAGE_VERSION
    )
}

/// Подкоманда `version`: печатает [`version_text`] и возвращает код процесса.
pub fn run_version_subcommand() -> i32 {
    println!("{}", version_text());
    0
}

/// То же для инструмента с другим именем.
fn run_version_subcommand_for(tool: &str) -> i32 {
    println!("{}", version_text_for(tool));
    0
}

/// Разбор аргументов командной строки сервера.
///
/// Возвращает код выхода, если запуск сервера не нужен, и `None` - если нужен.
///
/// **Неизвестный аргумент игнорируется, а не отвергается.** Сервер запускает редактор,
/// и состав аргументов задаёт его конфигурация; отказ сделал бы неработоспособной чужую
/// настройку ради флага, которого она не просила. Граница названа: единственные
/// разбираемые формы перечислены здесь.
///
/// Разбор живёт в библиотеке, а не в бинарнике (образец `address-map`): так проверяется
/// **вывод**, а не факт вызова - бинарник тестами не покрыть. Форма версии берётся у
/// [`version_text_for`], своей строки нет.
pub fn handle_server_args(args: &[String]) -> Option<i32> {
    let first = args.first()?;
    match first.as_str() {
        "version" | "--version" | "-V" => Some(run_version_subcommand_for("takt-lsp")),
        "--help" | "-h" | "help" => {
            println!("{}", server_help_text());
            Some(0)
        }
        _ => None,
    }
}

/// Справка сервера: он запускается редактором, а не пользователем.
///
/// Первой строкой названо главное недоразумение: запущенный вручную сервер
/// **завершится ошибкой протокола** - именно так выглядела попытка спросить у
/// него версию до этого исправления.
fn server_help_text() -> String {
    format!(
        "takt-lsp — языковой сервер Takt (LSP поверх stdio).\n\
         \n\
         Запускается РЕДАКТОРОМ, не вручную: без клиента процесс завершится\n\
         ошибкой протокола.\n\
         \n\
         Формы:\n\
         \x20 takt-lsp                 запуск сервера (stdio)\n\
         \x20 takt-lsp --version | -V  версии инструмента и языка\n\
         \x20 takt-lsp --help    | -h  эта справка\n\
         \x20 takt-lsp --graph ФАЙЛ    граф модели для схемы, JSON в поток вывода\n\
         \n\
         Пути поиска импортов задаются клиентом —\n\
         initializationOptions.searchPaths.\n\
         \n\
         {}",
        version_text_for("takt-lsp")
    )
}

#[cfg(test)]
mod tests {
    use super::{
        LANGUAGE_VERSION, handle_server_args, server_help_text, version_text, version_text_for,
    };

    /// сервер называет своё имя, а не имя компилятора.
    ///
    /// Имя важно: пользователь сверяет версию установленного `takt-lsp` с версией
    /// дерева, и строка "taktc ..." в ответе сервера сбивала бы сверку.
    #[test]
    fn server_version_names_the_server() {
        let text = version_text_for("takt-lsp");
        assert!(
            text.starts_with("takt-lsp "),
            "вывод обязан называть инструмент: {text:?}"
        );
        assert!(
            text.contains(LANGUAGE_VERSION),
            "вывод обязан нести версию языка: {text:?}"
        );
        // Контроль: форма у обоих инструментов одна - знание не раздвоено.
        assert_eq!(
            version_text().lines().count(),
            text.lines().count(),
            "форма вывода обязана совпадать с taktc"
        );
    }

    /// `--version`, `-V` и `version` останавливают запуск сервера.
    #[test]
    fn version_forms_stop_the_server() {
        for form in ["--version", "-V", "version"] {
            assert_eq!(
                handle_server_args(&[form.to_string()]),
                Some(0),
                "форма {form} обязана печатать версию и выходить"
            );
        }
        for form in ["--help", "-h", "help"] {
            assert_eq!(
                handle_server_args(&[form.to_string()]),
                Some(0),
                "форма {form} обязана печатать справку и выходить"
            );
        }
    }

    /// **Контроль:** обычный запуск и неизвестный аргумент сервер не
    /// останавливают.
    ///
    /// Без этой проверки правка читалась бы как "сервер стал отвергать аргументы":
    /// состав аргументов задаёт конфигурация редактора, и отказ сломал бы чужую
    /// настройку ради флага, которого она не просила.
    #[test]
    fn other_arguments_start_the_server() {
        assert_eq!(handle_server_args(&[]), None, "без аргументов — сервер");
        assert_eq!(
            handle_server_args(&["--stdio".to_string()]),
            None,
            "неизвестный аргумент обязан игнорироваться, а не отвергаться"
        );
    }

    /// Справка называет главное недоразумение - запуск вручную.
    #[test]
    fn help_names_the_editor_launch() {
        let text = server_help_text();
        assert!(
            text.contains("РЕДАКТОРОМ"),
            "справка обязана сказать, кто запускает сервер: {text:?}"
        );
        assert!(
            text.contains(LANGUAGE_VERSION),
            "справка обязана нести версии: {text:?}"
        );
    }

    /// Вывод подкоманды несёт обе версии, и обе взяты из кода.
    ///
    /// Сверка идёт с константой, а не с литералом вида `"0.10.0"`: литерал в тесте
    /// стал бы вторым источником истины о версии.
    #[test]
    fn version_text_carries_both_versions_from_code() {
        let text = version_text();
        assert!(
            text.contains(LANGUAGE_VERSION),
            "вывод обязан нести версию языка: {text:?}"
        );
        assert!(
            text.contains(env!("CARGO_PKG_VERSION")),
            "вывод обязан нести версию крейта: {text:?}"
        );
    }

    /// Версии названы **раздельно**: они намеренно разные, и пользователь не обязан
    /// угадывать, какая из них имеется в виду.
    #[test]
    fn version_text_names_which_version_is_which() {
        let text = version_text();
        let lines: Vec<&str> = text.lines().collect();
        assert_eq!(lines.len(), 2, "две версии — две строки: {text:?}");
        assert!(
            lines[0].starts_with("taktc "),
            "первая строка — крейт: {text:?}"
        );
        assert!(lines[1].contains("язык Takt"), "вторая — язык: {text:?}");
    }

    /// Константа экспортирована и имеет форму SemVer-тройки `x.y.z` из десятичных
    /// компонент. Форму стережёт этот тест: проверка `check-language-version.sh` грепает
    /// литерал по этому шаблону.
    #[test]
    fn language_version_is_semver_triple() {
        let parts: Vec<&str> = LANGUAGE_VERSION.split('.').collect();
        assert_eq!(
            parts.len(),
            3,
            "версия языка должна быть тройкой x.y.z, получено {LANGUAGE_VERSION:?}"
        );
        for p in parts {
            assert!(
                !p.is_empty() && p.chars().all(|c| c.is_ascii_digit()),
                "компонент версии должен быть непустым числом, получено {p:?} в {LANGUAGE_VERSION:?}"
            );
        }
    }

    /// Реэкспорт из корня крейта: потребители зовут `takt_lang::LANGUAGE_VERSION`.
    #[test]
    fn re_exported_from_crate_root() {
        assert_eq!(crate::LANGUAGE_VERSION, LANGUAGE_VERSION);
    }
}
