//! Темпоральная формула во всех местах доходит до верификатора.
//!
//! # Что доказывает набор
//!
//! Перебор целей отвечает на вопрос "не сломала ли формула вывод": темпоральная до
//! целей не доезжает по существу, и её след там - отсутствие `assert`. Но у неё есть
//! **второй потребитель** - `taktc verify`, и для него важно не молчание, а обратное:
//! формула, объявленная в любом из шести мест, обязана дойти до проверки, и её
//! **область** обязана соответствовать месту.
//!
//! Область - наблюдаемое отличие, а не деталь: формула уровня состояния говорит о
//! прогонах из этого состояния (решение 0049) и десахаризуется в `G (Состояние -> φ)`.
//! Проверять только "формула найдена" значило бы пропустить потерю области.
//!
//! Позиция диагностики проверяется здесь же: с `SE-055` называет место самой формулы, а
//! прежде - вместилища, и три формулы уровня модели печатались с одной и той же
//! строкой.

use std::collections::BTreeSet;

/// Модель с темпоральной формулой во всех шести местах.
const ALL_SITES: &str = "var k: u8 := 0;\n\
                         out o: u8 at 0;\n\
                         cond Low = k < 200;\n\
                         \n\
                         : [LTL] G Low;\n\
                         \n\
                         always {\n\
                         \x20   : [LTL] G Low;\n\
                         }\n\
                         \n\
                         fn bump(v: u8) -> u8 {\n\
                         \x20   : [LTL] G Low;\n\
                         \x20   return v + 1;\n\
                         }\n\
                         \n\
                         start Go {\n\
                         \x20   : [LTL] G Low;\n\
                         \x20   always {\n\
                         \x20       : [LTL] G Low;\n\
                         \x20       if k > 0 {\n\
                         \x20           : [LTL] G Low;\n\
                         \x20       }\n\
                         \x20       k := bump(k);\n\
                         \x20       o := k;\n\
                         \x20   }\n\
                         \x20   ref Go: k < 3;\n\
                         \x20   next Done;\n\
                         }\n\
                         state Done;\n";

fn model() -> std::rc::Rc<std::cell::RefCell<takt_lang::semantic::ModelNode>> {
    let (ast, _) = takt_lang::parse(ALL_SITES, 0).expect("разбор пробы");
    takt_lang::semantic::tree::construct_model(&ast, None, &[]).expect("семантика пробы")
}

/// **Шесть мест - шесть формул, и области распределены по месту.**
///
/// Три формулы уровня модели (её тело, блок `always` модели, тело функции) проверяются
/// без области; три уровня состояния (объявление, блок `always` состояния, вложенный
/// `if`) - с областью `Go`, то есть десахаризуются в `G (Go -> φ)`.
///
/// Спрашивается публичный вердикт верификатора, а не сборщик сайтов: набор проверяет
/// то, что видит автор, а не устройство обхода.
#[test]
fn every_site_reaches_the_verifier_with_its_scope() {
    let results = takt_lang::verify_all(model());
    assert_eq!(
        results.len(),
        6,
        "шесть мест объявления формулы (0203) — шесть проверок"
    );
    let scoped = results
        .iter()
        .filter(|r| format!("{}", r.formula).contains("Go ->"))
        .count();
    assert_eq!(
        (results.len() - scoped, scoped),
        (3, 3),
        "три формулы уровня модели и три уровня состояния"
    );
}

/// **Предупреждение `SE-055` выдаётся на каждую формулу и с её местом.**
///
/// Проверяется число разных координат: до сюда шла позиция вместилища, и три формулы
/// уровня модели печатались с одной и той же строкой - по сообщению нельзя было понять,
/// о которой речь.
#[test]
fn warning_is_emitted_per_formula_with_its_place() {
    let warnings = takt_lang::ltl_warnings(model());
    let ltl: Vec<_> = warnings
        .iter()
        .filter(|d| d.code.as_deref() == Some("SE-055"))
        .collect();
    assert_eq!(ltl.len(), 6, "по одному предупреждению на формулу: {ltl:?}");
    let places: BTreeSet<String> = ltl.iter().map(|d| format!("{:?}", d.loc)).collect();
    assert_eq!(
        places.len(),
        6,
        "каждое предупреждение называет своё место: {places:?}"
    );
}
