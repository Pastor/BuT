//! Разделитель образцов ветви `match` переживает форматирование.
//!
//! # Что проверяется
//!
//! Грамматика принимает образцы через **запятую** (`CommaOne<MatchPattern>`), а
//! форматтер печатал их через `|`. Разница не косметическая: `0 | 1` читается обратно
//! как один образец-выражение (побитовое или), то есть `0, 1 => ...` после `taktc fmt`
//! превращалось в `1 => ...`.
//!
//! Класс поймал тест A3 ("форматтер изменил смысл") - но лишь тогда, когда в корпусе
//! появился первый вход с многообразцовой ветвью.
//!
//! Здесь проверяется сам разделитель, а не только нейтральность: A3 сравнивает вывод
//! цели, и совпадение по случайности (когда разбираемое значение совпадает с
//! результатом `|`) её бы устроило.

/// Модель с многообразцовой ветвью.
const SOURCE: &str = "out o: u8 at 0;\n\
                      var k: u8 := 1;\n\
                      \n\
                      start Run {\n\
                      \x20   always {\n\
                      \x20       match k {\n\
                      \x20           0, 1 => { k := k + 1; }\n\
                      \x20           _ => { k := k + 2; }\n\
                      \x20       }\n\
                      \x20       o := k;\n\
                      \x20   }\n\
                      \x20   ref Run: k < 3;\n\
                      }\n";

/// **Образцы печатаются через запятую - так же, как их принимает грамматика.**
#[test]
fn patterns_keep_the_comma_separator() {
    let formatted = takt_lang::format::format_source(SOURCE).expect("форматирование");
    assert!(
        formatted.contains("0, 1 =>"),
        "разделитель образцов — запятая:\n{formatted}"
    );
    assert!(
        !formatted.contains("0 | 1"),
        "печать через `|` меняет смысл: это ОДИН образец-выражение:\n{formatted}"
    );
}

/// **Повторное форматирование ничего не меняет** (идемпотентность, 0462).
#[test]
fn formatting_patterns_is_idempotent() {
    let once = takt_lang::format::format_source(SOURCE).expect("первое форматирование");
    let twice = takt_lang::format::format_source(&once).expect("второе форматирование");
    assert_eq!(once, twice, "форматирование обязано быть идемпотентным");
}
