//! Комментарий последней строкой тела принадлежит этому телу.
//!
//! # Что здесь проверяется
//!
//! Комментарий, стоящий перед закрывающей скобкой, форматтер обязан выдать
//! **внутри** тела. Иначе его подхватывает `leading()` следующего элемента -
//! уже за скобкой, у чужого узла, - а если следующего элемента нет, он
//! всплывает в конец файла.
//!
//!
//! | Конструкция | До фичи | После |
//! |---|---|---|
//! | `enum`, `struct`, `fn`, именованный блок | хвост на месте | на месте |
//! | **состояние** | хвост уезжал в конец файла | на месте |
//! | **вложенная модель** | хвост уезжал в конец файла | на месте |
//!
//! **Корпус класс не покрывает:** комментариев внутри таких записей в 308 файлах ноль -
//! потому дефект и пережил три правки.
//!
//! # Два слоя
//!
//! 1. **поведение** - форматирование пробы со хвостом в каждой конструкции;
//! 2. **устройство** - греп по исходнику: закрывающая скобка тела печатается
//!    только через общую `close_body`. Первый слой ловит сегодняшние ветки,
//!    второй - **новую**, которую заведут завтра.

use takt_lang::format::format_source;

/// Хвостовой комментарий в каждой конструкции с телом.
const TAILS: &str = "enum Color {\n\
                     \x20   Red = 0\n\
                     \x20   // хвост перечисления\n\
                     }\n\
                     \n\
                     struct Point {\n\
                     \x20   x: u8\n\
                     \x20   // хвост структуры\n\
                     }\n\
                     \n\
                     fn add(a: u8, b: u8) -> u8 {\n\
                     \x20   return a + b;\n\
                     \x20   // хвост функции\n\
                     }\n\
                     \n\
                     model Inner {\n\
                     \x20   var k: u8 := 0;\n\
                     \x20   start Idle {\n\
                     \x20       always {\n\
                     \x20           k := add(k, 1);\n\
                     \x20           // хвост блока\n\
                     \x20       }\n\
                     \x20       // хвост состояния\n\
                     \x20   }\n\
                     \x20   // хвост модели\n\
                     }\n\
                     \n\
                     start Main = Inner;\n";

/// Отступ строки с комментарием - признак того, чьё это тело.
///
/// Комментарий, потерявший хозяина, всплывает в конец файла с нулевым отступом;
/// уехавший к соседу - с отступом соседа. Проверка порядка строк этого не различает:
/// уезжая, комментарии сохраняют взаимный порядок (проверено мутацией).
fn indent_of(text: &str, needle: &str) -> usize {
    let line = text
        .lines()
        .find(|l| l.contains(needle))
        .unwrap_or_else(|| panic!("в выводе нет строки '{needle}':\n{text}"));
    line.len() - line.trim_start().len()
}

/// Каждый хвостовой комментарий остаётся внутри своего тела.
///
/// Проверяется не факт наличия текста, а **глубина**: комментарий, потерявший хозяина,
/// из вывода не девается - он всплывает в конец файла с нулевым отступом.
#[test]
fn tail_comment_stays_inside_its_body() {
    let out = format_source(TAILS).expect("форматирование");
    for (comment, indent) in [
        ("хвост перечисления", 4),
        ("хвост структуры", 4),
        ("хвост функции", 4),
        ("хвост блока", 12),
        ("хвост состояния", 8),
        ("хвост модели", 4),
    ] {
        assert_eq!(
            indent_of(&out, comment),
            indent,
            "'{comment}' стоит не в своём теле:\n{out}"
        );
    }
}

/// Форматирование идемпотентно: второй прогон ничего не двигает.
///
/// Без этой проверки "комментарий на месте" могло бы означать "уехал ровно на столько,
/// чтобы тест прошёл": перенос хозяина виден на втором прогоне.
#[test]
fn formatting_is_idempotent() {
    let once = format_source(TAILS).expect("первое форматирование");
    let twice = format_source(&once).expect("второе форматирование");
    assert_eq!(once, twice, "второй прогон изменил вывод");
}

/// Уже канонический текст не меняется вовсе.
#[test]
fn canonical_text_is_unchanged() {
    let once = format_source(TAILS).expect("форматирование");
    assert_eq!(
        once, TAILS,
        "проба записана в каноне — форматтер не должен её трогать"
    );
}

/// **Устройство: закрывающая скобка тела печатается одной функцией.**
///
/// Ветка, напечатавшая `}` своими руками, комментарии перед ним не выдаст - и заметить
/// это по корпусу нельзя (комментариев внутри таких записей там нет). Поэтому тест
/// смотрит на **исходник** и падает списком мест.
///
/// Именно так класс и жил: три правки в трёх ветках, четвёртая и пятая ветки остались с
/// прежним поведением, а док-строка одной из них это прямо называла.
#[test]
fn closing_brace_goes_through_one_function() {
    let source = include_str!("../../src/format/mod.rs");
    let offenders: Vec<(usize, &str)> = source
        .lines()
        .enumerate()
        .filter(|(_, line)| {
            let t = line.trim();
            t.starts_with("out.line(\"}\")") || t.starts_with("out.line(&format!(\"}}")
        })
        .map(|(i, line)| (i + 1, line.trim()))
        .collect();
    assert!(
        offenders.is_empty(),
        "закрывающая скобка тела печатается в обход `close_body` \
         (комментарии перед ней потеряются) — места:\n{offenders:#?}"
    );
}
