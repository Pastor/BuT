//! Проект Takt вне страницы: роды файлов, манифест, архив, состав.
//!
//! # Предмет
//!
//! Проект - это набор файлов нескольких родов (модели, сценарии, пояснения,
//! раскладки схемы, карты адресов) и выбор автора: активный файл и сценарий, цель
//! и ключи сборки, задержки прогона. Знание об этом нужно серверу проектов,
//! командной строке и модулю под браузер, и носитель у него один - этот крейт:
//! второй список расширений или второе правило принадлежности сценария модели
//! разошлись бы с первым молча.
//!
//! # Формы проекта
//!
//! - каталог, где рядом с файлами лежит манифест `takt-project.json`;
//! - архив `.zip`: манифест и исходники в `src/` - форма обмена сервиса;
//! - одна модель: файл `.takt` и файлы рядом с ним по соглашению имён
//!   (`<модель>.takt-ui`, `<модель>.md`, `<модель>.takt-map`, сценарии по правилу
//!   принадлежности).
//!
//! Компилятора здесь нет: крейт берёт и сервер, который с компилятором не
//! линкуется.

