// Витрина открытых проектов: страница за страницей.
//
// # Чего здесь нет
//
// Разметки. Модуль ничего не рисует: он отдаёт записи и признак "есть ещё", а
// показывает их `account.js`. Так правило проверяется без браузера.

/**
 * Заводит ленту витрины поверх запроса к серверу.
 *
 * @param {(query: string|null, cursor: string|null) => Promise<object>} ask
 *        как спросить сервер: `api.showcase`
 * @returns {{first: (query: string|null) => Promise<object[]>,
 *            next: () => Promise<object[]>,
 *            hasMore: () => boolean}} лента
 */
export function feed(ask) {
  /** Курсор следующей страницы; `null` — продолжения нет. */
  let cursor = null;
  /**
   * Слово поиска текущей ленты.
   *
   * ⚠️ Хранится ЗДЕСЬ и уходит с каждой страницей: у сервера курсор задаёт
   * только место, а не отбор, и следующая страница без слова пришла бы из
   * всей витрины — читатель увидел бы под своим поиском чужие проекты.
   */
  let words = null;
  /** Идёт ли запрос: второе нажатие «ещё» до ответа дало бы записи дважды. */
  let busy = false;

  /** Принимает страницу от сервера и запоминает её курсор. */
  function accept(page) {
    // Курсора нет - страница последняя. Пустой строкой он быть не может: сервер отдаёт
    // его только у полной страницы, и "есть ещё" здесь означает ровно то, что сказал
    // сервер, а не догадку по числу записей.
    cursor = page?.next_cursor ?? null;
    return page?.items ?? [];
  }

  return {
    /**
     * Спрашивает первую страницу нового поиска.
     *
     * ⚠️ Курсор сбрасывается: искали другое слово — продолжать нечего, а
     * унесённый от прежнего поиска курсор отдал бы чужую страницу.
     */
    async first(query) {
      cursor = null;
      words = query || null;
      busy = true;
      try {
        return accept(await ask(words, null));
      } finally {
        busy = false;
      }
    },

    /**
     * Спрашивает следующую страницу тем курсором, что дал сервер.
     *
     * Пустой список — продолжения не было либо запрос уже идёт.
     */
    async next() {
      if (cursor === null || busy) return [];
      busy = true;
      try {
        return accept(await ask(words, cursor));
      } finally {
        busy = false;
      }
    },

    /** Есть ли ещё страницы. */
    hasMore() {
      return cursor !== null;
    },
  };
}
