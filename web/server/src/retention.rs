//! Срок хранения проекта и его свёртка.
//!
//! # Правило
//!
//! у проектов есть **срок хранения**. Не
//! обращались дольше срока - проект сворачивается в архив; обращение на чтение
//! **или** запись сбрасывает счётчик. Свёрнутый проект разворачивается **первым
//! же обращением**: для автора архивация невидима, кроме
//! того, что первое открытие медленнее.
//!
//! # Подметание
//!
//! Обход стоит **и командой, и по времени**: команда нужна тому, кто ставит её в
//! `cron`, а обход по времени - тому, у кого `cron` нет.
//! Оба зовут одну функцию: второй проход разошёлся бы с первым.
//!
//! # Осиротевшие каталоги
//!
//! Проходов **два**, и предметы у них разные. [`sweep`] сворачивает то, что база знает
//! и чего давно не спрашивали. [`sweep_orphans`] убирает обратное - то, что лежит на
//! диске, а строки в базе не имеет: удаление проекта идёт "сперва база, затем диск", и
//! обрыв между этими шагами, как и прямой `DELETE` в базе, оставляет каталог, которого
//! не видит никто - ни витрина, ни автор, ни выгрузка. Место он занимает, а удалить его
//! некому.
//!
//! Возраст сироты обязателен. Запись файла идёт "сперва база, затем диск", и каталог
//! успевает появиться раньше, чем транзакция закрыта: моложе [`ORPHAN_GRACE`] каталог
//! не трогается - иначе подметание удаляло бы исходники у автора прямо во время
//! сохранения.

use std::sync::Arc;

use tokio_postgres::GenericClient;

use crate::db;
use crate::store::Store;

/// Насколько грубо ведётся отметка обращения, секунд.
pub const GRANULARITY: i64 = 3600;

/// Сколько сирота обязана пролежать, прежде чем её подметут, секунд.
///
/// Это не вкус, а защита от гонки: между записью файла на диск и закрытием транзакции
/// проходит время, и в этот миг каталог выглядит сиротой, ею не будучи. Час на порядки
/// больше любого запроса и на порядки меньше срока хранения - то есть отделяет "идёт
/// запись" от "остался мусор".
pub const ORPHAN_GRACE: i64 = 3600;

/// Отмечает обращение и разворачивает свёрнутый проект.
///
/// Зовётся из **обоих** путей - чтения и записи: правило говорит про оба, и пропуск
/// одного означал бы, что активно правимый проект однажды свернётся под руками автора.
///
/// # Ошибки
/// Отказ базы либо диска.
pub async fn touch<C: GenericClient>(
    client: &C,
    store: &Arc<Store>,
    id: &str,
    owner: &str,
    archived_at: Option<i64>,
    touched_at: i64,
) -> anyhow::Result<()> {
    let now = db::now();
    if archived_at.is_some() {
        // Сначала диск, потом база: обратный порядок при обрыве оставляет проект
        // "развёрнутым" по записи и свёрнутым на диске - то есть без исходников.
        store.unpack(owner, id)?;
        client
            .execute(
                "UPDATE projects SET archived_at = NULL, touched_at = $2 WHERE id = $1",
                &[&id, &now],
            )
            .await?;
        return Ok(());
    }
    if due(now, touched_at) {
        client
            .execute(
                "UPDATE projects SET touched_at = $2 WHERE id = $1",
                &[&id, &now],
            )
            .await?;
    }
    Ok(())
}

/// Пора ли обновлять отметку обращения.
///
/// Отдельной функцией, потому что это и есть правило: сравнение внутри обработчика
/// проверить нечем, а здесь оно проверяется поведением.
pub fn due(now: i64, touched_at: i64) -> bool {
    now - touched_at >= GRANULARITY
}

/// Сворачивает проекты, к которым не обращались дольше срока.
///
/// Возвращает, сколько свёрнуто.
///
/// # Ошибки
/// Отказ базы. Отказ диска на одном проекте обход не останавливает: иначе
/// один испорченный проект оставлял бы несвёрнутыми все следующие, и заметить
/// это было бы нечем.
pub async fn sweep(
    client: &deadpool_postgres::Client,
    store: &Arc<Store>,
    retention_secs: i64,
) -> anyhow::Result<usize> {
    let border = db::now() - retention_secs;
    let rows = client
        .query(
            "SELECT id, owner_id FROM projects
             WHERE archived_at IS NULL AND touched_at < $1
             ORDER BY touched_at",
            &[&border],
        )
        .await?;
    let mut packed = 0;
    for row in &rows {
        let id: String = row.get(0);
        let owner: String = row.get(1);
        let names: Vec<String> = client
            .query(
                "SELECT name FROM project_files WHERE project_id = $1 ORDER BY name",
                &[&id],
            )
            .await?
            .iter()
            .map(|row| row.get(0))
            .collect();
        if let Err(error) = store.pack(&owner, &id, &names) {
            tracing::warn!(%error, project = %id, "проект не сворачивается");
            continue;
        }
        client
            .execute(
                "UPDATE projects SET archived_at = $2 WHERE id = $1",
                &[&id, &db::now()],
            )
            .await?;
        packed += 1;
    }
    Ok(packed)
}

/// Подметает осиротевшее: то, что лежит на диске, а строки в базе не имеет.
///
/// Возвращает, сколько проектов убрано. Пустые каталоги владельцев снимаются следом -
/// владелец без единого проекта каталога не заслуживает.
///
/// `grace_secs` - сколько сирота обязана пролежать; у сервера это [`ORPHAN_GRACE`], а
/// параметром оно вынесено ради проверок: ждать час, чтобы увидеть работу обхода,
/// значило бы мерить терпение прогона (приём [`crate::retention::sweep`], где так же
/// вынесен срок хранения).
///
/// # Ошибки
/// Отказ базы. Отказ диска на одном каталоге обход не останавливает - по той
/// же причине, что и у [`sweep`]: иначе один испорченный каталог оставлял бы
/// нетронутыми все следующие.
pub async fn sweep_orphans(
    client: &deadpool_postgres::Client,
    store: &Arc<Store>,
    grace_secs: i64,
) -> anyhow::Result<usize> {
    let now = db::now();
    let mut removed = 0;
    for owner in store.owners()? {
        for project in store.projects_of(&owner.name)? {
            // Молодое не трогаем: оно может принадлежать записи, которая прямо сейчас
            // идёт. Сирота никуда не денется - её подметёт следующий обход.
            if now - project.modified < grace_secs {
                continue;
            }
            let known = client
                .query_opt(
                    "SELECT 1 FROM projects WHERE id = $1 AND owner_id = $2",
                    &[&project.name, &owner.name],
                )
                .await?;
            if known.is_some() {
                continue;
            }
            if let Err(error) = store.remove_project(&owner.name, &project.name) {
                tracing::warn!(%error, project = %project.name, "осиротевший каталог не убирается");
                continue;
            }
            tracing::info!(project = %project.name, owner = %owner.name, "осиротевший каталог убран");
            removed += 1;
        }
        // Возраст каталога владельца берётся до удалений: снятие проекта обновляет
        // время родителя, и без этого пустой каталог ждал бы следующего обхода без
        // всякой причины.
        if now - owner.modified >= grace_secs
            && let Err(error) = store.remove_owner_if_empty(&owner.name)
        {
            tracing::warn!(%error, owner = %owner.name, "пустой каталог владельца не убирается");
        }
    }
    Ok(removed)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_granularity_is_coarser_than_a_click_and_finer_than_a_day() {
        // Проверяется поведение, а не само число: сравнение константы с константой
        // компилятор считает сам, и такая проверка краснеть не умеет. Смысл правила:
        // отметка обновляется реже, чем читают, и чаще, чем считается срок.
        let now = 1_000_000;
        assert!(!due(now, now - 30), "обновление на каждое чтение");
        assert!(!due(now, now - GRANULARITY + 1), "рано");
        assert!(due(now, now - GRANULARITY), "пора");
        assert!(
            due(now, now - 24 * 3600),
            "сутки без обновления — точно пора"
        );
    }

    #[test]
    fn a_young_directory_is_never_an_orphan() {
        // Предмет - Защита от гонки, а не число: запись идёт "сперва база, затем диск",
        // и каталог существует раньше, чем закрыта транзакция. Подмети его тогда - и
        // автор потеряет исходник в момент сохранения, не увидев ни отказа, ни следа.
        let now = 1_000_000;
        assert!(now - (now - 1) < ORPHAN_GRACE, "запись идёт прямо сейчас");
        assert!(now - (now - 60) < ORPHAN_GRACE, "минута — всё ещё запись");
        assert!(
            now - (now - ORPHAN_GRACE) >= ORPHAN_GRACE,
            "час без единой правки — мусор, а не запись"
        );
        // И порядок величин: выдержка сироты много меньше срока хранения, иначе мусор
        // лежал бы наравне с живыми проектами. Сравнение двух констант компилятор
        // считает сам, и такая проверка краснеть не умеет - потому свойство проверяется
        // Поведением: сутки старше выдержки, а квартал старше суток.
        assert!(now - (now - 24 * 3600) >= ORPHAN_GRACE, "сутки — уже мусор");
    }
}
